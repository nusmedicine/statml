const toPxOf = (P, span) => (x, y) => [P.x + P.s / 2 + (x / span) * (P.s / 2), P.y + P.s / 2 - (y / span) * (P.s / 2)];
/** an axis turns the short way: it has no sign, so a half-turn is no turn */
function blendAxis(a, b, t) {
  const c = lerpPt(a[0], a[1], 0.5), L = Math.hypot(b[1][0] - b[0][0], b[1][1] - b[0][1]) / 2;
  const a0 = Math.atan2(a[1][1] - a[0][1], a[1][0] - a[0][0]), a1 = Math.atan2(b[1][1] - b[0][1], b[1][0] - b[0][0]);
  let d = a1 - a0;
  while (d > Math.PI / 2) d -= Math.PI;
  while (d < -Math.PI / 2) d += Math.PI;
  const ang = a0 + d * t;
  return [[c[0] - L * Math.cos(ang), c[1] - L * Math.sin(ang)], [c[0] + L * Math.cos(ang), c[1] + L * Math.sin(ang)]];
}

/* ===================================================== the Design blocks */

/* Two blocks on the same 80 samples (`_lab/diablo-toy.mjs`, measured before
   the mock). In each, a shared factor h (sd 1.8) with no subtype in it, and
   the subtype z (±0.8 + noise) on an axis of the block's own. Every feature
   is scaled, as mixOmics scales it, so each block's direction of most
   variance is the shared axis at 45° or 135°. */
const ANG = { ha: 35, za: 115, hb: 145, zb: 60 };
const unitAt = (deg) => [Math.cos((deg * Math.PI) / 180), Math.sin((deg * Math.PI) / 180)];
const norm = (v) => { const n = Math.hypot(...v); return v.map((x) => x / n); };
const proj = (X, w) => X.map((r) => r.reduce((a, x, j) => a + x * w[j], 0));
const xtz = (X, z) => X[0].map((_, j) => X.reduce((a, r, i) => a + r[j] * z[i], 0));
/** each feature's covariance with a score vector: Xᵀs / n */
const covWith = (X, s) => xtz(X, s).map((v) => v / X.length);
const angleBetween = (a, b) => Math.acos(clamp(Math.abs(a[0] * b[0] + a[1] * b[1]), 0, 1)) * 180 / Math.PI;
function scaleCols(X) {
  const p = X[0].length, m = [], s = [];
  for (let j = 0; j < p; j++) {
    const c = X.map((r) => r[j]); m[j] = mean(c);
    s[j] = Math.sqrt(c.reduce((a, x) => a + (x - m[j]) ** 2, 0) / (c.length - 1));
  }
  return X.map((r) => r.map((x, j) => (x - m[j]) / s[j]));
}
/** the first right singular vector (mixOmics' svd.single start), by power iteration */
function pc1(X) {
  let v = norm(X[0].map((_, j) => 1 + 0.1 * j));
  for (let k = 0; k < 500; k++) v = norm(xtz(X, proj(X, v)));
  return v;
}

function makeToy(rng) {
  const ha = unitAt(ANG.ha), za = unitAt(ANG.za), hb = unitAt(ANG.hb), zb = unitAt(ANG.zb);
  const g = [], A0 = [], B0 = [];
  for (let i = 0; i < N_TOY; i++) {
    const grp = i % 2, h = 1.8 * rng.normal(), z = (grp ? 0.8 : -0.8) + 0.4 * rng.normal();
    g.push(grp);
    A0.push([0, 1].map((j) => h * ha[j] + z * za[j] + 0.25 * rng.normal()));
    B0.push([0, 1].map((j) => h * hb[j] + z * zb[j] + 0.25 * rng.normal()));
  }
  const A = scaleCols(A0), B = scaleCols(B0), Yd = scaleCols(g.map((k) => (k ? [0, 1] : [1, 0])));
  const blocks = [A, B, Yd];
  const pos2 = (t) => mean(t.filter((_, i) => g[i] === 1)) >= 0;

  /* sparse.mint.block_iteration, horst scheme, blocks updated in turn
     (mRNA, methylation, Y). One frame per omics update; Y's own update is
     run but not pressed: with two subtypes its score is the subtype however
     the weight is set. Signs: subtype 2 scores positive on mRNA and on Y,
     methylation's start agrees with mRNA's, so every pull points one way. */
  const loopAt = (c) => {
    const C = [[0, c, 1], [c, 0, 1], [1, 1, 0]];
    const W = blocks.map(pc1);
    if (!pos2(proj(A, W[0]))) W[0] = W[0].map((x) => -x);
    if (corr(proj(A, W[0]), proj(B, W[1])) < 0) W[1] = W[1].map((x) => -x);
    if (!pos2(proj(Yd, W[2]))) W[2] = W[2].map((x) => -x);
    const T = blocks.map((X, q) => proj(X, W[q]));
    const snap = (upd) => ({ wA: [...W[0]], wB: [...W[1]], t: [...T[0]], u: [...T[1]], y: [...T[2]], upd });
    const frames = [{}, snap(null)];
    for (let it = 0; it < 100; it++) {
      const old = W.map((w) => [...w]);
      for (let q = 0; q < 3; q++) {
        let upd = null;
        if (q < 2) upd = { block: q, other: covWith(blocks[q], T[1 - q]).map((v) => c * v), y: covWith(blocks[q], T[2]) };
        const z = T[0].map((_, i) => C[q].reduce((a, cc, l) => a + cc * T[l][i], 0));
        W[q] = norm(xtz(blocks[q], z));
        T[q] = proj(blocks[q], W[q]);
        if (q < 2) frames.push(snap(upd));
      }
      if (Math.max(...W.map((w, q) => w.reduce((a, x, j) => a + (x - old[q][j]) ** 2, 0))) < 1e-6) break;
    }
    /* the rounds after the arrows stopped moving are not pressed */
    let end = frames.length - 1;
    while (end > 3 && angleBetween(frames[end].wA, frames[end - 2].wA) < 0.5 && angleBetween(frames[end].wB, frames[end - 2].wB) < 0.5) end -= 2;
    const out = frames.slice(0, end + 1);
    out.forEach((f) => {
      if (!f.t) return;
      f.r = corr(f.t, f.u); f.cv = f.t.reduce((a, v, i) => a + v * f.u[i], 0) / N_TOY;
      f.etaA = etaOf(f.t, g, 2); f.etaB = etaOf(f.u, g, 2);
    });
    return out;
  };
  const loops = Object.fromEntries(WEIGHTS.map((c) => [String(c), loopAt(c)]));
  const all = Object.values(loops).flat().filter((f) => f.t);
  const span = 1.1 * Math.max(...A.flat().map(Math.abs), ...B.flat().map(Math.abs));
  const sspan = 1.08 * Math.max(...all.flatMap((f) => [...f.t, ...f.u]).map(Math.abs));
  return { g, A, B, loops, span, sspan, yVals: [Math.min(...all[0].y), Math.max(...all[0].y)] };
}

