/* ============================================================================
   Widget 83 · the model: block 1 of the language arc's trained tiny BERT,
   read, never trained. `weights.js` is GENERATED by
   `_lab/attention-weights.py` (torch, masked-token pretraining on the
   synthetic clinical notes, 3,000 steps, seed 0); `_lab/attention-verify.mjs`
   holds this forward to torch's own numbers on every sentence below.

   Block 1's input is x~ = the token's row + the position's row, which is
   where widget 74 stops. Everything here is that one step:

     q, k, v = x~ W_Q^T + b_Q, ...      (48 wide, split into 4 heads of 12)
     s_ij    = q_i . k_j / sqrt(d_k)    (or q_i . k_j, the Weights page's switch)
     a_ij    = softmax_j(s_ij)          (a masked key's score is -inf first)
     z_i     = sum_j a_ij v_j
   ========================================================================= */

import { WEIGHTS } from "./weights.js";

export const D = WEIGHTS.D, H = WEIGHTS.H, DK = WEIGHTS.dk, LMAX = WEIGHTS.Lmax;
const ID = Object.fromEntries(WEIGHTS.vocab.map((w, i) => [w, i]));
export const PAD = "[PAD]";

/* The widget's four sentences. The first is 08-1 cell 1's own; the second
   its masked-token example (cell 4); the last two put "discharge" in each of
   its two senses (cell 0's own example of a word read by its context). */
export const SENTENCES = {
  aspirin: "treated with aspirin for chest pain",
  masked: "treated with [MASK] for chest pain",
  wound: "patient presented with fever . yellow discharge from wound",
  home: "no nausea reported . planned discharge home today",
};

/* What each head of this block looks at, over 500 held-out notes: measured
   in `_lab/attention-measure.py` (W1, 2026-09-25), the share of a query's
   weight on the named keys. Printed under the Heads page's matrices. */
export const HABIT = [
  { what: "next token", share: 0.55 },
  { what: "own clause", share: 0.55 },
  { what: "previous token", share: 0.64 },
  { what: "own clause", share: 0.52 },
];

/** the tokens a sentence is read as: [CLS], its words, [SEP] */
export const tokensOf = (key) => ["[CLS]", ...SENTENCES[key].split(" "), "[SEP]"];

function linear(x, W, b) {           // torch's Linear: y = x W^T + b, W is [out][in]
  const y = new Float64Array(D);
  for (let o = 0; o < D; o++) {
    let s = b[o];
    for (let i = 0; i < D; i++) s += W[o * D + i] * x[i];
    y[o] = s;
  }
  return y;
}

/** x~ for each position: the token's row plus the position's row */
function embed(toks) {
  return toks.map((t, p) => {
    const r = ID[t === PAD ? "[PAD]" : t];
    if (r === undefined) throw new Error(`not in the vocabulary: ${t}`);
    const x = new Float64Array(D);
    for (let d = 0; d < D; d++) x[d] = WEIGHTS.tok[r * D + d] + WEIGHTS.pos[p * D + d];
    return x;
  });
}

function softmax(row, keep) {
  let m = -Infinity;
  for (let j = 0; j < row.length; j++) if (keep[j] && row[j] > m) m = row[j];
  const e = row.map((s, j) => (keep[j] ? Math.exp(s - m) : 0));
  const z = e.reduce((a, b) => a + b, 0);
  return e.map((v) => v / z);
}

/**
 * Block 1's attention on `toks`. Returns per head: alpha (scaled),
 * alphaRaw (no division), v, z, each row over every position of `toks`.
 * `mask` gives [PAD] keys no weight (attention_mask); without it they are
 * keys like any other.
 */
export function attend(toks, { mask = true } = {}) {
  const X = embed(toks), L = toks.length;
  const Q = X.map((x) => linear(x, WEIGHTS.Wq, WEIGHTS.bq));
  const K = X.map((x) => linear(x, WEIGHTS.Wk, WEIGHTS.bk));
  const V = X.map((x) => linear(x, WEIGHTS.Wv, WEIGHTS.bv));
  const keep = toks.map((t) => !(mask && t === PAD));
  const heads = [];
  for (let h = 0; h < H; h++) {
    const o = h * DK;
    const sl = (vec) => Array.from(vec.slice(o, o + DK));
    const q = Q.map(sl), k = K.map(sl), v = V.map(sl);
    const raw = q.map((qi) => k.map((kj) => qi.reduce((s, x, d) => s + x * kj[d], 0)));
    const alpha = raw.map((r) => softmax(r.map((s) => s / Math.sqrt(DK)), keep));
    const alphaRaw = raw.map((r) => softmax(r, keep));
    const z = alpha.map((a) => Array.from({ length: DK }, (_, d) => a.reduce((s, w, j) => s + w * v[j][d], 0)));
    heads.push({ alpha, alphaRaw, v, z });
  }
  return { tokens: toks, heads };
}

/** everything the four pages draw for one sentence */
export function stage(key) {
  const toks = tokensOf(key), L = toks.length;
  const padded = toks.concat(Array(LMAX - L).fill(PAD));
  return {
    key, tokens: toks, L,
    run: attend(toks),
    padded: { tokens: padded, masked: attend(padded, { mask: true }), open: attend(padded, { mask: false }) },
  };
}

/** the share of a row's weight on keys from `from` on (the [PAD] columns) */
export const tailShare = (row, from) => row.slice(from).reduce((a, b) => a + b, 0);
