/* ============================================================================
   Widget 109 · the models and the draws. `weights.js` is GENERATED by
   `_lab/generation-control-weights.py`; `_lab/generation-control-verify.mjs`
   holds every forward here to torch's own float64 numbers.

     causal  widget 84's decoder, read from 84's weights file, not retrained:
             next-token prediction on one-clause notes. The Sampling page.
     cond    the same size, trained on notes of two kinds with a condition token
             after [BOS] ([TREAT] or [NEG]), left out of 20% of training notes;
             the loss is on the note's tokens only. The Conditioning page.

   The forward is 84's (`transformer/model.js`), decoder only: 84's is written
   against its own five-model file and loading it would bring 1 MB of models
   this widget never runs. The verify holds this copy to torch directly, so the
   two cannot drift apart without one of them failing against torch.

   A DRAW (slot 109's design, 2026-10-20): every token is drawn by one uniform
   u in [0, 1). The tokens are laid end to end in the MODEL's order, most
   probable first, each taking an interval as long as the rule gives it, and u
   picks the interval it falls in. The same u under another rule, or another
   prefix, is the same draw: switching the rule changes what u picks, never u.
   ========================================================================= */

import { MODELS, VOCABS, GRAMMAR } from "./weights.js";

const D = 48, H = 4, DK = 12;
export const BOS = 1, EOS = 2;
/** tokens a note may have before the page stops it; no note from [BOS] reached it at T ≤ 1.6 in 1,000 (`generation-control-measure.json`) */
export const MAX_TOKENS = 11;
export const VOCAB = { causal: VOCABS.causal, cond: VOCABS.cond };
export const ID = Object.fromEntries(VOCABS.cond.map((w, i) => [w, i]));
const IN_GRAMMAR = new Set(GRAMMAR);
/** a note (its words joined by spaces) the training grammar can produce */
export const inGrammar = (text) => IN_GRAMMAR.has(text);

/* ------------------------------------------------------------ the weights */

function decode(b64) {
  let bytes;
  if (typeof Buffer !== "undefined") bytes = new Uint8Array(Buffer.from(b64, "base64"));
  else { const s = atob(b64); bytes = new Uint8Array(s.length); for (let i = 0; i < s.length; i++) bytes[i] = s.charCodeAt(i); }
  return new Float32Array(bytes.buffer, bytes.byteOffset, bytes.byteLength / 4);
}
function unpack({ spec, b64 }) {
  const all = decode(b64), out = {};
  let o = 0;
  for (const [name, shape] of spec) {
    const n = shape.reduce((a, b) => a * b, 1);
    out[name] = { v: all.subarray(o, o + n), shape };
    o += n;
  }
  if (o !== all.length) throw new Error(`weights: ${o} of ${all.length} numbers read`);
  return out;
}
const W = { causal: unpack(MODELS.causal), cond: unpack(MODELS.cond) };
const LPOS = W.causal.pos.shape[0];

/* ------------------------------------------------------------ the forward */

function linear(x, Wt, bt) {
  const [nOut, nIn] = Wt.shape, y = new Array(nOut);
  for (let o = 0; o < nOut; o++) {
    let s = bt.v[o];
    for (let i = 0; i < nIn; i++) s += Wt.v[o * nIn + i] * x[i];
    y[o] = s;
  }
  return y;
}
function layerNorm(x, g, b) {
  const n = x.length, m = x.reduce((a, v) => a + v, 0) / n;
  const va = x.reduce((a, v) => a + (v - m) * (v - m), 0) / n, s = Math.sqrt(va + 1e-5);
  return x.map((v, i) => ((v - m) / s) * g.v[i] + b.v[i]);
}
const add = (a, b) => a.map((v, i) => v + b[i]);
function softmax(row) {
  let m = -Infinity;
  for (const s of row) if (s > m) m = s;
  const e = row.map((s) => (s === -Infinity ? 0 : Math.exp(s - m)));
  const z = e.reduce((a, b) => a + b, 0);
  return e.map((v) => v / z);
}
/** masked self-attention: a key after its query scores −∞ */
function attention(T, pre, X) {
  const Q = X.map((x) => linear(x, T[`${pre}.q`], T[`${pre}.qb`]));
  const K = X.map((x) => linear(x, T[`${pre}.k`], T[`${pre}.kb`]));
  const V = X.map((x) => linear(x, T[`${pre}.v`], T[`${pre}.vb`]));
  const Z = X.map(() => new Array(D).fill(0));
  for (let h = 0; h < H; h++) {
    const o = h * DK;
    Q.forEach((q, i) => {
      const a = softmax(K.map((k, j) => {
        if (j > i) return -Infinity;
        let s = 0;
        for (let d = 0; d < DK; d++) s += q[o + d] * k[o + d];
        return s / Math.sqrt(DK);
      }));
      a.forEach((w, j) => { for (let d = 0; d < DK; d++) Z[i][o + d] += w * V[j][o + d]; });
    });
  }
  return Z.map((z) => linear(z, T[`${pre}.o`], T[`${pre}.ob`]));
}
const ffn = (T, pre, x) => linear(linear(x, T[`${pre}.ff1`], T[`${pre}.ff1b`]).map((v) => Math.max(0, v)), T[`${pre}.ff2`], T[`${pre}.ff2b`]);
/** a post-LN block: h = LayerNorm(x + Attention(x)); y = LayerNorm(h + FFN(h)) */
function block(T, pre, X) {
  const a = attention(T, `${pre}.att`, X);
  const mid = X.map((x, i) => layerNorm(add(x, a[i]), T[`${pre}.n1`], T[`${pre}.n1b`]));
  return mid.map((h) => layerNorm(add(h, ffn(T, pre, h)), T[`${pre}.n2`], T[`${pre}.n2b`]));
}

const memo = { causal: new Map(), cond: new Map() };
/** the model's probability of every token in its vocabulary, after the context `ids` (ids[0] = [BOS]) */
export function nextProbs(which, ids) {
  const key = ids.join(","), hit = memo[which].get(key);
  if (hit) return hit;
  if (ids.length > LPOS) throw new Error(`a context of ${ids.length} tokens; the model keeps ${LPOS} positions`);
  const T = W[which];
  let h = ids.map((r, p) => Array.from({ length: D }, (_, d) => T.tok.v[r * D + d] + T.pos.v[p * D + d]));
  for (const b of ["b0", "b1"]) h = block(T, b, h);
  const p = softmax(linear(h[h.length - 1], T.mlm, T.mlmb));
  memo[which].set(key, p);
  return p;
}

/* ------------------------------------------------------------ the rules */

/** the token ids in the model's order, most probable first (ties by id, as numpy's stable argsort) */
export const orderOf = (p) => p.map((v, i) => i).sort((a, b) => p[b] - p[a] || a - b);
/** the distribution the token is drawn from: greedy puts 1 on the most probable token; temperature
    divides the log probabilities by T and renormalises; top-k keeps the k most probable and renormalises */
export function ruleDist(p, rule, { T = 1, k = 3 } = {}) {
  if (rule === "greedy") { const q = p.map(() => 0); q[orderOf(p)[0]] = 1; return q; }
  if (rule === "temperature") {
    const z = p.map((v) => Math.log(Math.max(v, 1e-300)) / T), m = Math.max(...z), e = z.map((v) => Math.exp(v - m)), s = e.reduce((a, b) => a + b, 0);
    return e.map((v) => v / s);
  }
  const keep = orderOf(p).slice(0, k), s = keep.reduce((a, i) => a + p[i], 0), q = p.map(() => 0);
  for (const i of keep) q[i] = p[i] / s;
  return q;
}
/** the token whose interval holds u, the intervals in the model's order */
export function drawOf(p, q, u) {
  const order = orderOf(p);
  let c = 0, last = order[0];
  for (const i of order) {
    if (q[i] <= 0) continue;
    c += q[i]; last = i;
    if (u < c) return i;
  }
  return last;
}
/** entropy in nats: 0 when one token has all the probability */
export const entropy = (p) => -p.reduce((s, v) => (v > 0 ? s + v * Math.log(v) : s), 0);

/** one note: from the context `start`, a token a draw from `us`, until [EOS] or MAX_TOKENS.
    Each step keeps what the page draws: the context, the model's p, the rule's q, u and the token. */
export function generate(which, start, us, rule = "temperature", opts = {}) {
  const ids = start.slice(), steps = [];
  for (let j = 0; j < MAX_TOKENS; j++) {
    const p = nextProbs(which, ids), q = ruleDist(p, rule, opts), tok = drawOf(p, q, us[j]);
    steps.push({ ctx: ids.slice(), p, q, u: us[j], tok });
    if (tok === EOS) break;
    ids.push(tok);
  }
  const words = ids.slice(start.length).map((i) => VOCAB[which][i]);
  return { steps, words, text: words.join(" "), ended: steps[steps.length - 1].tok === EOS };
}
