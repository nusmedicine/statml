/** one bond as two lanes, one per direction; `sep` 1 is apart, 0 merged into one line */
function drawLanes(ctx, colors, p, q, u, v, sep = 1) {
  const dx = q[0] - p[0], dy = q[1] - p[1], L = Math.hypot(dx, dy) || 1, nx = (-dy / L) * LANE * sep, ny = (dx / L) * LANE * sep;
  /* the bond itself, under its lanes, so a direction masked to 0 still shows where it runs */
  line(ctx, p[0], p[1], q[0], q[1], colors.ink3, 1);
  line(ctx, p[0] + nx, p[1] + ny, q[0] + nx, q[1] + ny, ramp(colors, u), 3.4);
  line(ctx, p[0] - nx, p[1] - ny, q[0] - nx, q[1] - ny, ramp(colors, v), 3.4);
}
/** one bond as one line, its width and colour a score in 0–1 */
function drawScoredBond(ctx, colors, p, q, v) {
  line(ctx, p[0], p[1], q[0], q[1], colors.ink3, 1);
  line(ctx, p[0], p[1], q[0], q[1], ramp(colors, v), 2 + 4.5 * v);
}
function nearestAtom(P, pt) {
  let best = -1, bd = NODE_R + 3;
  P.forEach((p, i) => { const d = Math.hypot(p[0] - pt.x, p[1] - pt.y); if (d < bd) { bd = d; best = i; } });
  return best;
}
function nearestBond(P, pt) {
  let best = -1, bd = 6;
  MOL.bonds.forEach(([i, j], b) => {
    const [ax, ay] = P[i], [bx, by] = P[j], vx = bx - ax, vy = by - ay, L2 = vx * vx + vy * vy;
    const t = Math.max(0, Math.min(1, ((pt.x - ax) * vx + (pt.y - ay) * vy) / L2));
    const d = Math.hypot(ax + t * vx - pt.x, ay + t * vy - pt.y);
    if (d < bd) { bd = d; best = b; }
  });
  return best;
}

