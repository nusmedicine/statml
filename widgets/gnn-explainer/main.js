defineWidget({
  slug: "gnn-explainer",
  status: "draft",
  title: "Deep Learning - Graphs: Explainability",
  subtitle: S.subtitle,
  credit: "Molecule data: Stokes et al., Cell 2020, via FinGAT",
  layout: "side",
  height: (params) => (params.page === "mask" ? H_MASK : params.page === "scores" ? H_SCORES : H_RUNS),
  pointer: true,

  params: {
    page: { role: "page", type: "segmented", label: S.pageLabel, options: PAGES, default: "mask", display: true },
    /* hidden in All runs, which combines every start (his round 1: a control that did nothing) */
    start: { type: "int", label: S.startLabel, detail: S.startDetail, min: 1, max: NR, default: 1, display: true,
      when: { any: [{ param: "page", oneOf: ["mask", "scores"] }, { param: "show", equals: "one" }] } },
    show: { type: "segmented", label: S.showLabel, detail: S.showDetail, options: SHOW_OPTS, default: "one", display: true, when: ON("runs") },
    /* authoring escape hatch, first render only: presses already made on the stage the link opens */
    shown: { type: "int", min: 0, max: 3, default: 0, hidden: true },
  },

  /* none: each page keys its marks on the canvas (a ramp key, captions), and a legend reads params alone */
  legend: [],

  compute: () => ({}),

  animation: {
    stepLabel: S.stepLabel,
    stepTitle: S.stepTitle,
    /* each press is read, once: Step alone (play-only-for-motion-or-repetition) */
    runLabel: null,

    init: ({ params, fromScratch }) => {
      const stage = stageOf(params);
      const anim = { stage, n: {}, t: 1, dur: 1000, halt: false };
      anim.n[stage] = fromScratch ? 0 : Math.max(0, Math.min(stepsOf(stage), Number(params.shown) || 0));
      anim.beat = anim.n[stage];
      anim.done = anim.n[stage] >= stepsOf(stage);
      return anim;
    },

    advance: (anim, { dt }) => {
      /* a press a stage switch interrupted ends here, before the new stage's (mid-press-page-switch) */
      if (anim.halt) { anim.halt = false; return false; }
      const stage = anim.stage;
      if (anim.t < 1) anim.t = Math.min(1, anim.t + dt / anim.dur);
      else if ((anim.n[stage] ?? 0) < stepsOf(stage)) {
        anim.n[stage] = (anim.n[stage] ?? 0) + 1;
        anim.dur = durOf(stage, anim.n[stage]);
        anim.t = 0;
      }
      anim.beat = anim.n[stage] ?? 0;
      anim.done = anim.beat >= stepsOf(stage) && anim.t >= 1;
      return anim.t < 1;
    },

    rebuild: (anim, { params }) => {
      const stage = stageOf(params);
      /* only a change of stage ends a press in flight; a new random start keeps it */
      if (stage !== anim.stage && anim.t < 1) { anim.t = 1; anim.halt = true; }
      anim.stage = stage;
      anim.beat = anim.n[stage] ?? 0;
      anim.done = anim.beat >= stepsOf(stage) && anim.t >= 1;
    },
  },

  draw({ ctx, colors, w, params, anim, pointer }) {
    if (params.page === "mask") drawMask(ctx, colors, w, params, anim, pointer);
    else if (params.page === "scores") drawScores(ctx, colors, w, params, anim, pointer);
    else drawRuns(ctx, colors, w, params, anim, pointer);
  },

  readout({ params, anim }) {
    const stage = stageOf(params), beat = shownStep(anim, stage), run = runOf(params), R = RUNS[run];
    if (params.page === "mask") {
      const f = maskFrame(anim, stage), E = edgeAt(R, f), on = beat >= 1 || inFlight(anim, stage) != null;
      const above = MOL.bonds.filter((_, b) => Math.max(E[2 * b], E[2 * b + 1]) > 0.5).length;
      return [
        { label: S.tileFull, value: f2(k(INFO.pFull)), note: S.tileFullNote },
        { label: S.tileMasked, value: on ? f2(seriesAt(R.p, f)) : S.tileWait, note: S.tileMaskedNote },
        { label: S.tileAbove, value: on ? String(above) : S.tileWait, note: on ? S.tileAboveNote(epochAt(f)) : "" },
      ];
    }
    if (params.page === "scores") {
      const sc = scoresOf(run), ranks = SALT.filter((i) => MOL.atoms[i][0] === "O").map(sc.rank).sort((a, b) => a - b);
      return [
        { label: S.tileBonds, value: beat >= 1 ? String(NB) : S.tileWait, note: S.tileBondsNote },
        { label: S.tileAtoms, value: beat >= 2 ? String(NA) : S.tileWait, note: S.tileAtomsNote },
        { label: S.tileWater, value: beat >= 2 ? ranks.join(" · ") : S.tileWait, note: S.tileWaterNote },
      ];
    }
    if (params.show === "one") {
      return [
        { label: S.tileKept, value: String(R.kept.length), note: S.tileKeptNote },
        { label: S.tileOnly, value: beat >= 1 ? f2(k(R.pKept)) : S.tileWait, note: S.tileOnlyNote },
        { label: S.tileRand, value: beat >= 1 ? f2(k(median(R.pRand))) : S.tileWait, note: S.tileRandNote },
      ];
    }
    return [
      { label: S.tileEvery, value: beat >= 1 ? String(ALWAYS.length) : S.tileWait, note: S.tileEveryNote },
      { label: S.tileSome, value: beat >= 1 ? String(KEEP_COUNT.filter((c) => c > 0).length) : S.tileWait, note: S.tileSomeNote },
      { label: S.tileShare, value: beat >= 1 ? `${Math.round(100 * JACCARD)}%` : S.tileWait, note: S.tileShareNote },
    ];
  },

  summary({ params, anim }) {
    const stage = stageOf(params), beat = shownStep(anim, stage), R = RUNS[runOf(params)];
    if (params.page === "mask") { const f = maskFrame(anim, stage); return S.sumMask(params.start, beat, epochAt(f), f2(seriesAt(R.p, f))); }
    if (params.page === "scores") return S.sumScores(params.start, beat);
    return S.sumRuns(params.start, params.show === "all", beat);
  },
});
