"""Widget 107 diffusion: writes widgets/diffusion/data.js.

    python -I diffusion-export.py

Reads _lab/diffusion-mock-data.json (from `diffusion-mockdata.py <data> cuda`,
which needs the models of `diffusion-measure.py train uncond|cond`) and
repacks every image at 4 bits a pixel, his call 12 (2026-10-20): 16 greys,
two pixels a byte, high nibble first; the page multiplies by 17 to get back
0-255. The forward page's clean digits stay at 8 bits, since the page mixes
them with its own epsilon. Stored images are the notebook's display values,
clamp(x, -1, 1) * 0.5 + 0.5.
"""
import base64, json, os
import numpy as np

HERE = os.path.dirname(os.path.abspath(__file__))
d = json.load(open(os.path.join(HERE, "diffusion-mock-data.json")))
# review round 1 (his calls 2026-10-20): the conditional model's training, from diffusion-mock2data.py
d2 = json.load(open(os.path.join(HERE, "diffusion-mock2-data.json")))

def pack(b64s):
    """8-bit display bytes (any number of 28x28 images) -> 4-bit base64"""
    u = np.frombuffer(base64.b64decode(b64s), np.uint8)
    q = np.clip(np.round(u / 17.0), 0, 15).astype(np.uint8)
    assert len(q) % 2 == 0
    return base64.b64encode(((q[0::2] << 4) | q[1::2]).astype(np.uint8).tobytes()).decode()

tr = d["training"]
assert tr["tag_batch"] == [0, 5, 20, 50, 100, 200, 235, 470, 705]
out = {
    "FORWARD": {"labels": d["forward"]["labels"], "x0": d["forward"]["x0"]},
    "TRAINING": {
        "t": tr["t"], "label": tr["label"], "mse": tr["mse"], "batch": tr["tag_batch"],
        "loss": [float(f"{v:.3g}") for v in tr["batch_loss"]],
        "x0": pack(tr["x0"]), "eps": pack(tr["eps"]), "xt": pack(tr["xt"]),
        "epsHat": [pack(s) for s in tr["eps_hat"]], "samples": [pack(s) for s in tr["samples"]],
    },
    "GENERATION": {
        "t": d["generation"]["t"],
        "xt": [pack(s) for s in d["generation"]["xt"]],
        "epsHat": [pack(s) for s in d["generation"]["eps_hat"]],
        "x0Hat": [pack(s) for s in d["generation"]["x0_hat"]],
    },
    # one string a frame holding the 40 samples in row order (row r, label c at r * 10 + c)
    "CONDITIONAL": {
        "t": d["conditional"]["t"],
        "xt": [pack(base64.b64encode(b"".join(base64.b64decode(d["conditional"]["xt"][k][f]) for k in range(40))).decode())
               for f in range(len(d["conditional"]["t"]))],
        "x0Hat": [pack(base64.b64encode(b"".join(base64.b64decode(d["conditional"]["x0_hat"][k][f]) for k in range(40))).decode())
                  for f in range(len(d["conditional"]["t"]))],
        # eps-hat for the first row only (labels 0-9), the sample the subtraction row draws
        "epsHat": [pack(base64.b64encode(b"".join(base64.b64decode(d["conditional"]["eps_hat"][k][f]) for k in range(10))).decode())
                   for f in range(len(d["conditional"]["t"]))],
    },
    "COND_TRAINING": {
        "batch": d2["cond_training"]["tag_batch"], "mse": d2["cond_training"]["mse"],
        "loss": [float(f"{v:.3g}") for v in d2["cond_training"]["batch_loss"]],
        "epsHat": [pack(s) for s in d2["cond_training"]["eps_hat"]], "samples": [pack(s) for s in d2["cond_training"]["samples"]],
    },
}
assert len(out["GENERATION"]["t"]) == 51 and len(out["CONDITIONAL"]["t"]) == 26
assert out["COND_TRAINING"]["batch"] == [0, 5, 20, 50, 100, 200, 235, 470, 705, 940, 1175]
dst = os.path.join(HERE, "..", "diffusion", "data.js")
with open(dst, "w", encoding="utf-8", newline="\n") as f:
    f.write("/* Widget 107 `diffusion`: generated by widgets/_lab/diffusion-export.py. Do not edit by hand. */\n")
    for k, v in out.items():
        f.write(f"export const {k} = {json.dumps(v, separators=(',', ':'))};\n")
print("wrote", dst, os.path.getsize(dst), "bytes")
