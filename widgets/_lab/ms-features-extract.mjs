/* ms-features — the lesson's numbers for slot 93, written to stdout as a module.
 *   node widgets/_lab/ms-features-extract.mjs > widgets/ms-features/data.js
 * Reads the MAF and the sample file in the 09 lesson folder (02-2's download).
 * The mock's copy, _lab/ms-features-data.js, is the same file. */
import fs from "fs";
import { fileURLToPath } from "url";
const dir = fileURLToPath(new URL("../../../jupyterbook/phm5003/notebook/09 - Proteomics & Metabolomics Analysis/", import.meta.url));
const rows = fs.readFileSync(dir + "m_MTBLS6038_LC-MS_negative_reverse-phase_metabolite_profiling_v2_maf.tsv", "utf8").trim().split(/\r?\n/).map(l => l.split("\t"));
const head = rows[0];
const sIdx = head.map((h, i) => [h, i]).filter(([h]) => /^P\d+/.test(h));
const sfile = fs.readFileSync(dir + "s_MTBLS6038.txt", "utf8").trim().split(/\r?\n/).map(l => l.split("\t"));
const sh = sfile[0], sn = sh.indexOf("Sample Name"), co = sh.indexOf("Factor Value[Cohort]");
const cohort = Object.fromEntries(sfile.slice(1).map(r => [r[sn].replace(/"/g, ""), r[co].replace(/"/g, "")]));
const M = { C: 12, H: 1.00782503207, N: 14.0030740048, O: 15.99491461956 };
const mono = f => [...f.matchAll(/([A-Z][a-z]?)(\d*)/g)].reduce((s, [, e, n]) => s + M[e] * (n ? +n : 1), 0);
const mets = rows.slice(1).map(r => {
  const v = sIdx.map(([, i]) => +r[i]);
  const nz = v.filter(x => x > 0).sort((a, b) => a - b);
  return { name: r[4], formula: r[1], mz: +r[5], rt: +r[9], exact: +(mono(r[1]) - 1.00727646688).toFixed(4),
    zeros: v.length - nz.length, minNz: nz[0] ?? 0, medNz: nz.length ? nz[nz.length >> 1] : 0, v };
});
const glu = mets.find(m => m.name === "Glutaric acid"), eth = mets.find(m => m.name === "Ethylmalonic acid");
const both = sIdx.map(([h], j) => j).filter(j => glu.v[j] > 0);
console.error("glutaric detected in", both.length, "samples; first", both.slice(0, 10).map(j => sIdx[j][0] + ":" + cohort[sIdx[j][0]] + ":" + glu.v[j] + "/" + eth.v[j]));
console.error("glutaric nonzero range", glu.minNz, glu.medNz, Math.max(...glu.v), "ethylmalonic", eth.minNz, eth.medNz, Math.max(...eth.v));
// three with glutaric detected, three without; in each, cancer and hyperplasia both present
const isC = j => cohort[sIdx[j][0]] === "Prostate cancer", isH = j => cohort[sIdx[j][0]] === "Prostatic hyperplasia";
const none = sIdx.map((_, j) => j).filter(j => glu.v[j] === 0);
const pick = [...both.filter(isC).slice(0, 2), ...both.filter(isH).slice(0, 1), ...none.filter(isC).slice(0, 1), ...none.filter(isH).slice(0, 2)].sort((a, b) => a - b);
const out = {
  source: "MTBLS6038 MAF (negative mode), the 02-2 download; exact [M-H]- from the formula",
  samples: pick.map(j => ({ id: sIdx[j][0], cohort: cohort[sIdx[j][0]] })),
  metabolites: mets.map(m => ({ name: m.name, formula: m.formula, mz: m.mz, rt: m.rt, exact: m.exact, zeros: m.zeros, minNz: m.minNz, medNz: m.medNz, at: pick.map(j => m.v[j]) })),
  n: sIdx.length,
};
process.stdout.write("/* GENERATED by _lab/ms-features-extract.mjs from MTBLS6038 (the 02-2 download): regenerate, do not edit. */\nexport default " + JSON.stringify(out, null, 1) + ";\n");
