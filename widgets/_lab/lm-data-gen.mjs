// lm-data-gen.mjs — generate _lab/lm-data.js from the Framingham CSV.
//
//   node widgets/_lab/lm-data-gen.mjs <path-to-framingham.csv>
//
// Run ONCE per CSV download; the output module is what gets committed and what
// every lm-* planning script imports. The table is generated and spliced
// programmatically with its totals asserted here, never typed, because widget
// 15's age aggregate was typed into a heredoc and drifted from age 53 up —
// seventeen wrong rows that looked exactly like correct ones.
//
// The filter is VERBATIM from PHM5003 05-01 cell 2 (and repeated in 05-02,
// 05-03, 05-04): filter(BPMeds==0) then drop_na over ALL 16 columns — so a row
// with a missing glucose is dropped even though no lm-* widget uses glucose.
// That is the notebook's own frame and it is what makes n = 3547.
import { readFileSync, writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";
import { dirname, join } from "node:path";

const csvPath = process.argv[2];
if (!csvPath) { console.error("usage: node lm-data-gen.mjs <framingham.csv>"); process.exit(1); }

// The GitHub raw file has CR-only line endings; split on every convention.
const rows = readFileSync(csvPath, "utf8").split(/\r\n|\r|\n/).filter((l) => l.length);
const header = rows[0].split(",");
const need = ["male", "age", "diabetes", "totChol", "sysBP", "BMI", "BPMeds"];
for (const c of need) if (!header.includes(c)) throw new Error(`column ${c} missing`);

const parsed = rows.slice(1).map((line) => {
  const cells = line.split(",");
  if (cells.length !== header.length) throw new Error(`row with ${cells.length} cells`);
  const rec = {};
  header.forEach((h, i) => { rec[h] = cells[i] === "NA" ? null : Number(cells[i]); });
  return rec;
});
if (parsed.length !== 4240) throw new Error(`expected 4240 raw rows, got ${parsed.length}`);

const kept = parsed.filter((r) => r.BPMeds === 0 && header.every((h) => r[h] !== null));

// n = 3547 is the number every 05-0x reference coefficient stands on (df 3545).
if (kept.length !== 3547) throw new Error(`expected n=3547 after filter, got ${kept.length}`);

// Spot-check the head against 05-01 cell 2's printed output.
const head = [[26.97, 106], [28.73, 121], [25.34, 127.5], [28.58, 150], [23.1, 130], [30.3, 180]];
head.forEach(([bmi, bp], i) => {
  if (kept[i].BMI !== bmi || kept[i].sysBP !== bp)
    throw new Error(`head row ${i}: got BMI=${kept[i].BMI} sysBP=${kept[i].sysBP}`);
});

const col = (k) => kept.map((r) => r[k]);
const sum = (a) => a.reduce((s, v) => s + v, 0);
const lines = [
  "// GENERATED by lm-data-gen.mjs from the notebooks' own framingham.csv —",
  "// DO NOT EDIT BY HAND. Frame: filter(BPMeds==0) + drop_na over all 16",
  "// columns, exactly PHM5003 05-01 cell 2. n = 3547, df = 3545.",
  "// sex: 1 = male, 0 = female (the CSV's `male` column, renamed as 05-01 does).",
  `export const N = ${kept.length};`,
  `export const BMI = [${col("BMI").join(",")}];`,
  `export const SYSBP = [${col("sysBP").join(",")}];`,
  `export const AGE = [${col("age").join(",")}];`,
  `export const SEX = [${col("male").join(",")}];`,
  `export const TOTCHOL = [${col("totChol").join(",")}];`,
  `export const DIABETES = [${col("diabetes").join(",")}];`,
  "",
];
const out = join(dirname(fileURLToPath(import.meta.url)), "..", "lm-least-squares", "data.js");
writeFileSync(out, lines.join("\n"));

// Totals, printed so the commit records them and a re-run can be diffed.
console.log(`wrote ${out} (${lines.join("\n").length} bytes)`);
for (const k of ["BMI", "sysBP", "age", "male", "totChol", "diabetes"])
  console.log(`  sum(${k}) = ${sum(col(k))}`);
