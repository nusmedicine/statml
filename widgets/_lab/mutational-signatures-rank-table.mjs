/* Writes widgets/mutational-signatures/rank-table.js: the Rank page's ten
 * starts at ranks 2–8, seeds 1–20, the hypermutated tumor in and left out,
 * run by the widget's own engine (model.js § the Rank page).
 *
 *   node widgets/_lab/mutational-signatures-rank-table.mjs [workers]
 *
 * About 7 s a rank on one core, so 40 cohorts × 7 ranks spread over workers.
 * Regenerate whenever the cohort or the engine changes; the verify rebuilds
 * one rank live and fails if the table disagrees.
 */
import { Worker, isMainThread, parentPort, workerData } from "node:worker_threads";
import { writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";
import { cpus } from "node:os";

const here = fileURLToPath(import.meta.url);

if (isMainThread) {
  const M = await import("../mutational-signatures/model.js");
  const jobs = [];
  for (let seed = 1; seed <= M.SEED_MAX; seed += 1) for (const hyper of ["in", "out"]) for (const r of M.RANKS_TRIED) jobs.push({ seed, hyper, r });
  /* the slow ranks first, so the pool ends together */
  jobs.sort((a, b) => b.r - a.r);
  const nWorkers = Math.min(Number(process.argv[2]) || Math.max(1, cpus().length - 2), jobs.length);
  const table = {};
  let next = 0, doneCount = 0;
  const t0 = Date.now();
  await new Promise((resolve) => {
    let live = nWorkers;
    for (let w = 0; w < nWorkers; w += 1) {
      const worker = new Worker(here, { workerData: null });
      const feed = () => { if (next < jobs.length) worker.postMessage(jobs[next++]); else { worker.terminate(); if (--live === 0) resolve(); } };
      worker.on("message", (res) => {
        ((table[res.seed] ??= {})[res.hyper] ??= {})[res.r] = { kls: res.kls, labels: res.labels };
        doneCount += 1;
        if (doneCount % 20 === 0) process.stderr.write(`${doneCount}/${jobs.length} ${((Date.now() - t0) / 1000).toFixed(0)} s\n`);
        feed();
      });
      worker.on("error", (e) => { console.error(e); process.exit(1); });
      feed();
    }
  });
  const seeds = {};
  for (let seed = 1; seed <= M.SEED_MAX; seed += 1) {
    seeds[seed] = {};
    for (const hyper of ["in", "out"]) {
      seeds[seed][hyper] = {};
      for (const r of M.RANKS_TRIED) seeds[seed][hyper][r] = table[seed][hyper][r];
    }
  }
  const body = JSON.stringify({ nrun: M.NRUN, ranks: M.RANKS_TRIED, seeds });
  const out = `/* GENERATED by widgets/_lab/mutational-signatures-rank-table.mjs — do not edit.
   The Rank page's ten starts (model.js § the Rank page) at ranks ${M.RANKS_TRIED[0]}–${M.RANKS_TRIED.at(-1)}, seeds 1–${M.SEED_MAX},
   the hypermutated tumor in and left out: each start's label for every tumor
   (its largest exposure, one digit a tumor) and the KL divergence it ends at.
   Regenerate whenever the cohort or the engine changes. */
export const RANK_TABLE = ${body};
`;
  writeFileSync(new URL("../mutational-signatures/rank-table.js", import.meta.url), out);
  console.log(`wrote rank-table.js: ${(out.length / 1024).toFixed(0)} KB, ${jobs.length} ranks, ${((Date.now() - t0) / 1000).toFixed(0)} s on ${nWorkers} workers`);
} else {
  const M = await import("../mutational-signatures/model.js");
  parentPort.on("message", ({ seed, hyper, r }) => {
    const e = M.estimateRank(M.cohortMatrix(seed, hyper), r, seed);
    parentPort.postMessage({ seed, hyper, r, kls: e.kls.map((x) => +x.toFixed(2)), labels: e.labels.map((l) => Array.from(l).join("")) });
  });
}
