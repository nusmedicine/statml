const clamp = (v, lo, hi) => Math.max(lo, Math.min(hi, v));
const lerp = (a, b, e) => a + (b - a) * e;
const ease = (x) => (x < 0.5 ? 4 * x * x * x : 1 - (-2 * x + 2) ** 3 / 2);
/* a fixed jitter per index, so the strips draw the same picture every frame */
const jit = (i) => { const s = Math.sin(i * 12.9898 + 78.233) * 43758.5453; return s - Math.floor(s) - 0.5; };
function txt(ctx, colors, s, x, y, { size = colors.fsSm, fill = colors.ink2, align = "left", baseline = "alphabetic", weight = "" } = {}) {
  ctx.save(); ctx.font = `${weight ? weight + " " : ""}${size} ${colors.font}`; ctx.fillStyle = fill;
  ctx.textAlign = align; ctx.textBaseline = baseline; ctx.fillText(s, x, y); ctx.restore();
}
function line(ctx, x1, y1, x2, y2, col, w = 1, dash = null) {
  ctx.save(); ctx.strokeStyle = col; ctx.lineWidth = w; if (dash) ctx.setLineDash(dash);
  ctx.beginPath(); ctx.moveTo(x1, y1); ctx.lineTo(x2, y2); ctx.stroke(); ctx.restore();
}
function poly(ctx, P, col, w = 2, dash = null) {
  ctx.save(); ctx.strokeStyle = col; ctx.lineWidth = w; if (dash) ctx.setLineDash(dash);
  ctx.beginPath(); P.forEach(([x, y], i) => (i ? ctx.lineTo(x, y) : ctx.moveTo(x, y))); ctx.stroke(); ctx.restore();
}
function dot(ctx, x, y, r, col, alpha = 1) { ctx.save(); ctx.globalAlpha = alpha; ctx.fillStyle = col; ctx.beginPath(); ctx.arc(x, y, r, 0, Math.PI * 2); ctx.fill(); ctx.restore(); }
function ring(ctx, x, y, r, col, w = 1) { ctx.save(); ctx.strokeStyle = col; ctx.lineWidth = w; ctx.beginPath(); ctx.arc(x, y, r, 0, Math.PI * 2); ctx.stroke(); ctx.restore(); }
function frame(ctx, x, y, w, h, col, lw = 1, dash = null) {
  ctx.save(); ctx.strokeStyle = col; ctx.lineWidth = lw; if (dash) ctx.setLineDash(dash); ctx.strokeRect(x + 0.5, y + 0.5, w - 1, h - 1); ctx.restore();
}
function wrapText(ctx, colors, str, x, y, maxW, lh, opts = {}) {
  ctx.save(); ctx.font = `${opts.weight ? opts.weight + " " : ""}${opts.size ?? colors.fsSm} ${colors.font}`;
  const lines = []; let cur = "";
  for (const word of str.split(" ")) {
    const tryLine = cur ? `${cur} ${word}` : word;
    if (ctx.measureText(tryLine).width > maxW && cur) { lines.push(cur); cur = word; } else cur = tryLine;
  }
  if (cur) lines.push(cur);
  ctx.restore();
  lines.forEach((l, i) => txt(ctx, colors, l, x, y + i * lh, { fill: colors.ink2, ...opts }));
  return lines.length;
}
/** an axes box: scales from data to pixels, the frame, ticks and titles */
function axes(ctx, colors, R, { xr, yr, xt = null, yt = null, xticks = [], yticks = [], xlab = String, ylab = String }) {
  const X = (v) => R.x + ((v - xr[0]) / (xr[1] - xr[0])) * R.w, Y = (v) => R.y + R.h - ((v - yr[0]) / (yr[1] - yr[0])) * R.h;
  frame(ctx, R.x, R.y, R.w, R.h, colors.axis);
  xticks.forEach((v) => { line(ctx, X(v), R.y + R.h, X(v), R.y + R.h + 4, colors.axis); txt(ctx, colors, xlab(v), X(v), R.y + R.h + 15, { size: colors.fsXs, align: "center", fill: colors.ink3 }); });
  yticks.forEach((v) => { line(ctx, R.x - 4, Y(v), R.x, Y(v), colors.axis); txt(ctx, colors, ylab(v), R.x - 7, Y(v) + 4, { size: colors.fsXs, align: "right", fill: colors.ink3 }); });
  if (xt) txt(ctx, colors, xt, R.x + R.w / 2, R.y + R.h + 30, { size: colors.fsXs, align: "center", fill: colors.ink2 });
  if (yt) { ctx.save(); ctx.translate(R.x - 30, R.y + R.h / 2); ctx.rotate(-Math.PI / 2); txt(ctx, colors, yt, 0, 0, { size: colors.fsXs, align: "center", fill: colors.ink2 }); ctx.restore(); }
  return { X, Y };
}
const clipTo = (ctx, R) => { ctx.save(); ctx.beginPath(); ctx.rect(R.x, R.y, R.w, R.h); ctx.clip(); };

/* a 28x28 image as a small canvas in one ink, cached */
const rgbCache = new Map();
function rgbOf(col) {
  if (rgbCache.has(col)) return rgbCache.get(col);
  const c = document.createElement("canvas"); c.width = c.height = 1;
  const g = c.getContext("2d"); g.fillStyle = col; g.fillRect(0, 0, 1, 1);
  const d = g.getImageData(0, 0, 1, 1).data, out = [d[0], d[1], d[2]];
  rgbCache.set(col, out);
  return out;
}
const imgCache = new Map();
function drawImage(ctx, colors, key, px, x, y, s) {
  const id = `${key}|${colors.ink1}`;
  if (!imgCache.has(id)) {
    const c = document.createElement("canvas"); c.width = c.height = 28;
    const g = c.getContext("2d"), im = g.createImageData(28, 28), [r, gg, b] = rgbOf(colors.ink1);
    for (let i = 0; i < 784; i++) { const o = 4 * i; im.data[o] = r; im.data[o + 1] = gg; im.data[o + 2] = b; im.data[o + 3] = px[i]; }
    g.putImageData(im, 0, 0); imgCache.set(id, c);
  }
  ctx.save(); ctx.fillStyle = colors.surface; ctx.fillRect(x, y, s, s); ctx.imageSmoothingEnabled = false;
  ctx.drawImage(imgCache.get(id), x, y, s, s); ctx.restore();
  frame(ctx, x, y, s, s, colors.grid);
}

/* ------------------------------------------------------------- stages */

const pressesOf = (anim, page) => anim?.n?.[page] ?? 0;
const playingOn = (anim, page) => anim != null && anim.t < 1 && anim.playPage === page;
/** where Train is, in checkpoints: 0 before it (the untrained model), 0 → last during it, last after */
const posOf = (anim, page) => {
  const last = CK[page].length - 1;
  if (pressesOf(anim, page) < 1) return 0;
  return playingOn(anim, page) ? anim.t * last : last;
};
const ckOf = (anim, page) => Math.floor(posOf(anim, page) + 1e-9);
const moveOf = (anim, page) => { const q = posOf(anim, page), last = CK[page].length - 1; return q >= last ? 0 : ease(q - Math.floor(q)); };
const trainedOn = (anim, page) => pressesOf(anim, page) >= 1 && !playingOn(anim, page);
/** the learned α at the checkpoint shown, or null before Learned α's Train */
const learnedNow = (anim) => {
  if (pressesOf(anim, "learned") < 1) return null;
  const T = LATE.alpha_traj, k = ckOf(anim, "learned"), e = moveOf(anim, "learned");
  return e > 0 ? lerp(T[k], T[Math.min(T.length - 1, k + 1)], e) : T[k];
};

