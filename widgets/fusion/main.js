const PAD = 10;
function layoutOf(w, page) {
  const inner = w - 2 * PAD;
  if (page === "early") {
    const strip = { x: PAD + 84, y: 26, w: inner - 84 - 8, h: 116 };
    const gap = 46, pw = Math.floor((inner - 2 * gap - 40) / 3), top = strip.y + strip.h + 80;
    const ph = Math.round(clamp(pw * 0.95, 140, 220));
    const P = [0, 1, 2].map((j) => ({ x: PAD + 40 + j * (pw + gap), y: top, w: pw, h: ph }));
    const capTop = top + ph + 60;
    return { strip, P, capTop, height: capTop + 6 * 16 };
  }
  if (page === "late") {
    const gap = 50, cell = Math.floor((inner - gap) / 2), s = cell - 40;
    const r1 = 26, r2 = r1 + s + 96;
    const box = (c, r) => ({ x: PAD + 40 + c * (cell + gap), y: r, w: s, h: s });
    const capTop = r2 + s + 62;
    return { scat: box(0, r1), bars: { x: PAD + (cell + gap), y: r1, w: cell, h: s }, alpha: box(0, r2), auc: box(1, r2), capTop, height: capTop + 6 * 16 };
  }
  const rowH = 15, mx = PAD + 34, mat = { x: mx, y: 40, w: inner - 34, h: 10 * rowH, rowH };
  const retTop = mat.y + mat.h + 74, s = 30, rowR = s + 22;
  const colW = Math.floor(inner / 2);
  const capTop = retTop + 5 * rowR + 24;
  return { mat, ret: { top: retTop, s, rowR, colW }, capTop, height: capTop + 5 * 16 };
}

