function lateAlpha(params, anim) {
  /* each test patient's α: the slider's on One α, the gate's at the checkpoint shown on Gate */
  if (params.weighting !== "gate") { const a = learnedNow(anim) ?? LATE.alpha_traj[0]; return LATE_IDS.map(() => a); }
  const k = ckOf(anim, "gate"), e = moveOf(anim, "gate"), last = LATE.checkpoints.length - 1;
  const a0 = LATE.gate[k], a1 = LATE.gate[Math.min(last, k + 1)];
  return e > 0 ? a0.map((v, i) => lerp(v, a1[i], e)) : a0;
}

