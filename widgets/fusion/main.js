function aucOf(score) {
  const s = LATE_IDS.map(score), pos = [], neg = [];
  LATE_IDS.forEach((i) => (LATE.y[i] ? pos : neg).push(s[i]));
  let a = 0;
  for (const p of pos) for (const q of neg) a += p > q ? 1 : p === q ? 0.5 : 0;
  return a / (pos.length * neg.length);
}
