const svEsc = (t) => String(t).replace(/&/g, "&amp;").replace(/</g, "&lt;");
/** a box: an encoder solid on a raised surface, everything else plain; `hl` outlines it in --c-highlight */
function svBox(x, y, w, h, text, { kind = null, hl = false } = {}) {
  const st = kind === "enc" ? "fill:var(--surface-2);stroke:var(--ink-1);stroke-width:1.6"
    : `fill:var(--surface-1);stroke:${hl ? "var(--c-highlight)" : "var(--ink-3)"};stroke-width:${hl ? 1.8 : 1}`;
  return `<rect x="${x + 0.5}" y="${y + 0.5}" width="${w - 1}" height="${h - 1}" style="${st}"/>` +
    `<text x="${x + w / 2}" y="${y + h / 2 + 4}" text-anchor="middle" style="${kind === "enc" ? "font-weight:600;" : ""}fill:var(--ink-1)">${svEsc(text)}</text>`;
}
function svArrow(x0, y0, x1, y1) {
  const a = Math.atan2(y1 - y0, x1 - x0), h = 7;
  const p = [[x1, y1], [x1 - h * Math.cos(a - 0.4), y1 - h * Math.sin(a - 0.4)], [x1 - h * Math.cos(a + 0.4), y1 - h * Math.sin(a + 0.4)]];
  return `<line x1="${x0}" y1="${y0}" x2="${x1}" y2="${y1}" style="stroke:var(--ink-3);stroke-width:1.2"/>` +
    `<polygon points="${p.map((q) => q.map((v) => v.toFixed(1)).join(",")).join(" ")}" style="fill:var(--ink-3)"/>`;
}
const svText = (x, y, t, anchor = "middle", fill = "var(--ink-3)") => `<text x="${x}" y="${y}" text-anchor="${anchor}" style="fill:${fill}">${svEsc(t)}</text>`;

/** two branches, A above B: input → encoder → z, then whatever joins them; `mid` draws the join from the two z ends */
function twoBranch(y0, labels, mid) {
  const h = 26, rows = [y0, y0 + 40];
  let s = "";
  rows.forEach((ry, i) => {
    s += svBox(0, ry, 74, h, labels.inputs[i]) + svArrow(74, ry + h / 2, 90, ry + h / 2);
    s += svBox(92, ry, 92, h, labels.enc[i], { kind: "enc" }) + svArrow(184, ry + h / 2, 200, ry + h / 2);
    s += svBox(202, ry, 30, h, i ? "z_B" : "z_A");
  });
  return s + mid({ x: 232, rows, h, mid: y0 + 33 });
}
