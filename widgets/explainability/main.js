/** a caption over as many lines as it needs, a word at a time */
function wrap(ctx, s, x, y, room, lh, style) {
  let lineText = "", yy = y;
  for (const word of s.split(" ")) {
    const next = lineText ? `${lineText} ${word}` : word;
    if (lineText && width(ctx, next, style.font) > room) { txt(ctx, lineText, x, yy, style); lineText = word; yy += lh; } else lineText = next;
  }
  if (lineText) txt(ctx, lineText, x, yy, style);
}
const width = (ctx, s, font) => { ctx.save(); ctx.font = font; const v = ctx.measureText(s).width; ctx.restore(); return v; };
const rgb = (c) => { const m = String(c).match(/^#([0-9a-f]{6})$/i); return m ? [0, 2, 4].map((i) => parseInt(m[1].slice(i, i + 2), 16)) : [128, 128, 128]; };
const mix = (a, b, u) => `rgb(${a.map((x, i) => Math.round(x + (b[i] - x) * Math.max(0, Math.min(1, u)))).join(",")})`;
