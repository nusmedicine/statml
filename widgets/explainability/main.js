/** values per token (null = not yet revealed); `signed` for attributions, false for attention weights */
function drawStrip(ctx, c, w, p, G, vals, { signed, scale, title, e }) {
  txt(ctx, title, PAD, STRIP_HEAD, { font: cap(c), fill: c.ink1 });
  txt(ctx, S.predicted(p.task, e), w - PAD, STRIP_HEAD, { font: small(c), fill: c.ink2, align: "right" });
  line(ctx, [[X0, ZERO + 0.5], [w - PAD, ZERO + 0.5]], c.grid);
  txt(ctx, "0", X0 - 6, ZERO, { font: small(c), fill: c.ink3, align: "right" });
  const fill = (v) => (signed ? heat(c, v, scale) : weightFill(c, v, scale));
  G.cells.forEach((cell, i) => {
    const v = vals ? vals[i] : null, special = i === 0 || i === G.L - 1, boxed = !G.prot || special;
    const cx = cell.x + cell.w / 2;
    if (boxed) {
      ctx.save(); ctx.fillStyle = v == null ? c.surface2 : fill(v); ctx.fillRect(cell.x, TOK_Y - 10, cell.w, 20); ctx.restore();
      txt(ctx, G.toks[i], cx, TOK_Y, { font: G.prot ? small(c) : G.font, fill: c.ink1, align: "center" });
    } else {
      ctx.save(); ctx.fillStyle = v == null ? c.surface2 : fill(v); ctx.fillRect(cell.x, TOK_Y - 10, Math.max(1, cell.w + 0.3), 20); ctx.restore();
    }
    if (v == null) return;
    const over = Math.abs(v) > scale * 1.0001, hgt = (Math.min(Math.abs(v), scale) / (scale || 1)) * BAR;
    const bw = G.prot && !special ? Math.max(1, cell.w + 0.3) : Math.min(10, cell.w - 2);
    ctx.save(); ctx.fillStyle = signed ? (v >= 0 ? c.valueHigh : c.valueLow) : c.magnitude;
    if (v < 0) ctx.fillRect(cx - bw / 2, ZERO, bw, hgt); else ctx.fillRect(cx - bw / 2, ZERO - hgt, bw, hgt);
    ctx.restore();
    /* past the scale (a special token): the bar is clipped and broken by two strokes near its end, the value printed */
    if (over) for (const dy of [7, 11]) { const y = v >= 0 ? ZERO - BAR + dy : ZERO + BAR - dy; line(ctx, [[cx - bw / 2 - 1, y + 1.5], [cx + bw / 2 + 1, y - 1.5]], c.surface, 1.5); }
    if (boxed) txt(ctx, signed ? f2(v) : v.toFixed(2), cx, v < 0 ? ZERO + hgt + 9 : ZERO + 9, { font: monoX(c), fill: c.ink3, align: "center" });
  });
  if (G.prot) {
    const L = G.L;
    for (let r = 100; r < L - 1; r += 100) { const x = G.a + (r - 0.5) * G.pitch; line(ctx, [[x, TOK_Y + 11], [x, TOK_Y + 14]], c.ink3); txt(ctx, String(r), x, STRIP_END - 6, { font: small(c), fill: c.ink3, align: "center" }); }
    txt(ctx, "1", G.a, STRIP_END - 6, { font: small(c), fill: c.ink3, align: "left" });
  }
}

