/** ATTENTION. Notes: the whole matrix, its columns under the strip's tokens, a row label a query; the [CLS] row
    outlined, since the strip is that row. Proteins: the matrix in bins of 8 positions, square. */
function drawAttention(ctx, c, w, p, G, prog) {
  const { n, m } = attMatrix(p), b = p.block, h = p.head;
  if (G.prot) {
    txt(ctx, S.attHeadProt(b, h), PAD, MECH, { font: cap(c), fill: c.ink1 });
    const x0 = X0, y0 = MECH + 22, cs = MAT_S / n, mx = Math.max(...m);
    for (let i = 0; i < n; i++) for (let j = 0; j < n; j++) { ctx.fillStyle = weightFill(c, m[i * n + j], mx); ctx.fillRect(x0 + j * cs, y0 + i * cs, cs + 0.3, cs + 0.3); }
    ctx.save(); ctx.strokeStyle = c.ink1; ctx.lineWidth = 1.5; ctx.strokeRect(x0, y0, MAT_S, cs); ctx.restore();
    txt(ctx, "[CLS] …", x0 - 6, y0 + cs / 2, { font: small(c), fill: c.ink1, align: "right" });
    txt(ctx, S.queryAxis, x0 - 6, y0 + MAT_S / 2, { font: small(c), fill: c.ink3, align: "right" });
    txt(ctx, S.keyAxis, x0 + MAT_S / 2, y0 + MAT_S + 12, { font: small(c), fill: c.ink3, align: "center" });
    return;
  }
  txt(ctx, S.attHead(b, h), PAD, MECH, { font: cap(c), fill: c.ink1 });
  const y0 = MECH + 18, mx = Math.max(...m);
  for (let i = 0; i < n; i++) {
    const yy = y0 + i * CELL_H;
    txt(ctx, G.toks[i], X0 - 6, yy + CELL_H / 2, { font: i === 0 ? smallBold(c) : small(c), fill: i === 0 ? c.ink1 : c.ink2, align: "right" });
    for (let j = 0; j < n; j++) { const cell = G.cells[j]; ctx.fillStyle = weightFill(c, m[i * n + j], mx); ctx.fillRect(cell.x, yy + 1, cell.w, CELL_H - 2); }
  }
  const last = G.cells[n - 1];
  ctx.save(); ctx.strokeStyle = c.ink1; ctx.lineWidth = 1.5; ctx.strokeRect(X0 - 1, y0, last.x + last.w - X0 + 2, CELL_H); ctx.restore();
  /* the key in flight: its weight rides from the [CLS] row up to its token (his rule: only movement is eased) */
  if (prog.moving != null) {
    const j = prog.moving, cell = G.cells[j], u = prog.t, yA = y0 + 1, yB = TOK_Y - 10, yy = yA + (yB - yA) * ease(u);
    ctx.save(); ctx.fillStyle = weightFill(c, clsRow(p)[j], Math.max(...clsRow(p))); ctx.strokeStyle = c.ink1; ctx.lineWidth = 1.5;
    ctx.fillRect(cell.x, yy, cell.w, CELL_H - 2); ctx.strokeRect(cell.x, yy, cell.w, CELL_H - 2); ctx.restore();
  }
}

/** INTEGRATED GRADIENTS: the logit along the path, drawn up to the current α, a tick a step, the marker in ink */
function drawIG(ctx, c, w, p, alpha, k) {
  const e = rowOf(p), g = e.ig[p.steps], path = e.path, s = Number(p.steps), C = Math.min(s, TABLE.checks);
  txt(ctx, S.igHead, PAD, MECH, { font: cap(c), fill: c.ink1 });
  const ch = { x: X0, y: MECH + 22, w: w - PAD - X0 - 70, h: CHART_H };
  const lo = Math.min(...path), hi = Math.max(...path), pad = (hi - lo) * 0.1 || 1;
  const X = (a) => ch.x + a * ch.w, Y = (v) => ch.y + ch.h - ((v - lo + pad) / (hi - lo + 2 * pad)) * ch.h;
  line(ctx, [[ch.x, ch.y + ch.h + 0.5], [ch.x + ch.w, ch.y + ch.h + 0.5]], c.grid);
  line(ctx, [[ch.x - 0.5, ch.y], [ch.x - 0.5, ch.y + ch.h]], c.grid);
  txt(ctx, S.alpha0, ch.x, ch.y + ch.h + 12, { font: small(c), fill: c.ink3 });
  txt(ctx, S.alpha1(p.task), ch.x + ch.w, ch.y + ch.h + 12, { font: small(c), fill: c.ink3, align: "right" });
  for (let i = 1; i <= s; i++) { const x = X(i / s); line(ctx, [[x, ch.y + ch.h], [x, ch.y + ch.h - 4]], i / s <= alpha + 1e-9 ? c.ink2 : c.grid); }
  /* the curve, revealed up to α: between the table's 51 points, linear */
  const pts = [], N = path.length - 1;
  for (let i = 0; i <= N && i / N <= alpha + 1e-9; i++) pts.push([X(i / N), Y(path[i])]);
  if (alpha > 0 && alpha < 1) { const f = alpha * N, i = Math.floor(f), u = f - i; pts.push([X(alpha), Y(path[i] + (path[Math.min(N, i + 1)] - path[i]) * u)]); }
  if (pts.length > 1) line(ctx, pts, c.ink1, 2);
  txt(ctx, f2(path[0]), ch.x - 6, Y(path[0]), { font: monoX(c), fill: c.ink2, align: "right" });
  if (alpha > 0) {
    const [ex, ey] = pts[pts.length - 1];
    line(ctx, [[ex, ch.y], [ex, ch.y + ch.h]], c.ink2, 1, [3, 3]);
    ctx.save(); ctx.fillStyle = c.ink1; ctx.beginPath(); ctx.arc(ex, ey, 3.5, 0, 2 * Math.PI); ctx.fill(); ctx.restore();
    if (alpha >= 1) txt(ctx, f2(path[N]), ex + 8, ey, { font: monoX(c), fill: c.ink2 });
  }
  const part = igPart(p, k), sum = part.reduce((a, v) => a + v, 0), stepsDone = Math.round((k * s) / C);
  const msg = k >= C ? S.igDone(g.attr.reduce((a, v) => a + v, 0), g.fx - g.fb, Math.abs(g.delta)) : S.igSum(stepsDone, s, sum);
  txt(ctx, msg, X0, ch.y + ch.h + 32, { font: small(c), fill: c.ink1 });
}

/** OCCLUSION: the window on the strip, and the logit with each window occluded, charted under the strip's tokens */
function drawOcclusion(ctx, c, w, p, G, pos) {
  const e = rowOf(p), W = windows(p), f0 = e.occ.f0, n = Math.floor(pos);
  txt(ctx, S.occHead, PAD, MECH, { font: cap(c), fill: c.ink1 });
  const ch = { y: MECH + 22, h: CHART_H }, ys = W.map((x) => f0 - x.d);
  const lo = Math.min(f0, ...ys), hi = Math.max(f0, ...ys), pad = (hi - lo) * 0.1 || 1;
  const Y = (v) => ch.y + ch.h - ((v - lo + pad) / (hi - lo + 2 * pad)) * ch.h;
  const centre = (win) => { const a = G.cells[win.s], b = G.cells[win.s + win.k - 1]; return (a.x + b.x + b.w) / 2; };
  line(ctx, [[X0, Y(f0)], [w - PAD, Y(f0)]], c.ink3, 1, [4, 3]);
  txt(ctx, `${S.occNone} ${f2(f0)}`, X0 - 6, Y(f0), { font: small(c), fill: c.ink3, align: "right" });
  line(ctx, [[X0, ch.y + ch.h + 0.5], [w - PAD, ch.y + ch.h + 0.5]], c.grid);
  const shown = W.slice(0, n);
  if (G.prot) { if (shown.length > 1) line(ctx, shown.map((x, i) => [centre(x), Y(ys[i])]), c.ink1, 1.5); }
  else shown.forEach((x, i) => { ctx.save(); ctx.fillStyle = c.ink1; ctx.beginPath(); ctx.arc(centre(x), Y(ys[i]), 3.5, 0, 2 * Math.PI); ctx.fill(); ctx.restore(); });
  /* the window: on the strip's tokens, moving from one place to the next */
  if (pos > 0 && n < W.length + 1) {
    const i = Math.min(W.length - 1, Math.max(0, Math.ceil(pos) - 1)), u = pos - Math.floor(pos);
    const at = (win) => { const a = G.cells[win.s], b = G.cells[win.s + win.k - 1]; return [a.x - 2, b.x + b.w + 2]; };
    let [xa, xb] = at(W[i]);
    if (u > 0 && i > 0) { const [pa, pb] = at(W[i - 1]); const t = ease(u); xa = pa + (xa - pa) * t; xb = pb + (xb - pb) * t; }
    if (pos < W.length || u > 0) { ctx.save(); ctx.strokeStyle = c.ink1; ctx.lineWidth = 2; ctx.strokeRect(xa, TOK_Y - 13, xb - xa, 26); ctx.restore(); }
  }
  txt(ctx, S.occCount(Math.min(n, W.length), W.length, windowOf(p), strideOf(windowOf(p)), p.task), X0, ch.y + ch.h + 14, { font: small(c), fill: c.ink2 });
}

const ease = (u) => (u < 0.5 ? 2 * u * u : 1 - 2 * (1 - u) * (1 - u));

