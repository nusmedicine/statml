/** how many presses a page holds: a key (notes) or 50 keys (proteins); a checkpoint along the path; a window */
function unitsOf(page, p) {
  if (page === "attention") return PROTEIN(p.task) ? Math.ceil(tokensOf(p).length / 50) : tokensOf(p).length;
  if (page === "integrated-gradients") return Math.min(Number(p.steps), TABLE.checks);
  return windows(p).length;
}
/** a unit's duration: a press is slow enough to follow; Play takes about 4 s whatever the count */
const unitMs = (page, p, mode) => (mode === "step" ? (page === "occlusion" && PROTEIN(p.task) ? 120 : 450) : Math.max(15, Math.min(450, 4000 / unitsOf(page, p))));
const pageOf = (anim, params) => anim.p[params.page];
function settle(anim, params) {
  const pg = pageOf(anim, params);
  anim.key = params.page;
  anim.done = pg.n >= unitsOf(params.page, params) && pg.t >= 1;
}
/** the page's progress as a number of units, fractional while one is in flight */
const progress = (pg) => (pg.t < 1 ? pg.n - 1 + pg.t : pg.n);

