const bytes = (b64) => Uint8Array.from(atob(b64), (c) => c.charCodeAt(0));
const unsigned = (b64, scale) => Float32Array.from(bytes(b64), (b) => (b / 255) * scale);
const signedOf = (b64, scale) => Float32Array.from(bytes(b64), (b) => ((b > 127 ? b - 256 : b) / 127) * scale);
const prob = (e) => { const m = Math.max(...e.logits), z = e.logits.map((v) => Math.exp(v - m)); return z[e.pred] / (z[0] + z[1]); };
const rowOf = (p) => TABLE.rows[p.task][p.training][Number(p.example) - 1];
const exampleOf = (p) => TABLE.examples[p.task][Number(p.example) - 1];
/** the tokens of a row: a note's words, or a protein's residues, between [CLS] and [SEP] */
const tokensOf = (p) => { const [s] = exampleOf(p); return ["[CLS]", ...(PROTEIN(p.task) ? [...s.slice(0, rowOf(p).ig["5"].attr.length - 2)] : s.split(" ")), "[SEP]"]; };
const f2 = (v) => { const r = Math.abs(v) < 0.005 ? 0 : v; return (r < 0 ? "−" : "") + Math.abs(r).toFixed(2); };
const windowOf = (p) => Number(PROTEIN(p.task) ? p.window : p.words);
const strideOf = (k) => Math.max(1, Math.floor(k / 2));

/** the [CLS] row of the chosen block and head (or the mean of the heads), every key */
const CACHE = {};
function clsRow(p) {
  const e = rowOf(p), b = Number(p.block) - 1, heads = p.head === "mean" ? [0, 1, 2, 3] : [Number(p.head) - 1];
  const key = `cls/${p.task}/${p.training}/${p.example}/${p.block}/${p.head}`;
  if (CACHE[key]) return CACHE[key];
  let out;
  if (PROTEIN(p.task)) {
    const rows = heads.map((h) => unsigned(e.att.cls[b * 4 + h], e.att.clsScale[b * 4 + h]));
    out = Float32Array.from(rows[0], (_, j) => rows.reduce((a, r) => a + r[j], 0) / rows.length);
  } else {
    const L = Math.round(Math.sqrt(e.att[b][0].length));
    out = Float32Array.from({ length: L }, (_, j) => heads.reduce((a, h) => a + e.att[b][h][j], 0) / heads.length);
  }
  return (CACHE[key] = out);
}
/** the attention matrix shown under the strip: notes L x L, proteins pooled into bins */
function attMatrix(p) {
  const e = rowOf(p), b = Number(p.block) - 1, heads = p.head === "mean" ? [0, 1, 2, 3] : [Number(p.head) - 1];
  const key = `mat/${p.task}/${p.training}/${p.example}/${p.block}/${p.head}`;
  if (CACHE[key]) return CACHE[key];
  let n, m;
  if (PROTEIN(p.task)) {
    n = e.att.bins; const mats = heads.map((h) => unsigned(e.att.pooled[b * 4 + h], e.att.pooledScale[b * 4 + h]));
    m = Float32Array.from(mats[0], (_, j) => mats.reduce((a, x) => a + x[j], 0) / mats.length);
  } else {
    n = Math.round(Math.sqrt(e.att[b][0].length));
    m = Float32Array.from(e.att[b][0], (_, j) => heads.reduce((a, h) => a + e.att[b][h][j], 0) / heads.length);
  }
  return (CACHE[key] = { n, m });
}
/** IG's running sum after checkpoint c (1-based; 0 is all zeros) */
function igPart(p, c) {
  const g = rowOf(p).ig[p.steps], L = g.attr.length;
  if (c <= 0) return new Float32Array(L);
  if (!PROTEIN(p.task)) return Float32Array.from(g.part[c - 1]);
  const key = `ig/${p.task}/${p.training}/${p.example}/${p.steps}`;
  const all = CACHE[key] ?? (CACHE[key] = signedOf(g.part, g.pscale));
  return all.subarray((c - 1) * L, c * L);
}
/** occlusion's windows: their first position (1-based over the tokens, [CLS] is 0) and the logit's drop */
function windows(p) {
  const e = rowOf(p), k = windowOf(p), st = strideOf(k), d = e.occ[String(k)];
  return d.map((v, i) => ({ s: 1 + i * st, k, d: v }));
}
/** each position's attribution from the first n windows: the mean drop over the windows covering it */
function occValues(p, n) {
  const L = rowOf(p).ig["5"].attr.length, tot = new Float32Array(L), cnt = new Float32Array(L);
  windows(p).slice(0, n).forEach(({ s, k, d }) => { for (let i = s; i < s + k; i++) { tot[i] += d; cnt[i] += 1; } });
  return Float32Array.from(tot, (v, i) => (cnt[i] ? v / cnt[i] : 0));
}

