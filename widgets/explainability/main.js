/** where each token sits in the strip. Notes: a box a word, laid from X0. Proteins: [CLS] and [SEP] as labelled
    boxes at the ends, the residues as columns between them. */
function stripGeo(ctx, c, w, p) {
  const toks = tokensOf(p), L = toks.length;
  if (PROTEIN(p.task)) {
    const sw = 40, a = X0 + sw + 4, b = w - PAD - sw - 4, pitch = (b - a) / (L - 2);
    const cells = toks.map((_, i) => (i === 0 ? { x: X0, w: sw } : i === L - 1 ? { x: w - PAD - sw, w: sw } : { x: a + (i - 1) * pitch, w: pitch }));
    return { toks, L, cells, font: monoX(c), prot: true, a, b, pitch };
  }
  let font = body(c), gap = 6, ws = toks.map((s) => width(ctx, s, font) + 10);
  const room = w - PAD - X0;
  /* equal columns when every word fits one, up to 96 px: the matrix under the strip reads as a grid */
  const col = Math.min(96, (room - gap * (L - 1)) / L);
  if (ws.every((x) => x <= col)) ws = ws.map(() => col);
  if (ws.reduce((x, y) => x + y, 0) + gap * (L - 1) > room) { font = small(c); gap = 4; ws = toks.map((s) => width(ctx, s, font) + 8); }
  const tot = ws.reduce((x, y) => x + y, 0) + gap * (L - 1), squeeze = Math.min(1, (room - gap * (L - 1)) / (tot - gap * (L - 1)));
  let x = X0; const cells = ws.map((cw) => { const cell = { x, w: cw * squeeze }; x += cw * squeeze + gap; return cell; });
  return { toks, L, cells, font, prot: false };
}

