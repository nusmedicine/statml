const DUR = { scaffold: 2400, split: 3400, evaluate: 2000 };
const ease = (t) => (t < 0.5 ? 4 * t * t * t : 1 - (-2 * t + 2) ** 3 / 2);
const lerp = (a, b, t) => a + (b - a) * t;
/** each example and each split is its own stage, with its own presses (94's stageOf) */
