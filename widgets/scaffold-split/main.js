/* ONE BLOCK A SCAFFOLD, laid out ONCE at a fixed width so every page's
   height is a constant: a height that reads the width never settles in the
   harness (widget 62). A canvas narrower than the grid draws it scaled. Each
   group of two or more is a square-ish block of 5px cells, outlined, largest
   first; the single-molecule scaffolds follow as loose cells. The grid's order
   is data.js's: group by group, actives first inside a group. */
const PITCH = 6, CELL = 5, GAP = 5, GRID_W = 520, NAME_H = 14, CAP_H = 16, BAND_GAP = 10;
/* BANDS BY GROUP SIZE, EACH LABELLED (his pick A, round 1): the draft wrapped
   one flow of blocks into rows whose edges fell wherever the box shape
   changed, so the rows read as categories they were not (one mixed groups of
   7, 6, 5 and 4). Now a band is a size class, captioned with how many
   scaffolds it holds, and the separation says how lopsided the screen is. */
const BANDS = [[13, Infinity, "13 or more"], [7, 12, "7–12"], [4, 6, "4–6"], [3, 3, "3"], [2, 2, "2"], [1, 1, "1"]];
const GRID = (() => {
  const blocks = [], bands = [], cellAt = new Array(N), groupOf = new Array(N);
  const scols = Math.floor((GRID_W + 1) / PITCH);
  let y = 0, k = 0, singleTop = 0, nSingles = 0;
  BANDS.forEach(([lo, hi, range], bi) => {
    const gs = GROUPS.map(([n], g) => [n, g]).filter(([n]) => n >= lo && n <= hi);
    if (!gs.length) return;
    bands.push({ y, range, count: gs.length, single: lo === 1 });
    y += CAP_H;
    if (lo === 1) {
      singleTop = y; nSingles = gs.length;
      gs.forEach(([, g], j) => { cellAt[k] = [(j % scols) * PITCH, y + Math.floor(j / scols) * PITCH]; groupOf[k] = g; k += 1; });
      y += Math.ceil(gs.length / scols) * PITCH;
      return;
    }
    let x = 0, rowH = 0, row = 0;
    gs.forEach(([n, g]) => {
      const cols = Math.ceil(Math.sqrt(n)), rows = Math.ceil(n / cols), bw = cols * PITCH - 1, bh = rows * PITCH - 1;
      /* the first band's first row carries the two block names under it */
      if (x + bw > GRID_W) { x = 0; y += rowH + GAP + (bi === 0 && row === 0 ? NAME_H : 0); rowH = 0; row += 1; }
      blocks.push({ g, x, y, w: bw, h: bh, start: k, n });
      for (let j = 0; j < n; j++) { cellAt[k] = [x + (j % cols) * PITCH, y + Math.floor(j / cols) * PITCH]; groupOf[k] = g; k += 1; }
      x += bw + GAP; rowH = Math.max(rowH, bh);
    });
    y += rowH + (bi === 0 && row === 0 ? NAME_H : 0) + BAND_GAP;
  });
  const blockOfGroup = new Map(blocks.map((b) => [b.g, b]));
  return { blocks, bands, blockOfGroup, cellAt, groupOf, singleTop, nSingles, h: y };
})();
/** where the grid sits, and how much it is scaled, at this canvas width */
const gridBox = (w, top) => { const sc = Math.min(1, (w - 16) / GRID_W); return { x0: (w - GRID_W * sc) / 2, y0: top, sc }; };

/* per split and seed, the parts each group holds; for Compare */
const PARTS = {};
const partsOf = (kind, seed) => {
  const key = `${kind}${seed}`;
  if (!PARTS[key]) {
    const s = SPLITS[kind][seed], per = GROUPS.map(() => [0, 0, 0]);
    for (let k = 0; k < N; k++) per[GRID.groupOf[k]][+s[k]] += 1;
    PARTS[key] = per;
  }
  return PARTS[key];
};

/* TRAIN AND HELD OUT AS TWO COLUMNS (round 3, his pick B from
   `_lab/scaffold-split-groups-mock.html`, with hover pairing). Split 80 / 20
   moves every molecule out of the one grid into two columns, Train left and
   Held out right, each in the same size bands, the bands level across the gap
   so a size class reads straight across. A scaffold cut by the split appears
   in both columns as two pieces, each as WIDE as the whole block, so a strip
   of benzene on the right reads as benzene. Inside a band each column flows
   its own pieces: putting a scaffold's two pieces on one row needs a held-out
   column as wide as Train (a row of five large blocks has held-out strips
   about 300px wide), so hovering a piece rings its other piece instead. Split
   50 / 50 colours the held-out column in place, validation and test. */
const COL_L = 362, COL_GAP = 18, COL_R = GRID_W - COL_L - COL_GAP, HEAD_H = 20;
/* the move's staging, as fractions of the press: held-out cells start over the
   first MOVE.held, Train's from MOVE.train on; each cell takes MOVE.each */
const MOVE = { held: 0.4, train: 0.5, each: 0.12 };
const PAIRS = {};
function pairOf(kind, seed) {
  const key = `${kind}${seed}`;
  if (PAIRS[key]) return PAIRS[key];
  const split = SPLITS[kind][seed];
  const pos = new Array(N), outlines = [], caps = [];
  const sides = [[0, COL_L], [COL_L + COL_GAP, COL_R]].map(([x0, width], side) => {
    const byGroup = new Map();
    for (let k = 0; k < N; k++) if ((split[k] === "0") === (side === 0)) {
      const g = GRID.groupOf[k];
      if (!byGroup.has(g)) byGroup.set(g, []);
      byGroup.get(g).push(k);
    }
    return { x0, width, byGroup, n: [...byGroup.values()].reduce((t, ks) => t + ks.length, 0) };
  });
  let y = HEAD_H;
  BANDS.forEach(([lo, hi, range]) => {
    const per = sides.map((sd) => [...sd.byGroup.keys()].filter((g) => GROUPS[g][0] >= lo && GROUPS[g][0] <= hi));
    if (!per[0].length && !per[1].length) return;
    caps.push({ rule: y });
    let bottom = y + CAP_H;
    sides.forEach((sd, side) => {
      caps.push({ text: S.colBand(range, side === 1), x: sd.x0, y: y + CAP_H - 6 });
      let yy = y + CAP_H;
      if (lo === 1) {
        const sc = Math.floor((sd.width + 1) / PITCH);
        per[side].forEach((g, j) => { pos[sd.byGroup.get(g)[0]] = [sd.x0 + (j % sc) * PITCH, yy + Math.floor(j / sc) * PITCH]; });
        bottom = Math.max(bottom, yy + Math.ceil(per[side].length / sc) * PITCH);
        return;
      }
      let x = 0, rowH = 0;
      per[side].forEach((g) => {
        const ks = sd.byGroup.get(g), cols = Math.min(Math.ceil(Math.sqrt(GROUPS[g][0])), Math.floor((sd.width + 1) / PITCH));
        const rows = Math.ceil(ks.length / cols), bw = cols * PITCH - 1, bh = rows * PITCH - 1;
        if (x + bw > sd.width) { x = 0; yy += rowH + GAP; rowH = 0; }
        ks.forEach((k, j) => { pos[k] = [sd.x0 + x + (j % cols) * PITCH, yy + Math.floor(j / cols) * PITCH]; });
        outlines.push({ x: sd.x0 + x, y: yy, w: bw, h: bh, g, side });
        x += bw + GAP; rowH = Math.max(rowH, bh);
      });
      bottom = Math.max(bottom, yy + rowH);
    });
    y = bottom + BAND_GAP;
  });
  const heads = sides.map((sd, side) => ({ text: S.colHead(side, sd.n, sd.n / N), x: sd.x0 }));
  /* the order the move takes: held-out cells leave first, then Train closes up */
  const held = [], train = [];
  for (let k = 0; k < N; k++) (split[k] === "0" ? train : held).push(k);
  const start = new Float32Array(N);
  held.forEach((k, i) => { start[k] = MOVE.held * (i / held.length); });
  train.forEach((k, i) => { start[k] = MOVE.train + (1 - MOVE.train - MOVE.each) * (i / train.length); });
  PAIRS[key] = { pos, outlines, caps, heads, h: y, start, n: sides.map((sd) => sd.n) };
  return PAIRS[key];
}

/** every cell at posOf(k), coloured fillOf(k), an active marked inside it */
function drawCells(ctx, colors, b, posOf, fillOf) {
  ctx.save(); ctx.translate(b.x0, b.y0); ctx.scale(b.sc, b.sc);
  for (let k = 0; k < N; k++) {
    const [x, y] = posOf(k);
    ctx.fillStyle = fillOf(k); ctx.fillRect(x, y, CELL, CELL);
    if (LABELS[k] === "1") { ctx.fillStyle = colors.ink1; ctx.fillRect(x + 1, y + 1, CELL - 2, CELL - 2); }
  }
  ctx.restore();
}
/** the two columns' rules, captions, headings and outlines; pairG frames both pieces of one scaffold */
function drawPairFrame(ctx, colors, b, P, { ring = null, pairG = null } = {}) {
  ctx.save(); ctx.translate(b.x0, b.y0); ctx.scale(b.sc, b.sc);
  for (const c of P.caps) {
    if (c.rule != null) line(ctx, 0, c.rule - 4, GRID_W, c.rule - 4, colors.grid);
    else txt(ctx, colors, c.text, c.x, c.y, { fill: colors.ink3 });
  }
  P.heads.forEach((hd) => txt(ctx, colors, hd.text, hd.x, 13, { font: `600 ${colors.fsXs} ${colors.font}`, fill: colors.ink1 }));
  P.outlines.forEach((o, i) => {
    const paired = pairG != null && o.g === pairG, on = ring && ring(o, i);
    rect(ctx, o.x - 2, o.y - 2, o.w + 4, o.h + 4, null, paired ? colors.ink1 : on ? colors.highlight : colors.ink3, paired ? 2.5 : on ? 2 : 1);
  });
  ctx.restore();
}
/** the piece under the pointer in the two columns: { g, side }, side null for a one-molecule scaffold */
function pieceAt(b, P, p) {
  if (!p) return null;
  const x = (p.x - b.x0) / b.sc, y = (p.y - b.y0) / b.sc;
  for (const o of P.outlines) if (x >= o.x - 2 && x <= o.x + o.w + 2 && y >= o.y - 2 && y <= o.y + o.h + 2) return { g: o.g, side: o.side };
  for (let k = N - GRID.nSingles; k < N; k++) { const [cx, cy] = P.pos[k]; if (x >= cx && x < cx + PITCH && y >= cy && y < cy + PITCH) return { g: GRID.groupOf[k], side: null }; }
  return null;
}

/** paint every cell; fillOf(k) gives its colour, ringed groups get a highlight frame */
function drawGrid(ctx, colors, b, fillOf, { ring = null, labels = true } = {}) {
  ctx.save(); ctx.translate(b.x0, b.y0); ctx.scale(b.sc, b.sc);
  for (let k = 0; k < N; k++) {
    const [x, y] = GRID.cellAt[k];
    ctx.fillStyle = fillOf(k); ctx.fillRect(x, y, CELL, CELL);
    if (LABELS[k] === "1") { ctx.fillStyle = colors.ink1; ctx.fillRect(x + 1, y + 1, CELL - 2, CELL - 2); }
  }
  for (const bl of GRID.blocks) {
    const on = ring && ring(bl.g);
    rect(ctx, bl.x - 2, bl.y - 2, bl.w + 4, bl.h + 4, null, on ? colors.highlight : colors.ink3, on ? 2 : 1);
  }
  if (labels) {
    const bz = GRID.blockOfGroup.get(NAMED.benzene), em = GRID.blockOfGroup.get(NAMED.empty);
    txt(ctx, colors, S.benzene(GROUPS[NAMED.benzene][0]), bz.x, bz.y + bz.h + 13, { fill: colors.ink2 });
    txt(ctx, colors, S.empty(GROUPS[NAMED.empty][0]), em.x, em.y + em.h + 13, { fill: colors.ink2 });
    for (const band of GRID.bands) txt(ctx, colors, S.band(band), 0, band.y + CAP_H - 6, { fill: colors.ink3 });
  }
  ctx.restore();
}
/** the group under the pointer, or null */
function groupAt(b, p) {
  if (!p) return null;
  const x = (p.x - b.x0) / b.sc, y = (p.y - b.y0) / b.sc;
  for (const bl of GRID.blocks) if (x >= bl.x - 2 && x <= bl.x + bl.w + 2 && y >= bl.y - 2 && y <= bl.y + bl.h + 2) return { g: bl.g, k: null };
  if (y >= GRID.singleTop) {
    for (let k = N - GRID.nSingles; k < N; k++) { const [cx, cy] = GRID.cellAt[k]; if (x >= cx && x < cx + PITCH && y >= cy && y < cy + PITCH) return { g: GRID.groupOf[k], k }; }
  }
  return null;
}

/* ------------------------------------------------------------ molecules */

const BOND = { S: "SINGLE", D: "DOUBLE", T: "TRIPLE", A: "AROMATIC" };
const NODE_R = 8;
function node(ctx, colors, x, y, name, { stroke = null, ink = null } = {}) {
  dot(ctx, x, y, NODE_R, colors.surface);
  dot(ctx, x, y, NODE_R, colors.surface2, stroke ?? colors.ink1, 1.2);
  txt(ctx, colors, name, x, y + 0.5, { font: nodeFont(colors), fill: ink ?? colors.ink1, align: "center", baseline: "middle" });
}
function bond(ctx, p, q, type, colour) {
  const dx = q[0] - p[0], dy = q[1] - p[1], L = Math.hypot(dx, dy) || 1, nx = (-dy / L) * 2.2, ny = (dx / L) * 2.2;
  if (type === "D") { line(ctx, p[0] + nx, p[1] + ny, q[0] + nx, q[1] + ny, colour, 1.3); line(ctx, p[0] - nx, p[1] - ny, q[0] - nx, q[1] - ny, colour, 1.3); }
  else if (type === "T") { line(ctx, p[0], p[1], q[0], q[1], colour, 1.3); line(ctx, p[0] + 1.6 * nx, p[1] + 1.6 * ny, q[0] + 1.6 * nx, q[1] + 1.6 * ny, colour, 1.3); line(ctx, p[0] - 1.6 * nx, p[1] - 1.6 * ny, q[0] - 1.6 * nx, q[1] - 1.6 * ny, colour, 1.3); }
  else if (type === "A") { line(ctx, p[0] + nx, p[1] + ny, q[0] + nx, q[1] + ny, colour, 1.3); line(ctx, p[0] - nx, p[1] - ny, q[0] - nx, q[1] - ny, colour, 1.3, [3, 2.5]); }
  else line(ctx, p[0], p[1], q[0], q[1], colour, 1.3);
}
/** one scale for a pair, so a shared scaffold is drawn the same size in both */
function pairScale(mols, bw, bh) {
  let s = 24;
  for (const m of mols) {
    const xs = m.atoms.map((a) => a[1]), ys = m.atoms.map((a) => a[2]);
    s = Math.min(s, bw / Math.max(Math.max(...xs) - Math.min(...xs), 1e-6), bh / Math.max(Math.max(...ys) - Math.min(...ys), 1e-6));
  }
  return s;
}
/** the whole molecule centred in a box */
function placeBox(m, s, x0, y0, bw, bh) {
  const xs = m.atoms.map((a) => a[1]), ys = m.atoms.map((a) => a[2]);
  const cx = (Math.min(...xs) + Math.max(...xs)) / 2, cy = (Math.min(...ys) + Math.max(...ys)) / 2;
  return m.atoms.map((a) => [x0 + bw / 2 + (a[1] - cx) * s, y0 + bh / 2 + (a[2] - cy) * s]);
}
/** the molecule placed so its SCAFFOLD's centre is at (cx, cy): where the copy lands */
function placeScaffold(m, s, cx, cy) {
  const sc = m.atoms.filter((a) => a[3]);
  const mx = sc.reduce((t, a) => t + a[1], 0) / sc.length, my = sc.reduce((t, a) => t + a[2], 0) / sc.length;
  return m.atoms.map((a) => [cx + (a[1] - mx) * s, cy + (a[2] - my) * s]);
}
const scaffoldHalfW = (m, s) => {
  const sc = m.atoms.filter((a) => a[3]), mx = sc.reduce((t, a) => t + a[1], 0) / sc.length;
  return Math.max(...sc.map((a) => Math.abs(a[1] - mx))) * s + NODE_R;
};
function drawMol(ctx, colors, m, P, { only = false, dimSide = false } = {}) {
  const keep = (i) => !only || m.atoms[i][3];
  const side = (i) => dimSide && !m.atoms[i][3];
  m.bonds.forEach(([i, j, t]) => { if (keep(i) && keep(j)) bond(ctx, P[i], P[j], t, side(i) || side(j) ? colors.ink3 : colors.ink2); });
  m.atoms.forEach((a, i) => { if (keep(i)) node(ctx, colors, P[i][0], P[i][1], a[0], side(i) ? { stroke: colors.ink3, ink: colors.ink3 } : {}); });
}

