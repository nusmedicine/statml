const stepsOf = (stage) => STEPS[stage.split("-")[0]];
/** the settled count: while a press is in flight, the count before it */
const shownStep = (anim, stage) => (anim.n[stage] ?? 0) - (anim.stage === stage && anim.t < 1 ? 1 : 0);
/** the progress of the press in flight on this stage, raw; null when settled */
const inFlight = (anim, stage) => (anim.stage === stage && anim.t < 1 ? anim.t : null);
/* A SWEEP, NOT A FADE: a press colours the cells in the grid's order, each
   switching at once when the sweep reaches it (tween-only-movement). */
const SWEEP_END = 0.85;
const swept = (k, t) => t >= (k / N) * SWEEP_END;

