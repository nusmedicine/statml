/* ------------------------------------------------------------ Scaffold */

function drawScaffold(ctx, colors, w, params, anim, pointer) {
  const fam = params.example, ex = EXAMPLES[fam], stage = stageOf(params);
  const done = shownStep(anim, stage) >= 1, t = inFlight(anim, stage);
  const pressed = done || t != null;
  const lw = leftW(w), BW = lw - 20, BH = 124, tops = [40, 200];
  const s = pairScale(ex, BW - 24, BH - 20);
  const rx = lw + (w - lw) / 2 + 12;
  const mids = tops.map((y) => y + BH / 2), meet = (mids[0] + mids[1]) / 2;
  const ends = fam === "indoles" ? [meet, meet] : mids;
  const nScaf = new Set(ex.map((m) => m.group)).size;
  txt(ctx, colors, S.related, 12, 20, { font: capFont(colors), fill: colors.ink1 });
  txt(ctx, colors, S.scaffoldHead(nScaf), rx, 20, { font: capFont(colors), fill: colors.ink1, align: "center" });

  const left = ex.map((m, k) => placeBox(m, s, 10, tops[k], BW, BH));
  ex.forEach((m, k) => {
    drawMol(ctx, colors, m, left[k], { dimSide: pressed });
    txt(ctx, colors, S.molName(m), 10 + BW / 2, tops[k] + BH + 16, { fill: colors.ink1, align: "center", maxW: BW });
  });

  /* the bracket and arrows land with the copies (nothing moves over a mark in place) */
  if (done) {
    if (fam === "indoles") {
      const xb = lw + 4, half = scaffoldHalfW(ex[0], s);
      line(ctx, xb - 8, mids[0], xb, mids[0], colors.ink1, 1.5); line(ctx, xb, mids[0], xb, mids[1], colors.ink1, 1.5); line(ctx, xb - 8, mids[1], xb, mids[1], colors.ink1, 1.5);
      arrow(ctx, xb, meet, rx - half - 10, meet, colors.ink1);
    } else {
      ex.forEach((m, k) => arrow(ctx, lw - 2, mids[k], rx - scaffoldHalfW(m, s) - 10, mids[k], colors.ink1));
    }
  }
  /* each scaffold's copy moves from its molecule to the right, in its own lane */
  if (pressed) {
    const u = t == null ? 1 : ease(Math.min(1, t / 0.9));
    ex.forEach((m, k) => {
      const from = left[k], to = placeScaffold(m, s, rx, ends[k]);
      drawMol(ctx, colors, m, from.map((p, i) => [lerp(p[0], to[i][0], u), lerp(p[1], to[i][1], u)]), { only: true });
    });
  }
  if (done) {
    const named = fam === "indoles" ? [[ex[0], meet]] : ex.map((m, k) => [m, mids[k]]);
    named.forEach(([m, y]) => {
      const sc = m.atoms.filter((a) => a[3]), my = sc.reduce((q, a) => q + a[2], 0) / sc.length;
      const below = Math.max(...sc.map((a) => (a[2] - my) * s)) + NODE_R + 16;
      txt(ctx, colors, S.scafName(fam, m.group), rx, y + below, { fill: colors.ink1, align: "center", maxW: w - lw - 8 });
    });
  }

  /* the screen as blocks */
  line(ctx, 12, MOL_H, w - 12, MOL_H, colors.grid);
  const b = gridBox(w, MOL_H + 30);
  let kx = keyItem(ctx, colors, 12, MOL_H + 18, colors.surface3, S.active, { active: true });
  txt(ctx, colors, done ? S.fileCapRing : S.fileCap, kx, MOL_H + 19, { fill: done ? colors.ink1 : colors.ink2, maxW: w - kx - 8 });
  const rings = done ? new Set(ex.map((m) => m.group)) : null;
  drawGrid(ctx, colors, b, () => colors.surface3, { ring: rings ? (g) => rings.has(g) : null });
  const hov = groupAt(b, pointer);
  if (hov) hoverLabel(ctx, colors, S.hoverGroup(...GROUPS[hov.g]), pointer.x, pointer.y, w);
}

/* --------------------------------------------------------------- Split */

const partColor = (colors) => [colors.groupA, colors.groupB, colors.holdout];

function drawSplit(ctx, colors, w, params, anim, pointer) {
  const kind = params.split, seed = Number(params.seed), stage = stageOf(params);
  const split = SPLITS[kind][seed], st = STATS[kind][seed];
  const beat = shownStep(anim, stage), t = inFlight(anim, stage);
  const pc = partColor(colors);
  /* the state of cell k: -1 not yet split, 3 held out, else its part */
  /* before Split 80 / 20, the one grid, every cell not yet split */
  const fillOf = () => colors.surface3;

  /* the key names only what is drawn */
  const reached = beat + (t != null ? 1 : 0);
  let x = 12;
  if (reached === 0) x = keyItem(ctx, colors, x, 16, colors.surface3, S.keyNone);
  if (reached >= 1) x = keyItem(ctx, colors, x, 16, pc[0], S.keyTrain);
  if (reached === 1) x = keyItem(ctx, colors, x, 16, colors.ink3, S.keyHeld);
  if (reached >= 2) { x = keyItem(ctx, colors, x, 16, pc[1], S.keyVal); x = keyItem(ctx, colors, x, 16, pc[2], S.keyTest); }
  x = keyItem(ctx, colors, x, 16, colors.surface3, S.active, { active: true });
  const status = reached === 0 ? S.splitStatus[0] : S.splitStatus[Math.min(2, reached)](kind);
  txt(ctx, colors, status, 12, 36, { fill: colors.ink3, maxW: w - 24 });

  const b = gridBox(w, GRID_TOP), P = pairOf(kind, seed);
  if (beat === 0 && t == null) {
    drawGrid(ctx, colors, b, fillOf);
    const hov = groupAt(b, pointer);
    if (hov) hoverLabel(ctx, colors, S.hoverGroup(...GROUPS[hov.g]), pointer.x, pointer.y, w);
  } else if (beat === 0) {
    /* the move: each cell eases from the one grid to its column, held-out cells first */
    const at = (k) => {
      const u = ease(Math.max(0, Math.min(1, (t - P.start[k]) / MOVE.each)));
      const p0 = GRID.cellAt[k], p1 = P.pos[k];
      return [lerp(p0[0], p1[0], u), lerp(p0[1], p1[1], u)];
    };
    drawCells(ctx, colors, b, at, (k) => (t >= P.start[k] ? (split[k] === "0" ? pc[0] : colors.ink3) : colors.surface3));
  } else {
    /* settled in the two columns; Split 50 / 50 colours the held-out column in place */
    const fillCol = (k) => {
      const part = +split[k];
      if (part === 0) return pc[0];
      return beat >= 2 || (t != null && swept(k, t)) ? pc[part] : colors.ink3;
    };
    drawCells(ctx, colors, b, (k) => P.pos[k], fillCol);
    const hov = t == null ? pieceAt(b, P, pointer) : null;
    drawPairFrame(ctx, colors, b, P, { pairG: hov && hov.side != null ? hov.g : null });
    /* cell 30's figure, once all three parts exist */
    if (beat >= 2) drawBars(ctx, colors, w, GRID_TOP + P.h * b.sc + 22, st, pc);
    if (hov) {
      const [n, a] = GROUPS[hov.g], pr = partsOf(kind, seed)[hov.g];
      hoverLabel(ctx, colors, beat >= 2 ? S.hoverParts(n, a, pr) : S.hoverPair(n, a, pr[0], pr[1] + pr[2]), pointer.x, pointer.y, w);
    }
  }
}

function drawBars(ctx, colors, w, top, st, pc) {
  const pw = Math.min(150, (w - 70) / 3 - 18), ph = 72, gap = (w - 52 - 3 * pw) / 2;
  for (let p = 0; p < 3; p++) {
    /* the title clear of a tall bar's share above it (the overlap sweep: "Validation" × "95.6%") */
    const x0 = 46 + p * (pw + gap), y0 = top + 28, share = st.act[p] / st.n[p];
    txt(ctx, colors, S.barTitle[p], x0 + pw / 2, top + 8, { font: capFont(colors), fill: colors.ink1, align: "center" });
    line(ctx, x0, y0, x0, y0 + ph, colors.axis); line(ctx, x0, y0 + ph, x0 + pw, y0 + ph, colors.axis);
    if (p === 0) {
      txt(ctx, colors, "1", x0 - 5, y0 + 4, { fill: colors.ink3, align: "right" });
      txt(ctx, colors, "0", x0 - 5, y0 + ph + 3, { fill: colors.ink3, align: "right" });
      ctx.save(); ctx.translate(x0 - 22, y0 + ph / 2); ctx.rotate(-Math.PI / 2);
      txt(ctx, colors, S.barY, 0, 0, { fill: colors.ink3, align: "center" }); ctx.restore();
    }
    [1 - share, share].forEach((v, lab) => {
      const bw = Math.min(40, pw * 0.3), bx = x0 + pw * (lab === 0 ? 0.28 : 0.72) - bw / 2, bh = v * ph;
      rect(ctx, bx, y0 + ph - bh, bw, bh, pc[p]);
      txt(ctx, colors, pct(v), bx + bw / 2, y0 + ph - bh - 4, { fill: colors.ink1, align: "center" });
      txt(ctx, colors, String(lab), bx + bw / 2, y0 + ph + 13, { fill: colors.ink3, align: "center" });
    });
  }
  txt(ctx, colors, S.barX, w / 2, top + 28 + ph + 28, { fill: colors.ink3, align: "center" });
}

/* ------------------------------------------------------------ Evaluate */

const F1 = SEEDS.flatMap((s) => [STATS.label[s].f1, STATS.scaffold[s].f1]);
const F1_LO = Math.floor(Math.min(...F1) * 10) / 10, F1_HI = Math.ceil(Math.max(...F1) * 10) / 10;
const meanF1 = (kind) => SEEDS.reduce((t, s) => t + STATS[kind][s].f1, 0) / SEEDS.length;

function drawEvaluate(ctx, colors, w, params, anim, pointer) {
  const kind = params.split, seed = Number(params.seed), stage = stageOf(params);
  const split = SPLITS[kind][seed], parts = partsOf(kind, seed);
  const beat = shownStep(anim, stage), t = inFlight(anim, stage), pc = partColor(colors);
  const P = pairOf(kind, seed);
  /* the test set is the subject: validation washed back; Train keeps its colour, it is what test is compared with */
  const fillOf = (k) => { const p = +split[k]; return p === 1 ? wash(pc[1], 0.35) : pc[p]; };
  const sharedGroup = (g) => parts[g][2] > 0 && parts[g][0] > 0;
  /* Compare rings both pieces of every shared scaffold, in the columns' order, as a sweep */
  const ringOn = beat >= 1 ? (o) => sharedGroup(o.g) : t != null ? (o, i) => sharedGroup(o.g) && t >= (i / P.outlines.length) * SWEEP_END : null;

  let x = 12;
  x = keyItem(ctx, colors, x, 16, pc[0], S.keyTrain);
  x = keyItem(ctx, colors, x, 16, wash(pc[1], 0.35), S.keyVal);
  x = keyItem(ctx, colors, x, 16, pc[2], S.keyTest);
  x = keyItem(ctx, colors, x, 16, colors.surface3, S.active, { active: true });
  txt(ctx, colors, beat >= 1 || t != null ? S.evStatus[1] : S.evStatus[0](kind), 12, 36, { fill: beat >= 1 || t != null ? colors.ink1 : colors.ink3, maxW: w - 24 });

  const b = gridBox(w, GRID_TOP);
  drawCells(ctx, colors, b, (k) => P.pos[k], fillOf);
  const hov = pieceAt(b, P, pointer);
  drawPairFrame(ctx, colors, b, P, { ring: ringOn, pairG: hov && hov.side != null ? hov.g : null });

  /* under the columns as drawn: a grid scaled to a narrow canvas left a gap above the chart */
  drawScores(ctx, colors, w, GRID_TOP + P.h * b.sc + 22, params, anim);

  if (hov) { const [n, a] = GROUPS[hov.g]; hoverLabel(ctx, colors, S.hoverParts(n, a, parts[hov.g]), pointer.x, pointer.y, w); }
}

/* each split's column fills when ITS Score lands, and stays: the comparison
   is between the two columns, so a column scored earlier is kept */
function drawScores(ctx, colors, w, top, params, anim) {
  const x0 = 52, pw = w - x0 - 20, y0 = top + 26, ph = SCORE_H - 62;
  const sy = (v) => y0 + ph - ((v - F1_LO) / (F1_HI - F1_LO)) * ph;
  txt(ctx, colors, S.scoreHead, 12, top + 10, { font: capFont(colors), fill: colors.ink1, maxW: w - 24 });
  line(ctx, x0, y0, x0, y0 + ph, colors.axis);
  for (let v = F1_LO; v <= F1_HI + 1e-9; v += 0.1) {
    line(ctx, x0 - 4, sy(v), x0, sy(v), colors.axis);
    txt(ctx, colors, v.toFixed(1), x0 - 6, sy(v) + 3, { fill: colors.ink3, align: "right" });
  }
  ["label", "scaffold"].forEach((k, c) => {
    const cx = x0 + pw * (c === 0 ? 0.27 : 0.68), cur = k === params.split, st = `evaluate-${k}`;
    const n = shownStep(anim, st), tf = inFlight(anim, st);
    const ink = cur ? colors.ink1 : colors.ink3;
    txt(ctx, colors, S.colName[k], cx, y0 + ph + 18, { fill: ink, align: "center", font: cur ? `600 ${colors.fsXs} ${colors.font}` : null });
    /* dots appear one a seed while Score is in flight */
    const shown = n >= 2 ? SEEDS.length : n === 1 && tf != null ? Math.floor(SEEDS.length * Math.min(1, tf / SWEEP_END)) : 0;
    const dx = 9, xL = cx - ((SEEDS.length - 1) * dx) / 2;
    SEEDS.slice(0, shown).forEach((s, i) => {
      const v = STATS[k][s].f1;
      dot(ctx, xL + i * dx, sy(v), 3.2, ink);
      if (s === Number(params.seed) && cur) dot(ctx, xL + i * dx, sy(v), 6.5, null, colors.highlight, 2);
    });
    if (n >= 2) {
      const m = meanF1(k), half = ((SEEDS.length - 1) * dx) / 2 + 8;
      line(ctx, cx - half, sy(m), cx + half, sy(m), ink, 1.5);
      txt(ctx, colors, S.meanTag(m.toFixed(2)), cx + half + 6, sy(m) + 3, { fill: ink });
    }
  });
}

