    stepLabel: S.stepLabel,
    stepTitle: S.stepTitle,
    /* one press a page, read once: Step alone (play-only-for-motion-or-repetition) */
    runLabel: null,

    init: ({ params, fromScratch }) => {
      const anim = { stage: params.page, n: {} };
      anim.n[params.page] = fromScratch ? 0 : clamp(Number(params.shown) || 0, 0, 1);
      anim.done = anim.n[params.page] >= 1;
      return anim;
    },
