/* a token colour as [r, g, b], for an image's pixels */
const rgbCache = new Map();
function rgbOf(col) {
  if (rgbCache.has(col)) return rgbCache.get(col);
  const c = document.createElement("canvas"); c.width = c.height = 1;
  const g = c.getContext("2d"); g.fillStyle = col; g.fillRect(0, 0, 1, 1);
  const d = g.getImageData(0, 0, 1, 1).data, out = [d[0], d[1], d[2]];
  rgbCache.set(col, out);
  return out;
}
/* a 28x28 image as a small canvas: each pixel `ink` at its intensity, the hidden ones in --c-unknown.
   Cached by image and colours, since draw() runs on every pointer move. */
const imgCache = new Map();
function imageCanvas(key, px, ink, hiddenCol = null, hidden = null) {
  const id = `${key}|${ink}|${hiddenCol}`;
  if (imgCache.has(id)) return imgCache.get(id);
  const c = document.createElement("canvas"); c.width = c.height = 28;
  const g = c.getContext("2d"), im = g.createImageData(28, 28);
  const [r, gg, b] = rgbOf(ink), hc = hiddenCol ? rgbOf(hiddenCol) : null;
  for (let i = 0; i < 784; i++) {
    const o = 4 * i;
    if (hidden && hidden[i]) { im.data[o] = hc[0]; im.data[o + 1] = hc[1]; im.data[o + 2] = hc[2]; im.data[o + 3] = 150; }
    else { im.data[o] = r; im.data[o + 1] = gg; im.data[o + 2] = b; im.data[o + 3] = px[i]; }
  }
  g.putImageData(im, 0, 0);
  imgCache.set(id, c);
  return c;
}
/* the masked input filled in: the given pixels light, the hidden ones at the prediction's value */
function filledCanvas(key, given, out, hidden, inkGiven, inkFill) {
  const id = `${key}|${inkGiven}|${inkFill}`;
  if (imgCache.has(id)) return imgCache.get(id);
  const c = document.createElement("canvas"); c.width = c.height = 28;
  const g = c.getContext("2d"), im = g.createImageData(28, 28), a = rgbOf(inkGiven), f = rgbOf(inkFill);
  for (let i = 0; i < 784; i++) { const o = 4 * i, col = hidden[i] ? f : a; im.data[o] = col[0]; im.data[o + 1] = col[1]; im.data[o + 2] = col[2]; im.data[o + 3] = hidden[i] ? out[i] : given[i]; }
  g.putImageData(im, 0, 0);
  imgCache.set(id, c);
  return c;
}
function drawFilled(ctx, colors, key, given, out, hidden, x, y, s) {
  ctx.save(); ctx.fillStyle = colors.surface; ctx.fillRect(x, y, s, s); ctx.imageSmoothingEnabled = false;
  ctx.drawImage(filledCanvas(key, given, out, hidden, colors.ink3, colors.ink1), x, y, s, s); ctx.restore();
  frame(ctx, x, y, s, s, colors.grid);
}
function drawImage(ctx, colors, key, px, x, y, s, { hidden = null, ink = null, ground = true, edge = true, alpha = 1 } = {}) {
  ctx.save();
  if (ground) { ctx.fillStyle = colors.surface; ctx.fillRect(x, y, s, s); }
  ctx.imageSmoothingEnabled = false;
  ctx.globalAlpha = alpha;
  ctx.drawImage(imageCanvas(key, px, ink ?? colors.ink1, hidden ? colors.unknown : null, hidden), x, y, s, s);
  ctx.restore();
  if (edge) frame(ctx, x, y, s, s, colors.grid);
}

/** the 16 numbers of an embedding as bars from a midline, scaled to the row's largest */
function codeBars(ctx, colors, z, x, y, w, h) {
  const n = z.length, bw = w / n, m = Math.max(1e-9, ...z.map(Math.abs)), mid = y + h / 2;
  frame(ctx, x, y, w, h, colors.grid); line(ctx, x + 2, mid, x + w - 2, mid, colors.grid);
  z.forEach((v, i) => {
    const cx = x + i * bw + bw / 2, bh = (v / m) * (h / 2 - 3);
    ctx.fillStyle = colors.ink2; ctx.fillRect(cx - bw / 2 + 1.5, bh >= 0 ? mid - bh : mid, bw - 3, Math.max(1, Math.abs(bh)));
  });
}

