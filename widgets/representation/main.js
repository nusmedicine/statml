function line(ctx, x1, y1, x2, y2, col, w = 1, dash = null) {
  ctx.save(); ctx.strokeStyle = col; ctx.lineWidth = w; if (dash) ctx.setLineDash(dash);
  ctx.beginPath(); ctx.moveTo(x1, y1); ctx.lineTo(x2, y2); ctx.stroke(); ctx.restore();
}
function frame(ctx, x, y, w, h, col, lw = 1, dash = null) {
  ctx.save(); ctx.strokeStyle = col; ctx.lineWidth = lw; if (dash) ctx.setLineDash(dash); ctx.strokeRect(x + 0.5, y + 0.5, w - 1, h - 1); ctx.restore();
}
function arrow(ctx, colors, x0, y, x1) {
  line(ctx, x0, y, x1 - 5, y, colors.ink3, 1.2);
  ctx.save(); ctx.fillStyle = colors.ink3; ctx.beginPath(); ctx.moveTo(x1, y); ctx.lineTo(x1 - 7, y - 4); ctx.lineTo(x1 - 7, y + 4); ctx.closePath(); ctx.fill(); ctx.restore();
}
function hoverLabel(ctx, colors, str, x, y, w) {
  ctx.save(); ctx.font = `600 ${colors.fsXs} ${colors.font}`;
  const tw = ctx.measureText(str).width; ctx.restore();
  const bx = Math.max(4, Math.min(w - tw - 14, x + 10)), by = Math.max(4, y - 26);
  ctx.save(); ctx.fillStyle = colors.surface; ctx.fillRect(bx, by, tw + 10, 18);
  ctx.strokeStyle = colors.ink3; ctx.strokeRect(bx + 0.5, by + 0.5, tw + 9, 17); ctx.restore();
  txt(ctx, colors, str, bx + 5, by + 9.5, { size: colors.fsXs, fill: colors.ink1, baseline: "middle", weight: "600" });
}
/** words laid into lines no wider than `maxW`, `lh` apart; returns the line count */
function wrapText(ctx, colors, str, x, y, maxW, lh, opts = {}) {
  ctx.save(); ctx.font = `${opts.weight ? opts.weight + " " : ""}${opts.size ?? colors.fsSm} ${colors.font}`;
  const lines = []; let cur = "";
  for (const word of str.split(" ")) {
    const tryLine = cur ? `${cur} ${word}` : word;
    if (ctx.measureText(tryLine).width > maxW && cur) { lines.push(cur); cur = word; } else cur = tryLine;
  }
  if (cur) lines.push(cur);
  ctx.restore();
  lines.forEach((l, i) => txt(ctx, colors, l, x, y + i * lh, { fill: colors.ink2, ...opts }));
  return lines.length;
}

/* a token colour as [r, g, b], for an image's pixels */
const rgbCache = new Map();
function rgbOf(col) {
  if (rgbCache.has(col)) return rgbCache.get(col);
  const c = document.createElement("canvas"); c.width = c.height = 1;
  const g = c.getContext("2d"); g.fillStyle = col; g.fillRect(0, 0, 1, 1);
  const d = g.getImageData(0, 0, 1, 1).data, out = [d[0], d[1], d[2]];
  rgbCache.set(col, out);
  return out;
}
/* a 28x28 image as a small canvas: each pixel ink at its intensity, the hidden ones in --c-unknown.
   Cached by image, colours and mask, since draw() runs on every pointer move. */
const imgCache = new Map();
function imageCanvas(key, px, ink, hiddenCol = null, hidden = null) {
  const id = `${key}|${ink}|${hiddenCol}`;
  if (imgCache.has(id)) return imgCache.get(id);
  const c = document.createElement("canvas"); c.width = c.height = 28;
  const g = c.getContext("2d"), im = g.createImageData(28, 28);
  const [r, gg, b] = rgbOf(ink), hc = hiddenCol ? rgbOf(hiddenCol) : null;
  for (let i = 0; i < 784; i++) {
    const o = 4 * i;
    if (hidden && hidden[i]) { im.data[o] = hc[0]; im.data[o + 1] = hc[1]; im.data[o + 2] = hc[2]; im.data[o + 3] = 150; }
    else { im.data[o] = r; im.data[o + 1] = gg; im.data[o + 2] = b; im.data[o + 3] = px[i]; }
  }
  g.putImageData(im, 0, 0);
  imgCache.set(id, c);
  return c;
}
function drawImage(ctx, colors, key, px, x, y, s, hidden = null) {
  ctx.save(); ctx.fillStyle = colors.surface; ctx.fillRect(x, y, s, s);
  ctx.imageSmoothingEnabled = false;
  ctx.drawImage(imageCanvas(key, px, colors.ink1, hidden ? colors.unknown : null, hidden), x, y, s, s);
  ctx.restore();
  frame(ctx, x, y, s, s, colors.grid);
}
function emptyBox(ctx, colors, x, y, w, h) { frame(ctx, x, y, w, h, colors.grid, 1, [3, 3]); }

/** the 16 numbers of an embedding as bars from a midline, scaled to the row's largest; a 0 is a dot on the line */
function codeBars(ctx, colors, z, x, y, w, h) {
  const n = z.length, bw = w / n, m = Math.max(1e-9, ...z.map(Math.abs)), mid = y + h / 2;
  frame(ctx, x, y, w, h, colors.grid); line(ctx, x + 2, mid, x + w - 2, mid, colors.grid);
  z.forEach((v, i) => {
    const cx = x + i * bw + bw / 2;
    if (Math.abs(v) < 1e-6) { ctx.save(); ctx.fillStyle = colors.ink3; ctx.beginPath(); ctx.arc(cx, mid, 1.6, 0, Math.PI * 2); ctx.fill(); ctx.restore(); return; }
    const bh = (v / m) * (h / 2 - 3);
    ctx.fillStyle = colors.ink2; ctx.fillRect(cx - bw / 2 + 1.5, bh >= 0 ? mid - bh : mid, bw - 3, Math.max(1, Math.abs(bh)));
  });
}

/** view-similarity matrix: ink at the similarity, the diagonal (matched pairs) in --c-reference, the chosen digit's row in --c-highlight */
function simMatrix(ctx, colors, Sm, x, y, s, digit) {
  const n = Sm.length, c = s / n;
  ctx.save(); ctx.fillStyle = colors.surface; ctx.fillRect(x, y, s, s); ctx.restore();
  for (let i = 0; i < n; i++) for (let j = 0; j < n; j++) {
    ctx.save(); ctx.globalAlpha = clamp(Sm[i][j], 0, 1); ctx.fillStyle = colors.ink1; ctx.fillRect(x + j * c, y + i * c, c, c); ctx.restore();
  }
  for (let i = 0; i < n; i++) frame(ctx, x + i * c, y + i * c, c, c, colors.reference, 1.6);
  frame(ctx, x, y + digit * c, s, c, colors.highlight, 1.6);
  frame(ctx, x, y, s, s, colors.grid);
}

