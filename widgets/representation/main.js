/** the training loss per 10 batches, log scale, drawn up to the checkpoint shown; a dot at each checkpoint passed */
function drawCurve(ctx, colors, R, page, k, e = 0) {
  const L = CHECK[page].curve, n = L.length, lo = Math.min(...L), hi = Math.max(...L);
  txt(ctx, colors, S.curveHead, R.x, R.y - 7, { size: colors.fsXs, fill: k >= 0 ? colors.ink1 : colors.ink3, weight: "600" });
  frame(ctx, R.x, R.y, R.w, R.h, colors.grid);
  /* batches on a log axis from 5 (the first checkpoint after 0) to the last: the checkpoints are spaced that way */
  const l0 = Math.log(5), l1 = Math.log(n * 10), X = (b) => R.x + 3 + ((Math.log(Math.max(5, b)) - l0) / (l1 - l0)) * (R.w - 6);
  const Y = (v) => R.y + R.h - 3 - ((Math.log(v) - Math.log(lo)) / (Math.log(hi) - Math.log(lo) || 1)) * (R.h - 6);
  for (const [b, lab] of S.ticks) {
    const x = X(b);
    line(ctx, x, R.y + R.h, x, R.y + R.h + 3, colors.axis);
    txt(ctx, colors, lab, x, R.y + R.h + 13, { size: colors.fsXs, fill: colors.ink3, align: b === 4690 ? "right" : "center" });
  }
  if (k < 0) { txt(ctx, colors, S.curveWait, R.x + R.w / 2, R.y + R.h / 2 + 4, { size: colors.fsXs, fill: colors.ink3, align: "center" }); return; }
  /* the line's end moves from this checkpoint toward the next, evenly on the log axis */
  const upto = k < NCK - 1 && e > 0 ? Math.exp(lerp(Math.log(Math.max(5, STEPS[k])), Math.log(STEPS[k + 1]), e)) : STEPS[k];
  ctx.save(); ctx.strokeStyle = colors.ink2; ctx.lineWidth = 1.3; ctx.beginPath();
  let started = false;
  for (let i = 0; i < n && (i + 1) * 10 <= Math.max(upto, 10); i++) { const x = X((i + 1) * 10), y = Y(L[i]); if (started) ctx.lineTo(x, y); else { ctx.moveTo(x, y); started = true; } }
  ctx.stroke(); ctx.restore();
  if (e > 0) {
    const i = Math.min(n - 1, Math.max(0, Math.round(upto / 10) - 1));
    ctx.save(); ctx.fillStyle = colors.ink1; ctx.beginPath(); ctx.arc(X(upto), Y(L[i]), 3.2, 0, Math.PI * 2); ctx.fill(); ctx.restore();
  }
  for (let j = 1; j <= k; j++) {
    const i = Math.min(n - 1, Math.max(0, Math.round(STEPS[j] / 10) - 1));
    ctx.save(); ctx.fillStyle = colors.ink1; ctx.beginPath(); ctx.arc(X(STEPS[j]), Y(L[i]), j === k && e === 0 ? 3.2 : 2, 0, Math.PI * 2); ctx.fill(); ctx.restore();
  }
}

/** a map: `frame_` the checkpoint drawn (null: not yet), `title` above it, `num` the 5-NN under it (null: none) */
function drawMap(ctx, colors, P, page, frame_, title, num, digit, pointer) {
  const on = frame_ != null;
  txt(ctx, colors, title, P.x, P.y - 7, { size: colors.fsXs, fill: on ? colors.ink1 : colors.ink3, weight: "600" });
  if (!on) {
    emptyBox(ctx, colors, P.x, P.y, P.s, P.s);
    txt(ctx, colors, S.mapWait, P.x + P.s / 2, P.y + P.s / 2, { size: colors.fsXs, fill: colors.ink3, align: "center" });
    return null;
  }
  frame(ctx, P.x, P.y, P.s, P.s, colors.grid);
  const px = mapPx(P, page, frame_);
  ctx.save(); ctx.globalAlpha = 0.4; ctx.fillStyle = colors.ink3;
  for (let i = 0; i < N_MAP; i++) if (LAB[i] !== digit) { ctx.beginPath(); ctx.arc(px[2 * i], px[2 * i + 1], 1.4, 0, Math.PI * 2); ctx.fill(); }
  ctx.restore();
  ctx.save(); ctx.fillStyle = colors.highlight;
  for (let i = 0; i < N_MAP; i++) if (LAB[i] === digit) { ctx.beginPath(); ctx.arc(px[2 * i], px[2 * i + 1], 2, 0, Math.PI * 2); ctx.fill(); }
  ctx.restore();
  if (num != null) txt(ctx, colors, S.mapNum(num), P.x + P.s, P.y + P.s + 15, { size: colors.fsXs, fill: colors.ink1, align: "right" });
  return nearest(px, pointer, P);
}
function nearest(px, pointer, P) {
  if (!pointer || pointer.x < P.x || pointer.x > P.x + P.s || pointer.y < P.y || pointer.y > P.y + P.s) return null;
  let best = -1, bd = 36;
  for (let i = 0; i < N_MAP; i++) { const dd = (px[2 * i] - pointer.x) ** 2 + (px[2 * i + 1] - pointer.y) ** 2; if (dd < bd) { bd = dd; best = i; } }
  return best >= 0 ? best : null;
}

function captionOf(page, anim) {
  const n = pressesOf(anim, page), C = S.cap[page];
  if (playingOn(anim, page)) return C.play(ckOf(anim, page));
  if (page === "contrastive") return C[Math.min(n, 3)]();
  return n >= 1 ? C.after() : C.before();
}

