const PAD = 10;
function layoutOf(w) {
  const S0 = Math.round(clamp(w * 0.085, 40, 58));
  const top = 18, r1 = top, r2 = top + S0 + 10, stripEnd = r2 + S0;
  const gap = 14, ms = Math.floor((w - 2 * PAD - gap) / 2);
  const mapsTop = stripEnd + 46;
  const A = { x: PAD, y: mapsTop, s: ms }, B = { x: PAD + ms + gap, y: mapsTop, s: ms };
  const capTop = mapsTop + ms + 36;
  return { S: S0, r1, r2, stripEnd, A, B, capTop, height: capTop + 4 * 16 + 4 };
}

/* the map's points in canvas pixels, one array per map */
function mapPx(P, page, which) {
  const xy = XY[page][which], m = 6, s = P.s - 2 * m, out = new Float32Array(xy.length);
  for (let i = 0; i < N_MAP; i++) { out[2 * i] = P.x + m + xy[2 * i] * s; out[2 * i + 1] = P.y + m + (1 - xy[2 * i + 1]) * s; }
  return out;
}

