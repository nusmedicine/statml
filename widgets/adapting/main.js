const PAD = 12;
const pct = (v) => `${Math.round(100 * v)}%`;
const cap = (c) => `600 ${c.fsSm} ${c.font}`;
const small = (c) => `${c.fsXs} ${c.font}`;
const smallBold = (c) => `600 ${c.fsXs} ${c.font}`;
const body = (c) => `${c.fsSm} ${c.font}`;
const ease = (t) => (t < 0.5 ? 2 * t * t : 1 - 2 * (1 - t) * (1 - t));
function txt(ctx, s, x, y, { font, fill, align = "left", baseline = "middle" }) {
  ctx.save(); ctx.font = font; ctx.fillStyle = fill; ctx.textAlign = align; ctx.textBaseline = baseline; ctx.fillText(s, x, y); ctx.restore();
}
const textW = (ctx, font, s) => { ctx.save(); ctx.font = font; const w = ctx.measureText(s).width; ctx.restore(); return w; };
function line(ctx, pts, stroke, lw = 1, dash = null) {
  ctx.save(); ctx.strokeStyle = stroke; ctx.lineWidth = lw; if (dash) ctx.setLineDash(dash);
  ctx.beginPath(); pts.forEach(([x, y], i) => (i ? ctx.lineTo(x, y) : ctx.moveTo(x, y))); ctx.stroke(); ctx.restore();
}
/** a row of tokens; `box(i)` fills a token's background, `under(i)` writes a line beneath it */
function tokenRow(ctx, c, toks, x, y, { box = () => null, under = () => null } = {}) {
  let cx = x;
  toks.forEach((t, i) => {
    const w0 = textW(ctx, body(c), t), u0 = under(i), w = u0 ? Math.max(w0, textW(ctx, small(c), u0)) : w0, b = box(i);
    if (b) { ctx.fillStyle = b; ctx.fillRect(cx - 3, y - 10, w + 6, 20); }
    txt(ctx, t, cx + (w - w0) / 2, y, { font: body(c), fill: c.ink1 });
    if (u0) txt(ctx, u0, cx + w / 2, y + 17, { font: small(c), fill: c.reference, align: "center" });
    cx += w + 10;
  });
}
function axisY(ctx, c, x, y0, h, ticks, at) {
  for (const v of ticks) {
    const y = at(v); line(ctx, [[x, y], [x + 0, y]], c.grid);
    txt(ctx, pct(v), x - 6, y, { font: small(c), fill: c.ink3, align: "right" });
  }
}

