const sx = (ch, s) => ch.x + ch.w * Math.sqrt(s / LAST);

function drawPretraining(ctx, c, w, pg) {
  /* 1 · the targets */
  txt(ctx, S.maskedHead, PAD, 16, { font: cap(c), fill: c.ink1 });
  TABLE.masked.forEach((m, i) => tokenRow(ctx, c, m.tokens.map((t, j) => (m.hidden.includes(j) ? "[MASK]" : t)), PAD + 8, 44 + i * 38,
    { box: (j) => (m.hidden.includes(j) ? c.surface3 : null), under: (j) => (m.hidden.includes(j) ? m.tokens[j] : null) }));
  txt(ctx, S.maskedNote, PAD, 160, { font: small(c), fill: c.ink3 });

  /* 2 · the probe: what a press shows switches at once; the line draws out */
  const k = pg.n - 1, at = k >= 0 ? PRE.find((r) => r.step === PRESS[k]) : null;
  txt(ctx, S.probeHead(at ? at.step : null), PAD, 196, { font: cap(c), fill: c.ink1 });
  tokenRow(ctx, c, PROBE, PAD + 8, 224, { box: (j) => (PROBE[j] === "[MASK]" ? c.surface3 : null) });
  if (!at) txt(ctx, S.probeWait, PAD + 8, 264, { font: body(c), fill: c.ink2 });
  else {
    txt(ctx, S.probeNote, w - PAD, 224, { font: small(c), fill: c.ink3, align: "right" });
    const bx = PAD + 118, bw = w - 2 * PAD - 170;
    at.top.forEach(([t, p], i) => {
      const y = 252 + i * 18;
      txt(ctx, t, bx - 8, y, { font: body(c), fill: c.ink1, align: "right" });
      ctx.fillStyle = c.empirical; ctx.fillRect(bx, y - 6, Math.max(1, bw * p), 12);
      txt(ctx, p.toFixed(2), bx + bw * p + 6, y, { font: small(c), fill: c.ink2 });
    });
  }

  /* 3 · held-out accuracy, the line through every checkpoint passed */
  const ch = preChart(w), Y = (v) => ch.y + ch.h - v * ch.h;
  txt(ctx, S.accHead, PAD, ch.y - 22, { font: cap(c), fill: c.ink1 });
  for (const v of [0, 0.5, 1]) { line(ctx, [[ch.x, Y(v)], [ch.x + ch.w, Y(v)]], c.grid); txt(ctx, pct(v), ch.x - 6, Y(v), { font: small(c), fill: c.ink3, align: "right" }); }
  for (const s of [0, 100, 500, 1000, 3000]) txt(ctx, s.toLocaleString("en-US"), sx(ch, s), ch.y + ch.h + 12, { font: small(c), fill: c.ink3, align: "center" });
  txt(ctx, S.accAxis, ch.x + ch.w, ch.y + ch.h + 28, { font: small(c), fill: c.ink3, align: "right" });
  if (at) {
    const from = k > 0 ? PRESS[k - 1] : 0, cut = sx(ch, from) + (sx(ch, at.step) - sx(ch, from)) * ease(pg.t);
    const pts = PRE.filter((r) => r.step <= at.step).map((r) => [sx(ch, r.step), Y(r.mlm)]);
    const drawn = []; let end = pts[0];
    for (let i = 0; i < pts.length; i++) {
      if (pts[i][0] <= cut) { drawn.push(pts[i]); end = pts[i]; continue; }
      const a = pts[i - 1], b = pts[i], f = (cut - a[0]) / (b[0] - a[0]);
      end = [cut, a[1] + (b[1] - a[1]) * f]; drawn.push(end); break;
    }
    line(ctx, drawn, c.empirical, 2);
    ctx.fillStyle = c.empirical; ctx.beginPath(); ctx.arc(end[0], end[1], 4, 0, 2 * Math.PI); ctx.fill();
    if (pg.t >= 1) txt(ctx, pct(at.mlm), end[0] + 8, end[1] - 10, { font: smallBold(c), fill: c.ink1 });
  }
  txt(ctx, at ? S.preLine(k, at) : "", PAD, PRE_H - 14, { font: body(c), fill: c.ink2 });
}

function drawAdapting(ctx, c, w, params, state, pg) {
  /* 1 · the labelled notes */
  txt(ctx, S.notesHead(params.notes), PAD, 16, { font: cap(c), fill: c.ink1 });
  state.notes.forEach(([t, y], i) => {
    const yy = 44 + i * 24, lab = `${y} ${LABELS[params.task][y]}`;
    ctx.save(); ctx.strokeStyle = c.ink3; ctx.strokeRect(PAD + 8.5, yy - 9.5, 92, 19); ctx.restore();
    txt(ctx, lab, PAD + 54, yy, { font: small(c), fill: c.ink1, align: "center" });
    txt(ctx, t, PAD + 112, yy, { font: body(c), fill: c.ink1 });
  });
  txt(ctx, S.notesNote, PAD, 146, { font: small(c), fill: c.ink3 });

  /* 2 · his adapt figure, a column a way */
  txt(ctx, S.waysHead, PAD, 182, { font: cap(c), fill: c.ink1 });
  const colW = (w - 2 * PAD) / 3, bw = Math.min(118, colW - 46), top = 206, bbH = 64, hdH = 22;
  WAYS.forEach((way, i) => {
    const col = c[way.color], x = PAD + i * colW + 34, n = TABLE.trains[way.key], backT = way.key === "full";
    txt(ctx, way.name, x + bw / 2, top, { font: smallBold(c), fill: c.ink1, align: "center" });
    const by = top + 14;
    ctx.fillStyle = backT ? col : c.surface3; ctx.fillRect(x, by, bw, bbH);
    txt(ctx, S.backbone, x + bw / 2, by + 18, { font: smallBold(c), fill: backT ? c.surface : c.ink2, align: "center" });
    txt(ctx, backT ? BACKBONE.toLocaleString("en-US") : `${BACKBONE.toLocaleString("en-US")} ${S.frozen}`, x + bw / 2, by + 34,
      { font: small(c), fill: backT ? c.surface : c.ink3, align: "center" });
    if (way.key === "lora") [0, 1].forEach((j) => {
      const lw = (bw - 24) / 2, lx = x + 8 + j * (lw + 8);
      ctx.fillStyle = col; ctx.fillRect(lx, by + bbH - 18, lw, 13);
      txt(ctx, S.lora, lx + lw / 2, by + bbH - 11.5, { font: small(c), fill: c.surface, align: "center" });
    });
    const hy = by + bbH + 4;
    ctx.fillStyle = col; ctx.fillRect(x, hy, bw, hdH);
    txt(ctx, S.head, x + bw / 2, hy + hdH / 2, { font: smallBold(c), fill: c.surface, align: "center" });
    /* the Trainable bracket, his figure's */
    const t0 = backT ? by : way.key === "lora" ? by + bbH - 20 : hy, t1 = hy + hdH;
    line(ctx, [[x - 6, t0], [x - 11, t0], [x - 11, t1], [x - 6, t1]], c.ink1, 1.5);
    ctx.save(); ctx.translate(x - 19, (t0 + t1) / 2); ctx.rotate(-Math.PI / 2);
    txt(ctx, S.trainable, 0, 0, { font: smallBold(c), fill: c.ink1, align: "center" }); ctx.restore();
    txt(ctx, S.trains(n), x + bw / 2, t1 + 14, { font: smallBold(c), fill: col, align: "center" });
    const p = n / (BACKBONE + n - (backT ? BACKBONE : 0));
    txt(ctx, S.share(p < 0.01 ? `${(100 * p).toFixed(1)}%` : pct(p)), x + bw / 2, t1 + 28, { font: small(c), fill: c.ink3, align: "center" });
  });
  const sy = top + 14 + 64 + 4 + 22 + 50;
  line(ctx, [[PAD + 8, sy], [PAD + 26, sy]], c.reference, 2, [5, 3]);
  txt(ctx, S.scratchNote(TABLE.trains.scratch), PAD + 32, sy, { font: small(c), fill: c.ink2 });

  /* 3 · the curves, grown by the Train press */
  const ch = adaptChart(w), Y = (v) => ch.y + ch.h - ((v - 0.4) / 0.6) * ch.h, X = (i) => ch.x + ch.w * i / POINTS;
  txt(ctx, S.curveHead(params.notes), PAD, ch.y - 24, { font: cap(c), fill: c.ink1 });
  for (const v of [0.4, 0.6, 0.8, 1]) { line(ctx, [[ch.x, Y(v)], [ch.x + ch.w, Y(v)]], c.grid); txt(ctx, pct(v), ch.x - 6, Y(v), { font: small(c), fill: c.ink3, align: "right" }); }
  for (let s = 0; s <= STEPS; s += 100) txt(ctx, String(s), X(s / EVERY), ch.y + ch.h + 12, { font: small(c), fill: c.ink3, align: "center" });
  txt(ctx, S.curveAxis, ch.x + ch.w, ch.y + ch.h + 28, { font: small(c), fill: c.ink3, align: "right" });
  const fy = Y(state.base);
  line(ctx, [[ch.x, fy], [ch.x + ch.w, fy]], c.ink3, 1, [3, 3]);
  txt(ctx, S.floor(params.task, pct(state.base)), ch.x + ch.w, fy + 10, { font: small(c), fill: c.ink3, align: "right" });

  const upto = progress(pg);
  if (upto > 0) {
    const ends = [];
    for (const way of [...WAYS, SCRATCH]) {
      const cv = state.run[way.key], last = Math.floor(upto), f = upto - last;
      const pts = cv.slice(0, last + 1).map((v, i) => [X(i), Y(v)]);
      if (f > 0 && last < POINTS) pts.push([X(last + f), Y(cv[last] + (cv[last + 1] - cv[last]) * f)]);
      line(ctx, pts, c[way.color], 2, way === SCRATCH ? [5, 3] : null);
      const e = pts[pts.length - 1]; ends.push({ x: e[0], y: e[1], v: cv[Math.min(POINTS, Math.round(upto))], way });
    }
    ends.sort((a, b) => a.y - b.y);
    for (let i = 1; i < ends.length; i++) ends[i].y = Math.max(ends[i].y, ends[i - 1].y + 13);
    for (const e of ends) txt(ctx, `${pct(e.v)} ${e.way.short}`, e.x + 6, e.y, { font: smallBold(c), fill: c[e.way.color] });
  }
  txt(ctx, S.adaptLine(pg.n > 0 && pg.t >= 1, params.task, state.run, state.base), PAD, ADAPT_H - 14, { font: body(c), fill: c.ink2 });
}

/* ============================================================ animation */

const MAX = { pretraining: PRESS.length, adapting: 1 };
const MS = { pretraining: 700, adapting: 4000 };
const pageOf = (anim, params) => anim.p[params.page];
/** how far along the 400 steps the curves are, in table points */
const progress = (pg) => (pg.n === 0 ? 0 : POINTS * pg.t);
function settle(anim, params) {
  const pg = pageOf(anim, params);
  anim.key = params.page;
  anim.done = pg.n >= MAX[params.page] && pg.t >= 1;
}

defineWidget({
  slug: "adapting",
  status: "draft",
  title: S.title,
  subtitle: S.subtitle,
  layout: "side",
  height: ({ page }) => (page === "adapting" ? ADAPT_H : PRE_H),

  params: {
    page: { role: "page", type: "segmented", label: S.pageLabel, options: PAGES, default: "pretraining", display: true },
    task: { type: "segmented", label: S.taskLabel, options: TASKS, default: "outcome", when: { param: "page", equals: "adapting" } },
    notes: { type: "choice", label: S.sizeLabel, detail: S.sizeDetail, options: SIZES.map((v) => ({ value: v, label: Number(v).toLocaleString("en-US") })),
      default: "256", when: { param: "page", equals: "adapting" } },
    /* authoring escape hatch, first render only: presses already made on the page opened */
    shown: { type: "int", min: 0, max: 7, default: 0, hidden: true },
  },

  legend: [],

  compute: ({ params }) => ({
    run: TABLE.adapt[params.task][params.notes],
    base: TABLE.base[params.task],
    notes: TABLE.notes[params.task],
  }),

  animation: {
    stepLabel: { param: "page", labels: S.step, default: S.step.pretraining },
    stepTitle: { param: "page", labels: S.stepTitle, default: S.stepTitle.pretraining },
    /* no Play: Pretraining's presses are each read, and Adapting's one press is the whole run (his picks) */
    runLabel: null,
    init: ({ params, fromScratch }) => {
      const anim = { p: { pretraining: { n: 0, t: 1 }, adapting: { n: 0, t: 1 } }, moving: false, halt: false };
      if (!fromScratch) anim.p[params.page].n = Math.max(0, Math.min(MAX[params.page], Number(params.shown) || 0));
      settle(anim, params);
      return anim;
    },
    advance: (anim, { dt, params }) => {
      if (anim.halt) { anim.halt = false; anim.moving = false; settle(anim, params); return false; }
      const pg = pageOf(anim, params);
      let more;
      if (pg.t < 1) { pg.t = Math.min(1, pg.t + dt / MS[params.page]); more = pg.t < 1; }
      else if (pg.n < MAX[params.page]) { pg.n += 1; pg.t = 0; more = true; }
      else more = false;
      anim.moving = more;
      settle(anim, params);
      return more;
    },
    rebuild: (anim, { params }) => {
      /* a press belongs to the page it started on: a switch mid-press finishes it (widget 70's rule) */
      if (anim.moving && params.page !== anim.key) {
        for (const pg of Object.values(anim.p)) pg.t = 1;
        anim.halt = true;
      }
      settle(anim, params);
    },
  },

  draw({ ctx, colors, w, params, state, anim }) {
    const pg = pageOf(anim, params);
    if (params.page === "adapting") drawAdapting(ctx, colors, w, params, state, pg);
    else drawPretraining(ctx, colors, w, pg);
  },

  readout({ params, state, anim }) {
    const pg = pageOf(anim, params);
    if (params.page === "pretraining") {
      const k = pg.t >= 1 ? pg.n - 1 : pg.n - 2, at = k >= 0 ? PRE.find((r) => r.step === PRESS[k]) : null;
      return [
        { label: S.tileStep, value: at ? `${at.step.toLocaleString("en-US")} of ${LAST.toLocaleString("en-US")}` : S.wait, note: S.tileStepNote },
        { label: S.tileMlm, value: at ? pct(at.mlm) : S.wait, note: S.tileMlmNote },
        { label: S.tileTop, value: at ? `${at.top[0][0]} ${at.top[0][1].toFixed(2)}` : S.wait, note: S.tileTopNote },
      ];
    }
    const upto = progress(pg), i = Math.min(POINTS, Math.round(upto));
    return [...WAYS, SCRATCH].map((way) => ({
      label: way.short, value: upto > 0 ? pct(state.run[way.key][i]) : S.wait, note: S.tileWayNote(TABLE.trains[way.key]),
    }));
  },

  summary({ params, anim }) {
    return S.sum(PAGES.find((p) => p.value === params.page).label, pageOf(anim, params).n, MAX[params.page]);
  },
});
