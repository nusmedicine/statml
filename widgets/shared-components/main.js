/* Two blocks on the same samples. In each, the shared axis carries the
   subtype difference (±0.85 plus noise) and is the SMALLER spread; a private
   axis, unrelated to the other block, is the larger (sd 1.6). Measured on the
   draft's seed: PCA keeps ~75% of each block and its scores correlate ~0.2;
   PLS keeps ~25% and they correlate ~0.9. The angles keep the four axes
   apart on screen, so no arrow lies along a feature axis. */
const N_CONCEPT = 80;
const ANG = { a: [62, -28], b: [18, 108] };
const unitAt = (deg) => [Math.cos((deg * Math.PI) / 180), Math.sin((deg * Math.PI) / 180)];

function topEig2(a, b, d) {
  const tr = a + d, det = a * d - b * b, l = tr / 2 + Math.sqrt(Math.max(0, (tr * tr) / 4 - det));
  const v = Math.abs(b) > 1e-12 ? [l - d, b] : a >= d ? [1, 0] : [0, 1];
  const n = Math.hypot(v[0], v[1]);
  return [v[0] / n, v[1] / n];
}
const project = (X, d) => X.map((p) => p[0] * d[0] + p[1] * d[1]);
const flip = (d) => [-d[0], -d[1]];

function makeConcept(rng) {
  const ua = unitAt(ANG.a[0]), va = unitAt(ANG.a[1]), ub = unitAt(ANG.b[0]), vb = unitAt(ANG.b[1]);
  const g = [], A = [], B = [];
  for (let i = 0; i < N_CONCEPT; i++) {
    const grp = i % 2;
    const s = (grp ? 0.85 : -0.85) + 0.35 * rng.normal();
    const a = 1.6 * rng.normal(), b = 1.6 * rng.normal();
    g.push(grp);
    A.push([0, 1].map((j) => s * ua[j] + a * va[j] + 0.2 * rng.normal()));
    B.push([0, 1].map((j) => s * ub[j] + b * vb[j] + 0.2 * rng.normal()));
  }
  const centre = (X) => { const m = [0, 1].map((j) => mean(X.map((p) => p[j]))); return X.map((p) => [p[0] - m[0], p[1] - m[1]]); };
  const Ac = centre(A), Bc = centre(B);
  const cross = (X, Z) => { const M = [[0, 0], [0, 0]]; X.forEach((x, i) => { for (let r = 0; r < 2; r++) for (let c = 0; c < 2; c++) M[r][c] += x[r] * Z[i][c]; }); return M; };
  const CA = cross(Ac, Ac), CB = cross(Bc, Bc), M = cross(Ac, Bc);
  /* PLS's first pair: the top singular vectors of X₁ᵀX₂ */
  const MMt = [M[0][0] ** 2 + M[0][1] ** 2, M[0][0] * M[1][0] + M[0][1] * M[1][1], M[1][0] ** 2 + M[1][1] ** 2];
  const w1 = topEig2(MMt[0], MMt[1], MMt[2]);
  let w2 = [M[0][0] * w1[0] + M[1][0] * w1[1], M[0][1] * w1[0] + M[1][1] * w1[1]];
  const n2 = Math.hypot(w2[0], w2[1]); w2 = [w2[0] / n2, w2[1] / n2];
  /* Signs: subtype 2 scores positive in PLS block 1; then each method's
     second direction makes its scores correlate positively, and PCA's first
     agrees with PLS's, so a switch of method moves the samples the least. */
  const dirs = { pls: [w1, w2], pca: [topEig2(CA[0][0], CA[0][1], CA[1][1]), topEig2(CB[0][0], CB[0][1], CB[1][1])] };
  const tPls = project(Ac, dirs.pls[0]);
  if (mean(tPls.filter((_, i) => g[i])) < 0) { dirs.pls[0] = flip(dirs.pls[0]); dirs.pls[1] = flip(dirs.pls[1]); }
  if (dirs.pca[0][0] * dirs.pls[0][0] + dirs.pca[0][1] * dirs.pls[0][1] < 0) dirs.pca[0] = flip(dirs.pca[0]);
  const tot = (X) => X.reduce((s, p) => s + p[0] ** 2 + p[1] ** 2, 0);
  const view = {};
  for (const m of ["pca", "pls"]) {
    const t = project(Ac, dirs[m][0]);
    let u = project(Bc, dirs[m][1]);
    if (corr(t, u) < 0) { dirs[m][1] = flip(dirs[m][1]); u = u.map((x) => -x); }
    view[m] = { dirs: dirs[m], t, u, r: corr(t, u), varA: t.reduce((s, x) => s + x * x, 0) / tot(Ac), varB: u.reduce((s, x) => s + x * x, 0) / tot(Bc) };
  }
  const span = 1.08 * Math.max(...Ac.flat().map(Math.abs), ...Bc.flat().map(Math.abs));
  const sspan = 1.08 * Math.max(...["pca", "pls"].flatMap((m) => [...view[m].t, ...view[m].u].map(Math.abs)));
  return { g, A: Ac, B: Bc, view, span, sspan };
}

