/* =========================================================== DATA page */

const pairOf = (key) => PAIRS.find((p) => `${p.a}-${p.b}`.toLowerCase() === key);
/** one pair's PLS reading, and its benchmark: each block's PC1, the largest-variance direction */
const DATA_VIEW = {};
function dataView(pairKey) {
  if (DATA_VIEW[pairKey]) return DATA_VIEW[pairKey];
  const P = pairOf(pairKey);
  const xs = 1.08 * Math.max(...P.t.map(Math.abs)), ys = 1.08 * Math.max(...P.u.map(Math.abs));
  DATA_VIEW[pairKey] = {
    P, t: P.t, u: P.u, keptA: P.keptA, keptB: P.keptB, wA: P.wA, wB: P.wB, topA: P.topA, topB: P.topB, r: corr(P.t, P.u), xs, ys,
    ref: { r: Math.abs(corr(BLOCKS[P.a].pc1, BLOCKS[P.b].pc1)), keptA: BLOCKS[P.a].kept, keptB: BLOCKS[P.b].kept },
  };
  return DATA_VIEW[pairKey];
}

const D = { top: 34, x0: 66, sMax: 260, strip: 22, gapStrip: 8 };
function dataLayout(w) {
  const s = Math.min(D.sMax, Math.floor(w - D.x0 - 240));
  return { s, x: D.x0, y: D.top, side: D.x0 + s + 34 };
}
const H_DATA = D.top + D.sMax + D.gapStrip + D.strip + 40;

function dataMarks(L, V) {
  const sx = (v) => L.x + L.s / 2 + (v / V.xs) * (L.s / 2), sy = (v) => L.y + L.s / 2 - (v / V.ys) * (L.s / 2);
  const stripY = L.y + L.s + D.gapStrip + D.strip / 2, stripX = L.x - D.gapStrip - D.strip / 2;
  return {
    pts: V.t.map((t, k) => [sx(t), sy(V.u[k])]),
    bottom: V.t.map((t) => [sx(t), stripY]),
    left: V.u.map((u) => [stripX, sy(u)]),
  };
}

/** a block's weights as one row of cells, thousands wide, and its largest named */
function drawWeights(ctx, colors, x, y, width, b, wv, top) {
  txt(ctx, colors, S.weights(b), x, y, { size: colors.fsXs, fill: colors.ink1, weight: "600" });
  /* scaled by three standard deviations, not the largest: a few large weights would leave the row grey */
  const m = 3 * Math.sqrt(wv.reduce((s, v) => s + v * v, 0) / wv.length) || 1, cw = width / wv.length;
  for (let j = 0; j < wv.length; j++) { ctx.fillStyle = valueColour(colors, wv[j] / m); ctx.fillRect(x + j * cw, y + 6, Math.max(cw, 0.6), 10); }
  frame(ctx, colors, x, y + 6, width, 10);
  top.name.slice(0, 3).forEach((nm, i) => txt(ctx, colors, `${nm}  ${top.value[i] > 0 ? "+" : ""}${top.value[i].toFixed(3)}`, x, y + 30 + i * 13, { size: colors.fsXs, fill: colors.ink2 }));
}

function drawData(ctx, colors, w, params, anim, pointer) {
  const L = dataLayout(w), V = dataView(params.pair), P = V.P;
  const beat = shownStep(anim, "data"), t = inFlight(anim, "data");
  const found = beat >= 1 || t != null;
  const rise = t != null ? ease(seg(t, 0.15, 1)) : 1;
  const ez = ezOf(anim, "data");
  const to = dataMarks(L, V);
  const from = ez ? dataMarks(L, dataView(ez.params.pair)) : null;
  const e = ez ? ease(ez.t) : 1;
  const at = (key, i) => (from ? lerpPt(from[key][i], to[key][i], e) : to[key][i]);

  txt(ctx, colors, S.dims(P.a), L.x - D.gapStrip - D.strip, 14, { fill: colors.ink2 });
  txt(ctx, colors, S.dims(P.b), L.x - D.gapStrip - D.strip, 28, { fill: colors.ink2 });

  frame(ctx, colors, L.x, L.y + 4, L.s, L.s - 4);
  frame(ctx, colors, L.x, L.y + L.s + D.gapStrip, L.s, D.strip);
  frame(ctx, colors, L.x - D.gapStrip - D.strip, L.y + 4, D.strip, L.s - 4);
  txt(ctx, colors, S.strip(P.a), L.x + L.s / 2, L.y + L.s + D.gapStrip + D.strip + 15, { size: colors.fsXs, fill: colors.ink3, align: "center" });
  vText(ctx, colors, S.strip(P.b), L.x - D.gapStrip - D.strip - 8, L.y + L.s / 2, { size: colors.fsXs, fill: colors.ink3 });

  if (!found) {
    txt(ctx, colors, S.dataBefore, L.x + L.s / 2, L.y + L.s / 2, { fill: colors.ink3, align: "center", baseline: "middle" });
  } else {
    /* the strips appear at once with the press; the samples rise out of the
       bottom strip to their places, each in its own vertical lane */
    for (let i = 0; i < N_DATA; i++) {
      const col = subColour(colors, Y[i]);
      const b = at("bottom", i), l = at("left", i);
      dot(ctx, colors, b[0], b[1] + ((i % 5) - 2) * 3, 1.8, col, false);
      dot(ctx, colors, l[0] + ((i % 5) - 2) * 3, l[1], 1.8, col, false);
    }
    for (let i = 0; i < N_DATA; i++) {
      const q = at("pts", i), b = at("bottom", i);
      const y = lerp(b[1], q[1], rise);
      if (y > L.y + L.s && rise < 1) continue;
      dot(ctx, colors, q[0], y, 3, subColour(colors, Y[i]));
    }
    if (rise >= 1) txt(ctx, colors, `r = ${f2(V.r)}`, L.x + L.s - 6, L.y + 20, { fill: colors.ink1, align: "right", weight: "600" });
  }

  /* beside it: PLS against the benchmark, then each block's row of weights */
  if (found && rise >= 1) {
    const width = w - L.side - 4;
    drawTrade(ctx, colors, L.side, L.y + 30, width, [
      [S.rowR, f2(V.r), f2(V.ref.r)], [S.rowKept(BLOCK_NAME[P.a]), pct(V.keptA), pct(V.ref.keptA)], [S.rowKept(BLOCK_NAME[P.b]), pct(V.keptB), pct(V.ref.keptB)]]);
    drawWeights(ctx, colors, L.side, L.y + 154, width, P.a, V.wA, V.topA);
    drawWeights(ctx, colors, L.side, L.y + 230, width, P.b, V.wB, V.topB);
  }

  if (pointer && found && rise >= 1) {
    let hov = -1, best = 64;
    to.pts.forEach((q, i) => { const d = (q[0] - pointer.x) ** 2 + (q[1] - pointer.y) ** 2; if (d < best) { best = d; hov = i; } });
    if (hov >= 0) {
      ring(ctx, to.pts[hov][0], to.pts[hov][1], 6, colors.ink1);
      hoverLabel(ctx, colors, S.hovData(SUBTYPES[Y[hov]], BLOCK_NAME[P.a], f2(V.t[hov]), BLOCK_NAME[P.b], f2(V.u[hov])), pointer.x, pointer.y, w);
    }
  }
}

/* ==================================================== stages and easing */

const stepsOf = (stage, st) => (stage === "concept" ? st.concept.loop.length - 1 : stage === "factorize" ? 4 : 1);
const durOf = (stage) => (stage === "factorize" ? 450 : stage === "data" ? 1600 : 1400);
const EASE_MS = 900;
const shownStep = (anim, stage) => (anim.n[stage] ?? 0) - (anim.stage === stage && anim.t < 1 ? 1 : 0);
const inFlight = (anim, stage) => (anim.stage === stage && anim.t < 1 ? anim.t : null);
const ezOf = (anim, page) => (anim.ez && anim.ez.page === page && anim.ez.t < 1 ? anim.ez : null);
const complete = (anim, stage, st) => (anim.n[stage] ?? 0) >= stepsOf(stage, st);

/* ------------------------------------------------------------- widget */

defineWidget({
  slug: "shared-components",
  status: "draft",
  title: "Multi-omics: Shared Components",
  subtitle: S.subtitle,
  credit: "Data: TCGA Research Network (PanCanAtlas UCEC), via cBioPortal",
  layout: "side",
  height: (params) => (params.page === "concept" ? H_CONCEPT : params.page === "factorize" ? H_FACTOR : H_DATA),
  pointer: true,

  params: {
    page: { role: "page", type: "segmented", label: S.pageLabel, options: PAGES, default: "concept", display: true },
    pair: { type: "segmented", label: S.pairLabel, detail: S.pairDetail, options: PAIR_OPTS, default: PAIR_OPTS[0].value, display: true, when: ON("data") },
    /* authoring escape hatch, first render only: presses already made on the page the link opens */
    shown: { type: "int", min: 0, max: 1 + 2 * MAX_ROUNDS, default: 0, hidden: true },
  },

  /* a legend reads params only, so the dashed benchmark (which arrives with a press) is named on the canvas instead */
  legend: ({ params }) => (params.page === "concept"
    ? [
      { token: "cluster-a", label: S.sub[0], mark: "dot" },
      { token: "cluster-b", label: S.sub[1], mark: "dot" },
      { token: "highlight", label: S.arrow, mark: "line" },
    ]
    : params.page === "factorize"
      ? [{ token: "value-low", label: S.keyLow, mark: "bar" }, { token: "value-high", label: S.keyHigh, mark: "bar" }]
      : SUBTYPES.map((s, i) => ({ token: `cluster-${"abcd"[i]}`, label: s, mark: "dot" }))),

  compute: ({ rng }) => ({ concept: makeConcept(rng) }),

  animation: {
    stepLabel: S.stepLabel,
    stepTitle: S.stepTitle,
    /* each press is read once: Step alone (play-only-for-motion-or-repetition) */
    runLabel: null,

    init: ({ params, state, fromScratch }) => {
      const stage = params.page;
      const anim = { stage, n: {}, t: 1, dur: durOf(stage), halt: false, ez: null, last: { ...params } };
      anim.n[stage] = fromScratch ? 0 : clamp(Number(params.shown) || 0, 0, stepsOf(stage, state));
      anim.beat = anim.n[stage];
      anim.done = complete(anim, stage, state);
      return anim;
    },

    advance: (anim, { dt, state }) => {
      /* a press a page switch interrupted ends here, before the new page's (mid-press-page-switch) */
      if (anim.halt) { anim.halt = false; return false; }
      const stage = anim.stage;
      if (anim.ez && anim.ez.t < 1) anim.ez.t = Math.min(1, anim.ez.t + dt / EASE_MS);
      /* an ease core started runs the press in flight on with it, and never starts a new one */
      if (anim.mode === "ease") {
        if (anim.t < 1) anim.t = Math.min(1, anim.t + dt / anim.dur);
        anim.done = complete(anim, stage, state) && anim.t >= 1;
        return anim.t < 1 || (anim.ez != null && anim.ez.t < 1);
      }
      if (anim.t < 1) anim.t = Math.min(1, anim.t + dt / anim.dur);
      else if ((anim.n[stage] ?? 0) < stepsOf(stage, state)) {
        anim.n[stage] = (anim.n[stage] ?? 0) + 1;
        anim.dur = durOf(stage);
        anim.t = 0;
      }
      anim.beat = anim.n[stage] ?? 0;
      anim.done = complete(anim, stage, state) && anim.t >= 1;
      if (anim.t >= 1 && anim.ez) anim.ez.t = 1;
      return anim.t < 1;
    },

    rebuild: (anim, { params, state }) => {
      const stage = params.page, was = anim.stage;
      /* only a page change ends a press in flight (mid-press-page-switch) */
      if (stage !== was && anim.t < 1) { anim.t = 1; anim.halt = true; }
      /* a change of Pair on Data, once component 1 is found, eases from the pair it leaves */
      if (stage === was && stage === "data" && complete(anim, "data", state) && params.pair !== anim.last.pair) {
        anim.ez = { page: "data", params: { ...anim.last }, t: 0 };
        anim.easing = true;
      } else if (stage !== was) anim.ez = null;
      anim.last = { ...params };
      anim.stage = stage;
      anim.beat = anim.n[stage] ?? 0;
      anim.done = complete(anim, stage, state) && anim.t >= 1;
    },
  },

  draw({ ctx, colors, w, params, state, anim, pointer }) {
    renderFormula(formulaKey(params, anim));
    if (params.page === "concept") drawConcept(ctx, colors, w, params, state.concept, anim, pointer);
    else if (params.page === "factorize") drawFactorize(ctx, colors, w, params, state.concept, anim, pointer);
    else drawData(ctx, colors, w, params, anim, pointer);
  },

  readout({ params, state, anim }) {
    const stage = params.page;
    if (stage === "concept") {
      const frames = state.concept.loop, F0 = frames[clamp(shownStep(anim, stage), 0, frames.length - 1)];
      return [
        { label: S.tileR, value: F0.r != null ? f2(F0.r) : S.tileWait, note: S.tileRNote },
        { label: S.tileCov, value: F0.cv != null ? f2(F0.cv) : S.tileWait, note: S.tileCovNote },
        { label: S.tileKept(S.blockA), value: F0.keptA != null ? pct(F0.keptA) : S.tileWait, note: S.tileKeptNote },
        { label: S.tileKept(S.blockB), value: F0.keptB != null ? pct(F0.keptB) : S.tileWait, note: S.tileKeptNote },
      ];
    }
    if (stage === "factorize") {
      const n = shownStep(anim, stage), fin = finalOf(state.concept);
      return [
        { label: S.tileR, value: n >= 1 ? f2(fin.r) : S.tileWait, note: S.tileRNote },
        { label: S.tileKept(S.blockA), value: n >= 2 ? pct(fin.keptA) : S.tileWait, note: S.tileKeptNote },
        { label: S.tileKept(S.blockB), value: n >= 2 ? pct(fin.keptB) : S.tileWait, note: S.tileKeptNote },
      ];
    }
    const on = shownStep(anim, stage) >= 1, V = dataView(params.pair);
    return [
      { label: S.tileR, value: on ? f2(V.r) : S.tileWait, note: S.tileRNote },
      { label: S.tileKept(BLOCK_NAME[V.P.a]), value: on ? pct(V.keptA) : S.tileWait, note: S.tileKeptNote },
      { label: S.tileKept(BLOCK_NAME[V.P.b]), value: on ? pct(V.keptB) : S.tileWait, note: S.tileKeptNote },
    ];
  },

  summary({ params, state, anim }) {
    const stage = params.page, n = shownStep(anim, stage);
    if (stage === "concept") {
      const frames = state.concept.loop, F0 = frames[clamp(n, 0, frames.length - 1)];
      return `Two simulated blocks of two features, 80 samples in two subtypes. PLS, ${n} of ${frames.length - 1} presses${F0.r != null ? `; the scores correlate ${f2(F0.r)}` : ""}.`;
    }
    if (stage === "factorize") return `The two simulated blocks as matrices, PLS component 1: ${["nothing yet", "the scores t", "t cᵀ rebuilding each block", "the remainder E", "the remainder E, and X₁ᵀX₂ with its first singular pair"][clamp(n, 0, 4)]}.`;
    const V = dataView(params.pair);
    return `The lesson's ${BLOCK_NAME[V.P.a]} and ${BLOCK_NAME[V.P.b]} blocks, 405 samples coloured by subtype. ${n >= 1 ? `PLS component 1 scores plotted against each other; correlation ${f2(V.r)}, against ${f2(V.ref.r)} for the largest-variance directions.` : "No component found yet."}`;
  },
});
