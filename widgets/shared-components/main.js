/* Two blocks on the same samples. In each, the shared axis carries the
   subtype difference (±0.85 plus noise) and is the SMALLER spread; a private
   axis, unrelated to the other block, is the larger (sd 1.6). The
   largest-variance directions keep ~75% of each block and their scores
   correlate ~0.1; PLS's ~30% and ~0.9. The angles keep the four axes apart. */
const ANG = { a: [62, -28], b: [18, 108] };
const unitAt = (deg) => [Math.cos((deg * Math.PI) / 180), Math.sin((deg * Math.PI) / 180)];
const unit2 = (v) => { const n = Math.hypot(v[0], v[1]); return [v[0] / n, v[1] / n]; };
const rot = (v, deg) => { const c = Math.cos((deg * Math.PI) / 180), s = Math.sin((deg * Math.PI) / 180); return [c * v[0] - s * v[1], s * v[0] + c * v[1]]; };
const angleBetween = (a, b) => Math.acos(clamp(Math.abs(a[0] * b[0] + a[1] * b[1]), 0, 1)) * 180 / Math.PI;
function topEig2(a, b, d) {
  const tr = a + d, det = a * d - b * b, l = tr / 2 + Math.sqrt(Math.max(0, (tr * tr) / 4 - det));
  const v = Math.abs(b) > 1e-12 ? [l - d, b] : a >= d ? [1, 0] : [0, 1];
  return unit2(v);
}
const project = (X, d) => X.map((p) => p[0] * d[0] + p[1] * d[1]);
const flip = (d) => [-d[0], -d[1]];
const centre = (X) => { const m = [0, 1].map((j) => mean(X.map((p) => p[j]))); return X.map((p) => [p[0] - m[0], p[1] - m[1]]); };
const crossOf = (X, Z) => { const M = [[0, 0], [0, 0]]; X.forEach((x, i) => { for (let r = 0; r < 2; r++) for (let c = 0; c < 2; c++) M[r][c] += x[r] * Z[i][c]; }); return M; };
const largestVar = (X) => { const C = crossOf(X, X); return topEig2(C[0][0], C[0][1], C[1][1]); };
/** each feature's covariance with a score vector: Xᵀs / n */
const covWith = (X, s) => [0, 1].map((j) => X.reduce((acc, p, i) => acc + p[j] * s[i], 0) / X.length);
/** the share of X's variance along w: what t wᵀ rebuilds, ‖t‖² / ‖X‖² (round 4, the notebook's single W) */
const keptBy = (X, t) => t.reduce((s, v) => s + v * v, 0) / X.reduce((s, p) => s + p[0] ** 2 + p[1] ** 2, 0);

function makeBlocks(rng) {
  const ua = unitAt(ANG.a[0]), va = unitAt(ANG.a[1]), ub = unitAt(ANG.b[0]), vb = unitAt(ANG.b[1]);
  const g = [], A0 = [], B0 = [];
  for (let i = 0; i < N_CONCEPT; i++) {
    const grp = i % 2;
    const s = (grp ? 0.85 : -0.85) + 0.35 * rng.normal();
    const a = 1.6 * rng.normal(), b = 1.6 * rng.normal();
    g.push(grp);
    A0.push([0, 1].map((j) => s * ua[j] + a * va[j] + 0.2 * rng.normal()));
    B0.push([0, 1].map((j) => s * ub[j] + b * vb[j] + 0.2 * rng.normal()));
  }
  const A = centre(A0), B = centre(B0);

  /* PLS: mixOmics' loop, run to its end from a start 80° off the answer.
     Signs: subtype 2 scores positive on mRNA, and the loop's start chosen so
     its end agrees, so every frame keeps one orientation. */
  const loop = (start) => {
    let w2 = start, u = project(B, w2);
    const frames = [{}, { w2, u }];
    for (let r = 0; r < 40; r++) {
      const c1 = covWith(A, u), w1 = unit2(c1), t = project(A, w1);
      const prev2 = w2;
      const c2 = covWith(B, t); w2 = unit2(c2); u = project(B, w2);
      const prev1 = frames.at(-1).w1;
      if (r < MAX_ROUNDS) {
        frames.push({ w1, t, w2: prev2, u: project(B, prev2), cov: { block: "a", v: c1 } });
        frames.push({ w1, t, w2, u, cov: { block: "b", v: c2 } });
      }
      if (prev1 && angleBetween(prev1, w1) < 0.5 && angleBetween(prev2, w2) < 0.5) break;
    }
    /* trim rounds after the arrows stopped: the press that changes nothing is the reader's to see once */
    let end = frames.length - 1;
    while (end > 4 && angleBetween(frames[end].w1, frames[end - 2].w1) < 0.5 && angleBetween(frames[end].w2, frames[end - 2].w2) < 0.5) end -= 2;
    return frames.slice(0, end + 1);
  };
  let frames = loop([0, 1]);
  let start = unit2(rot(frames.at(-1).w2, 80));
  frames = loop(start);
  if (mean(frames.at(-1).t.filter((_, i) => g[i])) < 0) { start = flip(start); frames = loop(start); }
  const loopEnd = frames.length - 1;
  /* the button names the presses this loop has, then the factorization's */
  for (let n = loopEnd; n < SLOTS; n++) {
    N_LABELS[n] = AFTER[Math.min(n - loopEnd, 2)];
    N_TITLES[n] = AFTER_TITLE[Math.min(n - loopEnd, 2)];
  }
  const fin = frames.at(-1);
  const finish = (f) => {
    if (f.w1) f.keptA = keptBy(A, f.t);
    if (f.w2) f.keptB = keptBy(B, f.u);
    if (f.t && f.u) { f.r = corr(f.t, f.u); f.cv = f.t.reduce((acc, v, i) => acc + v * f.u[i], 0) / f.t.length; }
    return f;
  };
  frames = frames.map(finish);

  /* the benchmark, and Factorization's component 1: each block's direction
     of largest variance, turned to agree with PLS's so the dashed and solid
     lines are read side by side */
  let ra = largestVar(A), rb = largestVar(B);
  if (ra[0] * fin.w1[0] + ra[1] * fin.w1[1] < 0) ra = flip(ra);
  if (corr(project(A, ra), project(B, rb)) < 0) rb = flip(rb);
  const ref = finish({ w1: ra, t: project(A, ra), w2: rb, u: project(B, rb) });

  /* Factorization: mRNA alone, components 1 and 2 (w₂ at right angles, found in E) */
  /* turned to agree with PLS's mRNA loading vector, so N-integration's
     bridge sentence compares (0.42, 0.91) with (0.48, 0.88), not with its
     negative: a direction has no sign, but a student reads the numbers */
  let fw2 = [-ra[1], ra[0]];
  if (fw2[0] * fin.w1[0] + fw2[1] * fin.w1[1] < 0) fw2 = flip(fw2);
  const fac = { w: [ra, fw2], t: [project(A, ra), project(A, fw2)] };
  fac.kept1 = keptBy(A, fac.t[0]);
  /* the share of each score's variance that lies between the subtypes: latent
     variable 1 explains 71.5% of X and 0.00 of this, latent variable 2 0.80
     (measured, round 5's walk-through) */
  const eta = (t) => { const mt = mean(t); let b = 0; for (const k of [0, 1]) { const v = t.filter((_, i) => g[i] === k); b += v.length * (mean(v) - mt) ** 2; } return b / t.reduce((acc, x) => acc + (x - mt) ** 2, 0); };
  fac.eta = [eta(fac.t[0]), eta(fac.t[1])];

  /* Solve directly (round 5: "Shortcut" until his rename): X₁ᵀX₂ / n and its first singular pair, by the same
     alternation on the 2 × 2 table itself; it lands on the loop's end */
  const M = crossOf(A, B).map((r) => r.map((v) => v / N_CONCEPT));
  let s1 = [1, 0], s2 = [0, 1];
  for (let k = 0; k < 200; k++) {
    s1 = unit2([M[0][0] * s2[0] + M[0][1] * s2[1], M[1][0] * s2[0] + M[1][1] * s2[1]]);
    s2 = unit2([M[0][0] * s1[0] + M[1][0] * s1[1], M[0][1] * s1[0] + M[1][1] * s1[1]]);
  }
  if (s1[0] * fin.w1[0] + s1[1] * fin.w1[1] < 0) { s1 = flip(s1); s2 = flip(s2); }

  const span = 1.08 * Math.max(...A.flat().map(Math.abs), ...B.flat().map(Math.abs));
  const sspan = 1.08 * Math.max(...frames.filter((f) => f.t || f.u).flatMap((f) => [...(f.t ?? []), ...(f.u ?? [])]).map(Math.abs));
  const order = [...A.keys()].sort((i, j) => g[i] - g[j] || i - j);
  return { g, A, B, loop: frames, loopEnd, ref, fac, cross: { M, w1: s1, w2: s2 }, span, sspan, order };
}

/* P-integration: two studies, 40 samples each, the same two genes, an even
   subtype mix in each (an uneven one confounds study with subtype, measured
   in round 4's mock, and is not this page's subject). The stacked table is
   centred as one, as 01 cell 2 stacks it; w ∝ Xᵀy with y the subtype,
   centred (−0.5 / +0.5). */
function makeStudies(rng) {
  /* no study shift (his walk-through, round 5: "study 2 reads higher" was set
     up and never used; a study baseline is MINT's subject, named in the last
     caption, not computed) */
  const d = unitAt(-35), X0 = [], study = [], g = [];
  for (let st = 0; st < 2; st++) for (let i = 0; i < N_STUDY; i++) {
    const grp = i % 2, s = grp ? 0.8 : -0.8;
    X0.push([0, 1].map((j) => s * d[j] + 0.55 * rng.normal()));
    study.push(st); g.push(grp);
  }
  const X = centre(X0), y = g.map((v) => v - 0.5);
  const c = covWith(X, y), w = unit2(c), t = project(X, w);
  /* rows: each study's in subtype order, study 1's first */
  const order = [...X.keys()].sort((i, j) => study[i] - study[j] || g[i] - g[j] || i - j);
  const span = 1.1 * Math.max(...X.flat().map(Math.abs));
  return { X, study, g, y, c, w, t, order, span, rSub: corr(t, g) };
}

