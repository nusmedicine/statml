/** pixel positions of every mark in one frame of the Concept page */
function conceptMarks(L, st, F) {
  const [PA, PB, PS] = L.panels;
  const toPx = (P, span, x, y) => [P.x + P.s / 2 + (x / span) * (P.s / 2), P.y + P.s / 2 - (y / span) * (P.s / 2)];
  const R = 0.92 * st.span;
  const arrowOf = (P, d) => (d ? [toPx(P, st.span, -R * d[0], -R * d[1]), toPx(P, st.span, R * d[0], R * d[1])] : null);
  const feetOf = (P, X, d) => (d ? X.map((p) => { const t = p[0] * d[0] + p[1] * d[1]; return toPx(P, st.span, t * d[0], t * d[1]); }) : null);
  return {
    arrowA: arrowOf(PA, F.w1), arrowB: arrowOf(PB, F.w2),
    feetA: feetOf(PA, st.A, F.w1), feetB: feetOf(PB, st.B, F.w2),
    scores: F.t && F.u ? F.t.map((t, k) => toPx(PS, st.sspan, t, F.u[k])) : null,
  };
}
/** an axis turns the short way: it has no sign, so a half-turn is no turn */
function blendAxis(a, b, t) {
  const c = lerpPt(a[0], a[1], 0.5), L = Math.hypot(b[1][0] - b[0][0], b[1][1] - b[0][1]) / 2;
  const a0 = Math.atan2(a[1][1] - a[0][1], a[1][0] - a[0][0]), a1 = Math.atan2(b[1][1] - b[0][1], b[1][0] - b[0][0]);
  let d = a1 - a0;
  while (d > Math.PI / 2) d -= Math.PI;
  while (d < -Math.PI / 2) d += Math.PI;
  const ang = a0 + d * t;
  return [[c[0] - L * Math.cos(ang), c[1] - L * Math.sin(ang)], [c[0] + L * Math.cos(ang), c[1] + L * Math.sin(ang)]];
}

/* One press moves the page from frame k−1 to frame k, in two moves, never
   overlapping (tweens-move-in-lanes): an arrow that exists turns (0–0.45),
   then the feet slide along their perpendiculars and the scores move to
   their new places (0.45–1). An arrow that did not exist appears at once and
   its samples drop onto it; scores that did not exist appear at 0.8. The
   last press, which changes neither arrow, brings in the dashed benchmark
   and the table, at once (tween-only-movement-no-fades). */
function drawConcept(ctx, colors, w, params, st, anim, pointer) {
  const L = conceptLayout(w), [PA, PB, PS] = L.panels;
  const frames = st.loop, last = frames.length - 1;
  const k = Math.min(anim.n.concept ?? 0, last), p = inFlight(anim, "concept");
  const cur = frames[k], prev = p != null && k > 0 ? frames[k - 1] : null;
  const toPx = (P, x, y) => [P.x + P.s / 2 + (x / st.span) * (P.s / 2), P.y + P.s / 2 - (y / st.span) * (P.s / 2)];
  const M = conceptMarks(L, st, cur);
  const turn = p != null ? ease(seg(p, 0, 0.45)) : 1, slide = p != null ? ease(seg(p, 0.45, 1)) : 1;
  const P0 = prev ? conceptMarks(L, st, prev) : null;
  const done = k >= last;

  [[PA, S.blockA, S.axesA], [PB, S.blockB, S.axesB], [PS, S.scores, [S.scoreX, S.scoreY]]].forEach(([P, name, ax]) => {
    txt(ctx, colors, name, P.x, P.y - 10, { fill: colors.ink1, weight: "600" });
    frame(ctx, colors, P.x, P.y, P.s, P.s);
    txt(ctx, colors, ax[0], P.x + P.s / 2, P.y + P.s + 15, { size: colors.fsXs, fill: colors.ink3, align: "center" });
    vText(ctx, colors, ax[1], P.x - 8, P.y + P.s / 2, { size: colors.fsXs, fill: colors.ink3 });
  });

  if (done) {
    const R = conceptMarks(L, st, st.ref);
    refLine(ctx, colors, ...R.arrowA); refLine(ctx, colors, ...R.arrowB);
  }
  const arrowNow = (key) => (M[key] && P0 && P0[key] ? blendAxis(P0[key], M[key], turn) : M[key]);
  ["arrowA", "arrowB"].forEach((key) => { const a = arrowNow(key); if (a) axisArrow(ctx, a[0], a[1], colors.highlight); });

  const scoresNow = M.scores && P0?.scores ? M.scores.map((q, i) => lerpPt(P0.scores[i], q, slide)) : M.scores;
  const scoresOn = !!M.scores && (P0?.scores || p == null || p >= 0.8);

  [[PA, st.A, "feetA"], [PB, st.B, "feetB"]].forEach(([P, X, key]) => {
    X.forEach((pt, i) => {
      const [x, y] = toPx(P, pt[0], pt[1]);
      if (M[key]) {
        let foot = M[key][i];
        if (P0 && P0[key]) foot = lerpPt(P0[key][i], foot, slide);
        else if (p != null) { const drop = ease(seg(p, 0.1, 0.8)); const fx = lerp(x, foot[0], drop), fy = lerp(y, foot[1], drop); if (drop < 1) line(ctx, x, y, fx, fy, colors.ink3, 1); foot = [fx, fy]; }
        dot(ctx, colors, foot[0], foot[1], 2.6, subColour(colors, st.g[i]), false);
      }
      dot(ctx, colors, x, y, 4, subColour(colors, st.g[i]));
    });
  });
  if (scoresOn) {
    scoresNow.forEach((q, i) => dot(ctx, colors, q[0], q[1], 4, subColour(colors, st.g[i])));
    const r = P0?.scores && p != null ? lerp(prev.r, cur.r, slide) : cur.r;
    const cv = P0?.scores && p != null ? lerp(prev.cv, cur.cv, slide) : cur.cv;
    txt(ctx, colors, `r = ${f2(r)}`, PS.x + PS.s - 6, PS.y + 16, { fill: colors.ink1, align: "right", weight: "600" });
    txt(ctx, colors, `cov = ${f2(cv)}`, PS.x + PS.s - 6, PS.y + 32, { fill: colors.ink2, align: "right" });
  }

  /* beside the scores: what this press did and its covariances; once done, PLS against the benchmark */
  const T = L.text;
  const cap = k === 0 ? S.caption.before : done ? S.caption.done : k === 1 ? S.caption.start : k % 2 === 0 ? S.caption.updA : S.caption.updB;
  const nl = wrapText(ctx, colors, cap, T.x, T.y, T.w, 17);
  if (cur.cov && !done) drawCov(ctx, colors, T.x, T.y + nl * 17 + 14, T.w, cur.cov);
  if (done) {
    const Rf = st.ref;
    drawTrade(ctx, colors, T.x, PS.y + PS.s - 70, T.w,
      [[S.rowR, f2(cur.r), f2(Rf.r)], [S.rowKept(S.blockA), pct(cur.keptA), pct(Rf.keptA)], [S.rowKept(S.blockB), pct(cur.keptB), pct(Rf.keptB)]]);
  }

  /* pointer: the nearest sample in any panel, ringed in all three */
  if (pointer) {
    let hov = -1, best = 81;
    const tryPts = (pts) => pts.forEach((q, i) => { const d = (q[0] - pointer.x) ** 2 + (q[1] - pointer.y) ** 2; if (d < best) { best = d; hov = i; } });
    tryPts(st.A.map((q) => toPx(PA, q[0], q[1])));
    tryPts(st.B.map((q) => toPx(PB, q[0], q[1])));
    if (scoresOn && p == null) tryPts(scoresNow);
    if (hov >= 0) {
      [toPx(PA, ...st.A[hov]), toPx(PB, ...st.B[hov])].concat(scoresOn && p == null ? [scoresNow[hov]] : []).forEach((q) => ring(ctx, q[0], q[1], 7, colors.ink1));
      hoverLabel(ctx, colors, S.hovConcept(hov, S.sub[st.g[hov]]), pointer.x, pointer.y, w);
    }
  }
}

