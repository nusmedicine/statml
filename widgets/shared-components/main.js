/** pixel positions of every mark for one reading (method) of the Concept page */
function conceptMarks(L, st, method) {
  const V = st.view[method], [PA, PB, PS] = L.panels;
  const toPx = (P, span, x, y) => [P.x + P.s / 2 + (x / span) * (P.s / 2), P.y + P.s / 2 - (y / span) * (P.s / 2)];
  const foot = (X, d, k) => { const t = X[k][0] * d[0] + X[k][1] * d[1]; return [t * d[0], t * d[1]]; };
  return {
    arrows: [[PA, V.dirs[0]], [PB, V.dirs[1]]].map(([P, d]) => {
      const R = 0.92 * st.span;
      return [toPx(P, st.span, -R * d[0], -R * d[1]), toPx(P, st.span, R * d[0], R * d[1])];
    }),
    feetA: st.A.map((_, k) => toPx(PA, st.span, ...foot(st.A, V.dirs[0], k))),
    feetB: st.B.map((_, k) => toPx(PB, st.span, ...foot(st.B, V.dirs[1], k))),
    scores: V.t.map((t, k) => toPx(PS, st.sspan, t, V.u[k])),
  };
}
const lerpPt = (a, b, t) => [lerp(a[0], b[0], t), lerp(a[1], b[1], t)];
/** a mark set eased from the reading the rail left (`ez`) to the current one */
function blendMarks(from, to, t) {
  if (!from || t >= 1) return to;
  return {
    arrows: to.arrows.map((ar, i) => blendAxis(from.arrows[i], ar, t)),
    feetA: to.feetA.map((p, k) => lerpPt(from.feetA[k], p, t)),
    feetB: to.feetB.map((p, k) => lerpPt(from.feetB[k], p, t)),
    scores: to.scores.map((p, k) => lerpPt(from.scores[k], p, t)),
  };
}
/** an axis turns the short way: it has no sign, so a half-turn is no turn */
function blendAxis(a, b, t) {
  const c = lerpPt(a[0], a[1], 0.5), L = Math.hypot(b[1][0] - b[0][0], b[1][1] - b[0][1]) / 2;
  let a0 = Math.atan2(a[1][1] - a[0][1], a[1][0] - a[0][0]), a1 = Math.atan2(b[1][1] - b[0][1], b[1][0] - b[0][0]);
  let d = a1 - a0;
  while (d > Math.PI / 2) d -= Math.PI;
  while (d < -Math.PI / 2) d += Math.PI;
  const ang = a0 + d * t;
  return [[c[0] - L * Math.cos(ang), c[1] - L * Math.sin(ang)], [c[0] + L * Math.cos(ang), c[1] + L * Math.sin(ang)]];
}

