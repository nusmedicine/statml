/* each map's frame: square, holding every code and the circle */
function frameOf(codes) {
  const lo = [-R95, -R95], hi = [R95, R95];
  for (let i = 0; i < codes.length; i += 2) for (let k = 0; k < 2; k++) { lo[k] = Math.min(lo[k], codes[i + k]); hi[k] = Math.max(hi[k], codes[i + k]); }
  const cx = (lo[0] + hi[0]) / 2, cy = (lo[1] + hi[1]) / 2, half = (Math.max(hi[0] - lo[0], hi[1] - lo[1]) / 2) * 1.05;
  return { x0: cx - half, x1: cx + half, y0: cy - half, y1: cy + half };
}
