const bytes = (s) => Uint8Array.from(atob(s), (c) => c.charCodeAt(0));
/** float16 little-endian, as numpy writes it, to Float32Array */
function halves(s) {
  const b = bytes(s), n = b.length / 2, out = new Float32Array(n);
  for (let i = 0; i < n; i++) {
    const h = b[2 * i] | (b[2 * i + 1] << 8), e = (h >> 10) & 31, m = h & 1023, sg = h & 32768 ? -1 : 1;
    out[i] = e === 0 ? sg * 2 ** -14 * (m / 1024) : e === 31 ? (m ? NaN : sg * Infinity) : sg * 2 ** (e - 15) * (1 + m / 1024);
  }
  return out;
}
