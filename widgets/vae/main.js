  params: {
    page: { role: "page", type: "segmented", label: S.pageLabel, options: PAGES, default: "ae", display: true },
    z: {
      type: "text", label: S.zLabel, detail: S.zDetail, maxLength: 24, default: "", display: true,
      parse: parseZ, show: showZ,
      check: (t) => (String(t).trim() && !parseZ(t) ? S.zCheck : null),
    },
    label: { type: "int", label: S.labelLabel, detail: S.labelDetail, min: 0, max: 9, default: 5, display: true, when: ON("cvae") },
    /* authoring escape hatch, first render only: the Draw press already made on the page the link opens */
    shown: { type: "int", min: 0, max: 1, default: 0, hidden: true },
  },

  legend: () => [
    { token: "empirical", label: S.legend.code, mark: "dot" },
    { token: "prior", label: S.legend.circle, mark: "dash" },
    { token: "highlight", label: S.legend.point, mark: "ring" },
  ],

  compute: () => ({}),

  /* the map, cell by cell: a click sets z to the cell's centre; Conditional's row of ten sets the label */
  regions: ({ w, params }) => {
    const page = params.page, L = layoutOf(w, page), R = L.map, sc = mapScale(page, R), out = [], cs = 6;
    for (let py = R.y; py < R.y + R.h; py += cs) {
      for (let px = R.x; px < R.x + R.w; px += cs) {
        const [a, b] = sc.inv(px + cs / 2, py + cs / 2), v = parseZ(`${a},${b}`);
        out.push({ x: px, y: py, w: cs, h: cs, set: { z: v }, label: `z = ${showZ(v)}` });
      }
    }
    if (page === "cvae") {
      const T = L.strip;
      for (let d = 0; d < 10; d++) out.push({ x: PAD + d * (T.cell + T.gap), y: T.y, w: T.cell, h: T.cell + 18, set: { label: d }, label: `c = ${d}` });
    }
    return out;
  },

  animation: {
    stepLabel: "Draw",
    stepTitle: { param: "page", labels: TITLES, default: TITLES.ae },
    /* one press, read once: Step alone, no Play (play-only-for-motion-or-repetition) */
    runLabel: null,

    init: ({ params, fromScratch }) => {
      const page = params.page;
      const anim = { stage: page, n: {}, t: 1, playPage: null, halt: false };
      anim.n[page] = fromScratch ? 0 : clamp(Number(params.shown) || 0, 0, 1);
      anim.beat = anim.n[page];
      anim.done = anim.n[page] >= 1;
      return anim;
    },
    /* Draw: the sixteen decodes appear one at a time, each at once (no fade) */
    advance: (anim, { dt, params }) => {
      if (anim.halt) { anim.halt = false; return false; }
      const page = params.page;
      if (anim.t < 1) anim.t = Math.min(1, anim.t + dt / DRAW_MS);
      else if (pressesOf(anim, page) < 1) { anim.n[page] = 1; anim.t = 0; anim.playPage = page; }
      anim.beat = pressesOf(anim, page);
      anim.done = anim.beat >= 1 && anim.t >= 1;
      return anim.t < 1;
    },
    rebuild: (anim, { params }) => {
      /* only a page change ends a Draw in flight (mid-press-page-switch); z and the label keep it going */
      const page = params.page;
      if (page !== anim.stage && anim.t < 1) { anim.t = 1; anim.halt = true; }
      anim.stage = page;
      anim.beat = pressesOf(anim, page);
      anim.done = anim.beat >= 1 && anim.t >= 1;
    },
  },

