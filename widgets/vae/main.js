/** ConvTranspose2d(kernel 4, stride 2, padding 1): Ci × H × H → Co × 2H × 2H */
function convT(inp, Ci, H, w, b, Co) {
  const Ho = 2 * H, out = new Float32Array(Co * Ho * Ho);
  for (let i = 0; i < Ci; i++) for (let y = 0; y < H; y++) for (let x = 0; x < H; x++) {
    const v = inp[(i * H + y) * H + x];
    if (v === 0) continue;
    for (let o = 0; o < Co; o++) {
      const wb = (i * Co + o) * 16;
      for (let ky = 0; ky < 4; ky++) {
        const yy = 2 * y - 1 + ky;
        if (yy < 0 || yy >= Ho) continue;
        for (let kx = 0; kx < 4; kx++) {
          const xx = 2 * x - 1 + kx;
          if (xx >= 0 && xx < Ho) out[(o * Ho + yy) * Ho + xx] += v * w[wb + ky * 4 + kx];
        }
      }
    }
  }
  for (let o = 0; o < Co; o++) for (let k = 0; k < Ho * Ho; k++) out[o * Ho * Ho + k] += b[o];
  return out;
}
/** 10-3b's decoder: Linear → Unflatten (64, 7, 7) → ConvT → ReLU → ConvT → Sigmoid; the CVAE's Linear reads [z ‖ c] and is followed by a ReLU */
function decodeRaw(page, z, label) {
  const D = DEC[page], h = new Float32Array(3136), b0 = page === "cvae" ? label * 3136 : 0;
  for (let j = 0; j < 3136; j++) {
    const s = D.b[b0 + j] + D.wz[2 * j] * z[0] + D.wz[2 * j + 1] * z[1];
    h[j] = D.relu ? Math.max(0, s) : s;
  }
  const a = convT(h, 64, 7, D.d1w, D.d1b, 32);
  for (let k = 0; k < a.length; k++) a[k] = Math.max(0, a[k]);
  const o = convT(a, 32, 14, D.d2w, D.d2b, 1), px = new Uint8Array(784);
  for (let k = 0; k < 784; k++) px[k] = Math.round(255 / (1 + Math.exp(-o[k])));
  return px;
}
const decCache = new Map();
function decode(page, z, label = 0) {
  const key = `${page}|${z[0]}|${z[1]}|${page === "cvae" ? label : ""}`;
  if (!decCache.has(key)) {
    if (decCache.size > 400) decCache.clear();
    decCache.set(key, decodeRaw(page, z, label));
  }
  return decCache.get(key);
}
