/* ONE STACK, AS HIS FIGURES DRAW IT: the output at the top, the block's boxes in a
   dashed frame marked × 2, the embedding, the input at the bottom; every box filled
   in the stack's hue, the one joined to a matrix outlined in ink. Returns each box's
   rectangle by key, and the stack's bottom. */
const SK = { bh: 26, bh2: 34, gap: 14 };
/** a stack's height with `n1` one-line and `n2` two-line boxes in its frame */
const stackHeight = (n1, n2) => 8 + 20 + n1 * SK.bh + n2 * SK.bh2 + (n1 + n2 - 1) * SK.gap + 14 + 20 + SK.bh + 26 + 4;
function stack(ctx, colors, x, top, w, hue, { title, blocks, hot, input, output }) {
  const r = {}, fill = rgb(hue), ink = inkOn(colors, fill);
  const draw = (key, lines, y, h) => {
    ctx.fillStyle = hue; ctx.fillRect(x, y, w, h);
    if (hot.includes(key)) rect(ctx, x - 1.5, y - 1.5, w + 3, h + 3, colors.ink1, 2);
    [].concat(lines).forEach((l, i, all) => txt(ctx, l, x + w / 2, y + h / 2 + (i - (all.length - 1) / 2) * 12, { font: small(colors), fill: ink, align: "center" }));
    r[key] = { x, y, w, h };
  };
  let y = top;
  txt(ctx, output, x + w / 2, y, { font: small(colors), fill: colors.ink2, align: "center" }); y += 8;
  arrow(ctx, x + w / 2, y + 14, x + w / 2, y + 3, colors.ink3); y += 20;
  const fTop = y - 4;
  blocks.forEach(([key, lines], i) => {
    const h = [].concat(lines).length > 1 ? SK.bh2 : SK.bh;
    draw(key, lines, y, h);
    if (i > 0) { const up = r[blocks[i - 1][0]]; arrow(ctx, x + w / 2, y - 1, x + w / 2, up.y + up.h + 2, colors.ink3); }
    y += h + (i < blocks.length - 1 ? SK.gap : 0);
  });
  rect(ctx, x - 7, fTop, w + 14, y - fTop + 4, colors.reference, 1.3, [4, 3]);
  txt(ctx, S.times, x + w + 7, fTop - 8, { font: small(colors), fill: colors.reference, align: "right" });
  y += 14; arrow(ctx, x + w / 2, y + 14, x + w / 2, y + 2, colors.ink3); y += 20;
  draw("embedding", S.embedding, y, SK.bh); y += SK.bh;
  arrow(ctx, x + w / 2, y + 16, x + w / 2, y + 2, colors.ink3); y += 26;
  txt(ctx, input, x + w / 2, y, { font: small(colors), fill: colors.ink2, align: "center" });
  rotated(ctx, title, x - 16, (fTop + r.embedding.y) / 2, { font: cap(colors), fill: colors.ink1, align: "center" });
  r.bottom = y + 4;
  return r;
}

/* ------------------------------------------------------------ a matrix */

/** weights as a grid: rows over columns, labels in their sources' hues; `rows` limits the
    filled rows (the rest blank), `causal` leaves the keys after each query blank */
function matrix(ctx, colors, A, rt, ct, x0, y0, cs, { rowHue, colHue, causal = false, rows = A.length, colLabels = true, rowLabels = true, digits = true } = {}) {
  const font = mono(colors);
  if (colLabels) ct.forEach((t, j) => rotated(ctx, t, x0 + j * cs + cs / 2, y0 - 5, { font, fill: colHue, align: "left" }));
  const gap = cs > 5 ? 1 : 0;
  for (let i = 0; i < A.length; i++) {
    if (rowLabels) txt(ctx, rt[i], x0 - 5, y0 + i * cs + cs / 2, { font, fill: i < rows ? rowHue : colors.ink3, align: "right" });
    for (let j = 0; j < A[i].length; j++) {
      const x = x0 + j * cs, y = y0 + i * cs, blank = (causal && j > i) || i >= rows;
      const p = blank ? null : weightRgb(colors, A[i][j]);
      ctx.fillStyle = p ? css(p) : colors.surface2; ctx.fillRect(x, y, cs - gap, cs - gap);
      if (p && digits && cs >= 22) txt(ctx, A[i][j].toFixed(2).replace(/^0/, ""), x + cs / 2 - 0.5, y + cs / 2, { font, fill: inkOn(colors, p), align: "center" });
    }
  }
  rect(ctx, x0 - 0.5, y0 - 0.5, A[0].length * cs, A.length * cs, colors.ink2);
  return { x0, y0, w: A[0].length * cs, h: A.length * cs };
}

/* the newest filled row outlined, gliding down from the last one */
function rowOutline(ctx, colors, m, ch, n, t) {
  if (n < 1) return;
  const y = n >= 2 ? lerp(n - 2, n - 1, ease(t)) : n - 1;
  rect(ctx, m.x0 - 2.5, m.y0 + y * ch - 2, m.w + 4, ch + 3, colors.ink1, 1.5, [3, 3]);
}

