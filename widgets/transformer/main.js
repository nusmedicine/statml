function txt(ctx, s, x, y, { font, fill, align = "left", baseline = "alphabetic" }) {
  ctx.save(); ctx.font = font; ctx.fillStyle = fill; ctx.textAlign = align; ctx.textBaseline = baseline; ctx.fillText(s, x, y); ctx.restore();
}
function line(ctx, x1, y1, x2, y2, stroke, lw = 1, dash = null) {
  ctx.save(); ctx.strokeStyle = stroke; ctx.lineWidth = lw; if (dash) ctx.setLineDash(dash); ctx.beginPath(); ctx.moveTo(x1, y1); ctx.lineTo(x2, y2); ctx.stroke(); ctx.restore();
}
function arrow(ctx, x1, y1, x2, y2, stroke) {
  line(ctx, x1, y1, x2, y2, stroke, 1.2);
  const a = Math.atan2(y2 - y1, x2 - x1);
  ctx.save(); ctx.fillStyle = stroke; ctx.beginPath(); ctx.moveTo(x2, y2);
  ctx.lineTo(x2 - 7 * Math.cos(a - 0.4), y2 - 7 * Math.sin(a - 0.4)); ctx.lineTo(x2 - 7 * Math.cos(a + 0.4), y2 - 7 * Math.sin(a + 0.4)); ctx.fill(); ctx.restore();
}
function rect(ctx, x, y, w, h, stroke, lw = 1, dash = null) {
  ctx.save(); ctx.strokeStyle = stroke; ctx.lineWidth = lw; if (dash) ctx.setLineDash(dash); ctx.strokeRect(x, y, w, h); ctx.restore();
}
/** a box with one or two centred lines */
function box(ctx, colors, x, y, w, h, lines) {
  ctx.fillStyle = colors.surface2; ctx.fillRect(x, y, w, h);
  rect(ctx, x + 0.5, y + 0.5, w - 1, h - 1, colors.ink2);
  [].concat(lines).forEach((l, i, all) => txt(ctx, l, x + w / 2, y + h / 2 + (i - (all.length - 1) / 2) * 12, { font: small(colors), fill: colors.ink1, align: "center", baseline: "middle" }));
}
