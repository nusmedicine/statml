const maxOf = (page, state) => (page === "encoder" ? M.STAGES : page === "decoder" ? state.gen.steps.length : page === "pretraining" ? M.CLAUSE.length : 0);
const msOf = (page, mode) => (page === "encoder" ? ENC_MS : page === "decoder" ? DEC_MS : PRE_MS)[mode === "run" ? "run" : "step"];
function settle(anim, params, state) {
  anim.page = params.page;
  anim.inert = params.page === "tasks";
  const pg = anim.p[params.page];
  anim.done = pg ? pg.n >= maxOf(params.page, state) && pg.t >= 1 : false;
}

/* memoised: compute() is pure, and these depend on the parameter named or on nothing */
const MEMO = { pair: null, clause: null, gen: {}, dna: {} };
function stage(params) {
  MEMO.pair ??= M.encoderPair();
  MEMO.clause ??= M.clauseSteps();
  MEMO.gen[params.prompt] ??= M.generate(M.PROMPTS[Number(params.prompt) - 1]);
  MEMO.dna[params.gene] ??= M.translate(M.GENES[Number(params.gene) - 1]);
  return { pair: MEMO.pair, clause: MEMO.clause, table: M.treatTable(), gen: MEMO.gen[params.prompt], dna: MEMO.dna[params.gene] };
}

const heightOf = ({ page, prompt, w }) => {
  if (page === "decoder") { MEMO.gen[prompt] ??= M.generate(M.PROMPTS[Number(prompt) - 1]); return heightDecoder(w, MEMO.gen[prompt]); }
  return page === "tasks" ? heightTasks() : page === "pretraining" ? heightPretraining() : heightEncoder(w);
};

