/* GENERATION, THE DECODER PAGE'S STEP (his pick: below the figure, the lesson's
   prompt only). A press reads the tokens so far, prints the next token's five
   largest probabilities, and the largest glides up to the end of the line: up
   its own column, along a lane under the line, then into place — clear of the
   words already there (Kenneth, 2026-09-19: nothing moves over marks in place). */
const GLIDE_AT = 0.35;
const DEC_MS = { step: 900, run: 520 }, ENCDEC_MS = { step: 520, run: 300 };
function drawGeneration(ctx, colors, w, state, pg) {
  const y0 = heightSelf(w) + GEN.gap, gen = state.gen, n = pg.n, st = n > 0 ? gen.steps[n - 1] : null, landed = pg.t >= 1;
  const u = landed ? 1 : Math.max(0, (pg.t - GLIDE_AT) / (1 - GLIDE_AT)), promptLen = 1 + M.PROMPT.split(" ").length;
  txt(ctx, S.gen, PAD_L, y0, { font: cap(colors), fill: colors.ink1 });
  const toks = st ? (landed ? [...st.context, st.next] : st.context) : gen.steps[0].context;
  const cy = y0 + GEN.ctx;
  let x = PAD_L;
  toks.slice(1).forEach((t, i) => {
    txt(ctx, t, x, cy, { font: mono(colors), fill: i + 1 >= promptLen ? colors.groupB : colors.ink1 });
    x += textW(ctx, mono(colors), t) + 8;
  });
  if (!st || landed) txt(ctx, S.genArrow, x, cy, { font: small(colors), fill: colors.ink3 });
  const lx = PAD_L + 110, bmax = w - PAD_R - lx - 90, by = (r) => y0 + GEN.bars + r * GEN.pitch;
  if (!st) { txt(ctx, S.genWait, PAD_L, by(0) + GEN.barH / 2, { font: small(colors), fill: colors.ink3 }); return; }
  txt(ctx, S.genNext(st.context.at(-1)), lx, y0 + GEN.cap, { font: small(colors), fill: colors.ink3 });
  const order = st.probs.map((p, i) => [p, i]).sort((a, b) => b[0] - a[0]).slice(0, 5);
  order.forEach(([p, i], r) => {
    const y = by(r), word = M.VOCAB[i];
    if (!(r === 0 && u > 0 && !landed)) txt(ctx, word, lx - 6, y + GEN.barH / 2, { font: mono(colors), fill: r ? colors.ink2 : colors.ink1, align: "right" });
    ctx.fillStyle = r ? colors.surface3 : colors.groupB; ctx.fillRect(lx, y, Math.max(1, p * bmax), GEN.barH);
    txt(ctx, p.toFixed(3), lx + Math.max(1, p * bmax) + 5, y + GEN.barH / 2, { font: mono(colors), fill: colors.ink2 });
  });
  if (u > 0 && !landed) {
    const fx = lx - 6 - textW(ctx, mono(colors), st.next), fy = by(0) + GEN.barH / 2, lane = y0 + GEN.lane;
    const legs = [fy - lane, Math.abs(x - fx), lane - cy], total = legs[0] + legs[1] + legs[2];
    let d = ease(u) * total, gx = fx, gy = fy;
    if (d <= legs[0]) gy = fy - d;
    else if ((d -= legs[0]) <= legs[1]) { gy = lane; gx = lerp(fx, x, d / legs[1]); }
    else { d -= legs[1]; gx = x; gy = lane - d; }
    txt(ctx, st.next, gx, gy, { font: mono(colors), fill: colors.groupB });
  }
  /* his figure's loop: from the chosen bar round to the input */
  const rx = w - PAD_R - 4, ry = by(0) + GEN.barH / 2, ay = cy - 14, ax = x + textW(ctx, small(colors), S.genArrow) / 2;
  poly(ctx, [[lx + Math.max(1, order[0][0] * bmax) + 44, ry], [rx, ry], [rx, ay], [ax, ay]], colors.grid, 1.2);
  arrow(ctx, ax, ay, ax, cy - 8, colors.grid);
}

